!! column physics: bulk surface heat flux and its Tsf-derivatives, saturation
!! humidity, and `adjust_enthalpy`.
!!
!! The tables are 17-significant-digit literals produced by the Icepack oracle
!! (the upstream routines called directly; qsat is the formula inside them).
!! The surface-flux and relayering tables are identical for the Icepack and
