   subroutine check_surface(error, c)
      type(error_type), allocatable, intent(out) :: error
      type(ice_constants_t), intent(in) :: c
      integer, parameter :: N = size(SF_TSF)
      real(wp) :: flwout(N), fsens(N), flat(N), fsurf(N), dflw(N), dsens(N), dlat(N), dfs(N), qs(N), dqs(N)
      integer(int32) :: ierr
      integer :: i

      ierr = 0_int32
      do i = 1, N
         call surface_heat_flux(SF_TSF(i), SF_FSW(i), SF_RHOA(i), SF_FLW(i), SF_POTT(i), SF_QA(i), &
                                SF_SH(i), SF_LH(i), SF_EMIS(i), c, ICE_SFC_BULK, 0.0_wp, 0.0_wp, &
                                flwout(i), fsens(i), flat(i), fsurf(i), ierr)
         call dsurface_heat_flux_dTsf(SF_TSF(i), SF_RHOA(i), SF_SH(i), SF_LH(i), SF_EMIS(i), c, &
                                      ICE_SFC_BULK, 0.0_wp, dfs(i), dflw(i), dsens(i), dlat(i), ierr)
         qs(i) = ice_qsat_surface(SF_TSF(i) + c%Tffresh, SF_RHOA(i))
         dqs(i) = ice_dqsat_dTsf(SF_TSF(i) + c%Tffresh, SF_RHOA(i))
      end do
      if (ierr /= 0_int32) then
         call fail(error, "unexpected error bits")
         return
      end if
      call ice_golden_check(error, "flwout", flwout, SF_FLWOUT, 1.0e-12_wp, 1.0e-10_wp)
      if (allocated(error)) return
      call ice_golden_check(error, "fsens", fsens, SF_FSENS, 1.0e-12_wp, 1.0e-10_wp)
      if (allocated(error)) return
      call ice_golden_check(error, "flat", flat, SF_FLAT, 1.0e-12_wp, 1.0e-10_wp)
      if (allocated(error)) return
      call ice_golden_check(error, "fsurf", fsurf, SF_FSURF, 1.0e-12_wp, 1.0e-10_wp)
      if (allocated(error)) return
      call ice_golden_check(error, "dflwout", dflw, SF_DFLW, 1.0e-12_wp, 1.0e-12_wp)
      if (allocated(error)) return
      call ice_golden_check(error, "dfsens", dsens, SF_DSENS, 1.0e-12_wp, 1.0e-12_wp)
      if (allocated(error)) return
      call ice_golden_check(error, "dflat", dlat, SF_DLAT, 1.0e-12_wp, 1.0e-12_wp)
      if (allocated(error)) return
      call ice_golden_check(error, "dfsurf", dfs, SF_DFSURF, 1.0e-12_wp, 1.0e-12_wp)
      if (allocated(error)) return
      call ice_golden_check(error, "Qsfc", qs, SF_QSFC, 1.0e-12_wp, 0.0_wp)
      if (allocated(error)) return
      call ice_golden_check(error, "dQsfc_dTsf", dqs, SF_DQSFC, 1.0e-12_wp, 0.0_wp)
   end subroutine check_surface

   subroutine check_adjust(error, c)
      type(error_type), allocatable, intent(out) :: error
      type(ice_constants_t), intent(in) :: c
      integer, parameter :: N = size(AE_HN)
      real(wp) :: z1(5), z2(5), qn(4), hlyr, got(4*N), ref(4*N)
      integer(int32) :: ierr
      integer :: i, k

      ierr = 0_int32
      do i = 1, N
         z1 = [AE_Z1(i), AE_Z2(i), AE_Z3(i), AE_Z4(i), AE_Z5(i)]
         hlyr = AE_HN(i)/4.0_wp
         do k = 1, 5
            z2(k) = hlyr*real(k - 1, wp)
         end do
         qn = [AE_Q1(i), AE_Q2(i), AE_Q3(i), AE_Q4(i)]
         call adjust_enthalpy(4, z1, z2, hlyr, AE_HN(i), qn, c, ierr)
         got(4*(i - 1) + 1:4*i) = qn
         ref(4*(i - 1) + 1:4*i) = [AE_O1(i), AE_O2(i), AE_O3(i), AE_O4(i)]
      end do
      if (ierr /= 0_int32) then
         call fail(error, "unexpected error bits")
         return
      end if
      call ice_golden_check(error, "adjust_enthalpy", got, ref, 1.0e-13_wp, 1.0e-6_wp)
   end subroutine check_adjust

