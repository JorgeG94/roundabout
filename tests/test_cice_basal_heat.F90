   subroutine golden(error, set, gchk, gfbot, grs, gwl)
      !! Rows are compared per class (see the module header): bitwise (GPU: 1e-12) for everything that
      !! does not pass through the power, the measured tolerance for `rside`, `wlat` and limiter-scaled `fbot`.
      type(error_type), allocatable, intent(out) :: error
      integer, intent(in) :: set
      real(wp), intent(in) :: gchk(NROW), gfbot(NROW), grs(NROW), gwl(NROW)
      type(ice_params_t) :: p
      real(wp) :: a(NC), v(NC), vs(NC), qi(NIL, NC), qs(1, NC), et(NC)
      real(wp) :: dt, frz, sst, Tf, tx, ty, um, chk, Tb, fb, rs, wl, xt
      real(wp) :: w_rs, w_wl, w_fl, w_fx
      integer(int32) :: ie
      integer :: row, nbind, nzero, nexact
      character(len=160) :: msg

      p = ice_params_default(set, NC, NIL, NSL)
      nzero = 0
      nbind = 0
      nexact = 0
      w_rs = 0.0_wp; w_wl = 0.0_wp; w_fl = 0.0_wp; w_fx = 0.0_wp
      do row = 1, NROW
         call gen_state(row, NC, NIL, dt, frz, sst, Tf, tx, ty, um, a, v, vs, qi, qs)
         chk = sum(a) + sum(v) + sum(vs) + sum(qi) + sum(qs) + dt + frz + sst + Tf + tx + ty + um
         if (.not. (abs(chk - gchk(row)) <= 1.0e-12_wp*abs(gchk(row)))) then
            write (msg, '(a,i0)') "input recipe drifted from the oracle driver at row ", row
            call test_failed(error, trim(msg))
            return
         end if
         et = melt_energy(NC, NIL, v, vs, qi, qs)
         ie = 0_int32
         call ice_frzmlt_bottom_lateral(NC, dt, sum(a), frz, sst, Tf, tx, ty, um, p%thermo%floediam, &
                                        p%thermo%floeshape, p%c%rhow, p%c%cp_ocn, p%c%pi, p%c%puny, &
                                        et, Tb, fb, rs, wl, xt, ie)
         if (ie /= 0_int32) then
            call test_failed(error, "error bit raised on a golden row")
            return
         end if
         if (Tb /= Tf) then
            call test_failed(error, "Tbot differs from Tf")
            return
         end if
         if (rs == 0.0_wp) nzero = nzero + 1
         if (rs > 0.0_wp .and. rs < 1.0_wp .and. fb /= 0.0_wp) nbind = nbind + 1
         if (.not. (ieee_is_finite(fb) .and. ieee_is_finite(rs) .and. ieee_is_finite(wl))) then
            call test_failed(error, "non-finite golden output")
            return
         end if
         if (xt == 1.0_wp .or. rs == 0.0_wp) then
            ! no power in the path: fbot is exactly upstream's
            nexact = nexact + 1
            w_fx = max(w_fx, reldiff(fb, gfbot(row)))
         else
            w_fl = max(w_fl, reldiff(fb, gfbot(row)))
         end if
         w_rs = max(w_rs, reldiff(rs, grs(row)))
         w_wl = max(w_wl, reldiff(wl, gwl(row)))
      end do
      write (output_unit, '(a,i0,4(a,es10.3))') "basal_heat golden set ", set, ": worst rel diff rside ", w_rs, &
         " wlat ", w_wl, " fbot(limited) ", w_fl, " fbot(exact class) ", w_fx
      call check(error, nzero > 15 .and. nbind > 15 .and. nexact > 15, "golden rows cover closed gates and melting cells")
      if (allocated(error)) return
      call check(error, w_fx <= TOL_EXACT, "fbot (limiter inactive or rside = 0) equals upstream")
      if (allocated(error)) return
      call check(error, w_rs <= TOL_POW, "rside within the measured power difference")
      if (allocated(error)) return
      call check(error, w_wl <= TOL_POW, "wlat within the measured power difference")
      if (allocated(error)) return
      call check(error, w_fl <= TOL_POW, "limiter-scaled fbot within the measured power difference")
   end subroutine golden

   pure function reldiff(x, y) result(d)
      real(wp), intent(in) :: x, y
      real(wp) :: d
      if (x == y) then
         d = 0.0_wp
      else
         d = abs(x - y)/max(abs(y), tiny(1.0_wp))
      end if
   end function reldiff

