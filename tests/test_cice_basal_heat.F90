   subroutine gen_state(key, ncat, nilyr, dt, frzmlt, sst, Tf, tx, ty, umin, aicen, vicen, vsnon, qicen, qsnon)
      !! Draw order is the oracle driver's (part of the contract): with `ncat = 5`,
      !! `nilyr = 7` and `key = row` it reproduces the golden inputs exactly.
      integer, intent(in) :: key, ncat, nilyr
      real(wp), intent(out) :: dt, frzmlt, sst, Tf, tx, ty, umin
      real(wp), intent(out) :: aicen(ncat), vicen(ncat), vsnon(ncat), qicen(nilyr, ncat), qsnon(1, ncat)
      integer(int64) :: st
      integer :: n, k
      real(wp) :: u1, u2, u3, u4, u5, sss, dTemp, mag

      st = lcg_next(int(key, int64)*104729_int64 + 11_int64)
      st = lcg_next(st); dt = 600.0_wp + 2400.0_wp*lcg_unit(st)
      st = lcg_next(st); sss = 30.0_wp + 5.0_wp*lcg_unit(st)
      Tf = -0.054_wp*sss
      st = lcg_next(st); dTemp = 6.0_wp*lcg_unit(st)
      if (mod(key, 11) == 3) dTemp = 0.0_wp
      if (mod(key, 11) == 7) dTemp = -0.5_wp*dTemp/6.0_wp
      sst = Tf + dTemp
      st = lcg_next(st); u1 = lcg_unit(st)
      frzmlt = -(5.0_wp + 3000.0_wp*u1*u1)
      if (mod(key, 8) == 5) frzmlt = 25.0_wp*u1
      if (mod(key, 13) == 4) frzmlt = -1.0e6_wp
      st = lcg_next(st); mag = 0.3_wp*lcg_unit(st)**2
      st = lcg_next(st); u1 = lcg_unit(st)
      st = lcg_next(st); u2 = lcg_unit(st)
      tx = mag*(2.0_wp*u1 - 1.0_wp)
      ty = mag*(2.0_wp*u2 - 1.0_wp)
      if (mod(key, 9) == 2) then
         tx = 0.0_wp
         ty = 0.0_wp
      end if
      umin = 5.0e-4_wp
      if (mod(key, 2) == 1) umin = 5.0e-3_wp
      do n = 1, ncat
         st = lcg_next(st); u1 = lcg_unit(st)
         st = lcg_next(st); u2 = lcg_unit(st)
         st = lcg_next(st); u3 = lcg_unit(st)
         st = lcg_next(st); u4 = lcg_unit(st)
         st = lcg_next(st); u5 = lcg_unit(st)
         aicen(n) = 0.02_wp + 0.2_wp*u2
         vicen(n) = aicen(n)*(0.1_wp + 3.0_wp*u3)
         vsnon(n) = 0.0_wp
         if (u4 >= 0.3_wp) vsnon(n) = aicen(n)*0.4_wp*u5
         do k = 1, nilyr
            st = lcg_next(st); qicen(k, n) = -4.0e8_wp + 3.0e8_wp*lcg_unit(st)
         end do
         st = lcg_next(st); qsnon(1, n) = -1.2e8_wp + 0.3e8_wp*lcg_unit(st)
         if (u1 < 0.25_wp .or. mod(key, 10) == 6) then
            aicen(n) = 0.0_wp; vicen(n) = 0.0_wp; vsnon(n) = 0.0_wp
         end if
      end do
   end subroutine gen_state

   subroutine run_cell(p, ncat, nilyr, dt, frzmlt, sst, Tf, tx, ty, umin, aicen, vicen, vsnon, qicen, qsnon, &
                       fbot, rside, wlat, ie)
      !! One cell through the cell entry (1 x 1 arrays).
      type(ice_params_t), intent(in) :: p
      integer, intent(in) :: ncat, nilyr
      real(wp), intent(in) :: dt, frzmlt, sst, Tf, tx, ty, umin
      real(wp), intent(in) :: aicen(ncat), vicen(ncat), vsnon(ncat), qicen(nilyr, ncat), qsnon(1, ncat)
      real(wp), intent(out) :: fbot, rside, wlat
      integer(int32), intent(inout) :: ie
      real(wp) :: a(1, 1, ncat), v(1, 1, ncat), vs(1, 1, ncat), qi(1, 1, ncat, nilyr), qs(1, 1, ncat, 1)
      real(wp) :: fz(1, 1), ss(1, 1), tt(1, 1), ux(1, 1), uy(1, 1), fb(1, 1), rs(1, 1), wl(1, 1)
      integer(int32) :: iee(1, 1)
      integer :: n, k

      do n = 1, ncat
         a(1, 1, n) = aicen(n); v(1, 1, n) = vicen(n); vs(1, 1, n) = vsnon(n)
         qs(1, 1, n, 1) = qsnon(1, n)
         do k = 1, nilyr
            qi(1, 1, n, k) = qicen(k, n)
         end do
      end do
      fz = frzmlt; ss = sst; tt = Tf; ux = tx; uy = ty
      fb = -999.0_wp; rs = -999.0_wp; wl = -999.0_wp
      iee = ie
      call ice_frzmlt_bottom_lateral_cell(1, 1, 1, 1, ncat, nilyr, 1, dt, umin, p%thermo%floediam, &
                                          p%thermo%floeshape, p%c%rhow, p%c%cp_ocn, p%c%pi, p%c%puny, &
                                          a, v, vs, qi, qs, fz, ss, tt, ux, uy, fb, rs, wl, iee)
      fbot = fb(1, 1); rside = rs(1, 1); wlat = wl(1, 1); ie = iee(1, 1)
   end subroutine run_cell

   pure function melt_energy(ncat, nilyr, vicen, vsnon, qicen, qsnon) result(etotn)
      !! Per-category melt energy [J/m2], snow then ice, layer order (test copy of the formula).
      integer, intent(in) :: ncat, nilyr
      real(wp), intent(in) :: vicen(ncat), vsnon(ncat), qicen(nilyr, ncat), qsnon(1, ncat)
      real(wp) :: etotn(ncat)
      integer :: n, k
      do n = 1, ncat
         etotn(n) = 0.0_wp
         etotn(n) = etotn(n) + qsnon(1, n)*vsnon(n)/1.0_wp
         do k = 1, nilyr
            etotn(n) = etotn(n) + qicen(k, n)*vicen(n)/real(nilyr, wp)
         end do
      end do
   end function melt_energy

   subroutine simple_state(aicen, vicen, vsnon, qicen, qsnon, ice)
      !! Five categories, 7 layers, uniform deterministic state; `ice = .false.` zeroes the volumes.
      real(wp), intent(out) :: aicen(NC), vicen(NC), vsnon(NC), qicen(NIL, NC), qsnon(1, NC)
      logical, intent(in) :: ice
      integer :: n, k
      do n = 1, NC
         aicen(n) = 0.15_wp + 0.01_wp*real(n, wp)
         vicen(n) = merge(aicen(n)*(0.3_wp + 0.5_wp*real(n, wp)), 0.0_wp, ice)
         vsnon(n) = merge(aicen(n)*0.1_wp*real(n, wp), 0.0_wp, ice)
         qsnon(1, n) = -1.0e8_wp
         do k = 1, NIL
            qicen(k, n) = -2.5e8_wp - 1.0e7_wp*real(k, wp)
         end do
      end do
   end subroutine simple_state

   subroutine chk_rel(error, label, got, want, rtol)
      type(error_type), allocatable, intent(inout) :: error
      character(len=*), intent(in) :: label
      real(wp), intent(in) :: got, want, rtol
      if (allocated(error)) return
      if (.not. ieee_is_finite(got)) then
         call test_failed(error, label//": non-finite")
         return
      end if
      if (.not. (abs(got - want) <= rtol*abs(want))) then
         call test_failed(error, label//": value differs from the closed form")
      end if
   end subroutine chk_rel

