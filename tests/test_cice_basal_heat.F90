!! Basal heat flux and lateral-melt limiter (D3.1): closed forms, the energy
!! cap, gates, error paths, goldens from the Icepack oracle, the cell entry
!! against the column routine, and a device sweep of every cell.
!!
!! Expected values are closed forms written here or rows of the Icepack
!! oracle (upstream `frzmlt_bottom_lateral`, called directly through a renamed
!! copy; both constant sets, nilyr = 7; inputs regenerated by the LCG recipe
!! `gen_row`, identical to the oracle driver's, with a checksum guarding
!! against recipe drift).
!!
!! The plan's known answer (`sst - Tf = 0.5`, `tau = 0.1 N/m2`) holds:
!! `u* = sqrt(0.1/1026) = 9.8725e-3 m/s` and `fbot = -128.17 W/m2` (the plan's
!! coefficient 25965.8 is really `1026*4218*0.006 = 25966.008`; `fbot = -128.2`
!! to the digits quoted); at `tau = 0` the floor gives `-6.4915 W/m2` for
!! `ustar_min = 5e-4`.
!!
!! Golden tolerances.  Upstream is compared class by class.  `Tbot` and `fbot` on
!! every row where the limiter is inactive (`xtmp = 1`) or `rside = 0` involve no
!! power and are BITWISE on CPU builds (tolerance 0; 1e-12 scale-aware on the GPU
!! build, where FMA contraction is on for host code too; measured worst there
!! 1.6e-16).  The ONLY arithmetic that differs from upstream is the real-exponent
!! power in `ice_lateral_rside`: our reproducible `rdb_sm_pow` against the system
!! libm `pow` of the (pristine) oracle.  So `rside`, `wlat` and the limiter-scaled
!! `fbot` (scaled by an `xtmp` that contains `rside`) are not bitwise.  Measured
!! worst relative differences over 60 rows x 2 constant sets, nilyr = 7:
!!   gfortran -O2, contraction off: rside 2.6e-16, wlat 2.0e-16, scaled fbot 1.2e-16
!!   nvfortran GPU build (FMA on):  rside 1.8e-16, wlat 2.0e-16, scaled fbot 2.8e-16
