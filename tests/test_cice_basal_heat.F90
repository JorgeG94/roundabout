   subroutine test_known_answer(error)
      !! The plan's A6 numbers, recomputed by hand: `sst - Tf = 0.5`, `tau = 0.1` N/m2.
      type(error_type), allocatable, intent(out) :: error
      type(ice_params_t) :: p
      real(wp) :: a(NC), v(NC), vs(NC), qi(NIL, NC), qs(1, NC)
      real(wp) :: fbot, rside, wlat, dTemp, ustar, cpchr, Tf, sst, dt
      integer(int32) :: ie

      p = ice_params_default(ICE_CONSTANTS_ICEPACK, NC, NIL, NSL)
      call simple_state(a, v, vs, qi, qs, .false.)
      a = [1.0_wp, 0.0_wp, 0.0_wp, 0.0_wp, 0.0_wp]
      Tf = -1.8_wp
      sst = Tf + 0.5_wp
      dTemp = sst - Tf
      dt = 900.0_wp
      ie = 0_int32
      call run_cell(p, NC, NIL, dt, -1.0e4_wp, sst, Tf, 0.1_wp, 0.0_wp, 5.0e-4_wp, a, v, vs, qi, qs, fbot, rside, wlat, ie)
      call check(error, ie == 0_int32, "no error bits")
      if (allocated(error)) return
      ustar = sqrt(0.1_wp/1026.0_wp)
      cpchr = 4218.0_wp*1026.0_wp*0.006_wp
      call check(error, abs(ustar - 9.8725e-3_wp) < 1.0e-7_wp, "u* = 9.8725e-3 m/s (plan)")
      if (allocated(error)) return
      call check(error, abs(cpchr - 25966.008_wp) < 1.0e-9_wp, "1026*4218*0.006 = 25966.008 (plan quotes 25965.8)")
      if (allocated(error)) return
      call check(error, abs(fbot + 128.2_wp) < 0.03_wp, "fbot = -128.2 W/m2 (plan, to the digits quoted)")
      if (allocated(error)) return
      call chk_rel(error, "fbot closed form", fbot, -cpchr*dTemp*ustar, 1.0e-14_wp)
      call chk_rel(error, "wlat closed form", wlat, 1.6e-6_wp*dTemp**1.36_wp, 1.0e-14_wp)
      call chk_rel(error, "rside closed form", rside, 1.6e-6_wp*dTemp**1.36_wp*dt*p%c%pi/(0.66_wp*300.0_wp), 1.0e-14_wp)
      call check(error, ICE_FBOT_CH == 0.006_wp, "Ch = 0.006")
   end subroutine test_known_answer

   subroutine test_ustar_floor(error)
      type(error_type), allocatable, intent(out) :: error
      type(ice_params_t) :: p
      real(wp) :: a(NC), v(NC), vs(NC), qi(NIL, NC), qs(1, NC)
      real(wp) :: f0, f1, f2, f3, f4, r, w, cpchr, Tf, sst
      integer(int32) :: ie

      p = ice_params_default(ICE_CONSTANTS_ICEPACK, NC, NIL, NSL)
      call simple_state(a, v, vs, qi, qs, .false.)
      Tf = -1.8_wp
      sst = Tf + 0.5_wp
      cpchr = 4218.0_wp*1026.0_wp*0.006_wp
      ie = 0_int32
      ! tau = 0: the floor; OM3's 5e-4 gives -6.4915 W/m2, the code default 5e-3 ten times that
      call run_cell(p, NC, NIL, 900.0_wp, -1.0e4_wp, sst, Tf, 0.0_wp, 0.0_wp, 5.0e-4_wp, a, v, vs, qi, qs, f0, r, w, ie)
      call chk_rel(error, "tau=0, ustar_min=5e-4", f0, -cpchr*(sst - Tf)*5.0e-4_wp, 1.0e-14_wp)
      call check(error, abs(f0 + 6.4915_wp) < 1.0e-3_wp, "fbot = -6.49 W/m2 at the floor (plan)")
      if (allocated(error)) return
      call run_cell(p, NC, NIL, 900.0_wp, -1.0e4_wp, sst, Tf, 0.0_wp, 0.0_wp, 5.0e-3_wp, a, v, vs, qi, qs, f1, r, w, ie)
      call chk_rel(error, "tau=0, ustar_min=5e-3", f1, -cpchr*(sst - Tf)*5.0e-3_wp, 1.0e-14_wp)
      ! stress below the floor: sqrt(1e-8/1026) = 9.9e-7 << 5e-4
      call run_cell(p, NC, NIL, 900.0_wp, -1.0e4_wp, sst, Tf, 1.0e-8_wp, 0.0_wp, 5.0e-4_wp, a, v, vs, qi, qs, f2, r, w, ie)
      call check(error, f2 == f0, "stress under the floor gives the floor value exactly")
      if (allocated(error)) return
      ! sign of the stress is irrelevant; x and y enter as a magnitude
      call run_cell(p, NC, NIL, 900.0_wp, -1.0e4_wp, sst, Tf, -0.06_wp, 0.08_wp, 5.0e-4_wp, a, v, vs, qi, qs, f3, r, w, ie)
      call run_cell(p, NC, NIL, 900.0_wp, -1.0e4_wp, sst, Tf, 0.1_wp, 0.0_wp, 5.0e-4_wp, a, v, vs, qi, qs, f4, r, w, ie)
      call chk_rel(error, "|(-0.06, 0.08)| = 0.1", f3, f4, 1.0e-14_wp)
      call check(error, ie == 0_int32, "no error bits")
   end subroutine test_ustar_floor

   subroutine test_frzmlt_cap(error)
      !! `frzmlt` bounds `fbot` (no lateral energy: zero volumes), then the limiter's `-puny` shaves 1e-13.
      type(error_type), allocatable, intent(out) :: error
      type(ice_params_t) :: p
      real(wp) :: a(NC), v(NC), vs(NC), qi(NIL, NC), qs(1, NC)
      real(wp) :: fbot, r, w
      integer(int32) :: ie

      p = ice_params_default(ICE_CONSTANTS_ICEPACK, NC, NIL, NSL)
      call simple_state(a, v, vs, qi, qs, .false.)
      ie = 0_int32
      call run_cell(p, NC, NIL, 900.0_wp, -50.0_wp, -1.3_wp, -1.8_wp, 0.1_wp, 0.0_wp, 5.0e-4_wp, a, v, vs, qi, qs, fbot, r, w, ie)
      call check(error, abs(fbot + 50.0_wp) < 1.0e-9_wp, "frzmlt = -50 caps fbot (unbounded value -128.17)")
      if (allocated(error)) return
      call check(error, fbot >= -50.0_wp, "frzmlt <= fbot")
      if (allocated(error)) return
      call run_cell(p, NC, NIL, 900.0_wp, -128.0_wp, -1.3_wp, -1.8_wp, 0.1_wp, 0.0_wp, 5.0e-4_wp, a, v, vs, qi, qs, fbot, r, w, ie)
      call check(error, abs(fbot + 128.0_wp) < 1.0e-9_wp, "frzmlt just above the unbounded value")
   end subroutine test_frzmlt_cap

   subroutine test_energy_cap(error)
      !! With ice the lateral energy `fside` joins `fbot`: when the sum exceeds `frzmlt`
      !! both are scaled by the SAME `xtmp` and the total equals `frzmlt`; when it does not
      !! `xtmp = 1` and nothing is scaled.
      type(error_type), allocatable, intent(out) :: error
      type(ice_params_t) :: p
      real(wp) :: a(NC), v(NC), vs(NC), qi(NIL, NC), qs(1, NC), et(NC)
      real(wp) :: Tb, fb0, rs0, wl0, fb, rs, wl, xt, xt0, fside0, fside1, frz, dt, Tf, sst
      integer(int32) :: ie

      p = ice_params_default(ICE_CONSTANTS_ICEPACK, NC, NIL, NSL)
      call simple_state(a, v, vs, qi, qs, .true.)
      et = melt_energy(NC, NIL, v, vs, qi, qs)
      dt = 900.0_wp
      Tf = -1.8_wp
      sst = Tf + 3.0_wp
      ie = 0_int32
      ! unlimited reference
      call ice_frzmlt_bottom_lateral(NC, dt, sum(a), -1.0e12_wp, sst, Tf, 0.1_wp, 0.0_wp, 5.0e-4_wp, &
                                     p%thermo%floediam, p%thermo%floeshape, p%c%rhow, p%c%cp_ocn, p%c%pi, p%c%puny, &
                                     et, Tb, fb0, rs0, wl0, xt0, ie)
      fside0 = 0.0_wp
      fside0 = rs0*sum(et)/dt
      call check(error, xt0 == 1.0_wp .and. fb0 < 0.0_wp .and. fside0 < 0.0_wp .and. rs0 > 0.0_wp, &
                 "unlimited reference: xtmp = 1, fbot < 0, fside < 0")
      if (allocated(error)) return
      call check(error, Tb == Tf, "Tbot = Tf")
      if (allocated(error)) return
      ! binding: the offered melt potential is half of what the two sinks want
      frz = 0.5_wp*(fb0 + fside0)
      call ice_frzmlt_bottom_lateral(NC, dt, sum(a), frz, sst, Tf, 0.1_wp, 0.0_wp, 5.0e-4_wp, &
                                     p%thermo%floediam, p%thermo%floeshape, p%c%rhow, p%c%cp_ocn, p%c%pi, p%c%puny, &
                                     et, Tb, fb, rs, wl, xt, ie)
      call check(error, xt > 0.0_wp .and. xt < 1.0_wp, "limiter binds: 0 < xtmp < 1")
      if (allocated(error)) return
      fside1 = rs*sum(et)/dt
      call check(error, abs((fb + fside1) - frz) <= 1.0e-9_wp*abs(frz), "fbot + fside = frzmlt when capped")
      if (allocated(error)) return
      call check(error, rs == rs0*xt, "rside scaled by the same xtmp")
      if (allocated(error)) return
      call check(error, wl == wl0, "wlat is the melt SPEED, not scaled")
      if (allocated(error)) return
      call check(error, fb >= frz .and. fb <= 0.0_wp, "frzmlt <= fbot <= 0")
      if (allocated(error)) return
      ! just not binding: potential exceeds the demand
      frz = 2.0_wp*(fb0 + fside0)
      call ice_frzmlt_bottom_lateral(NC, dt, sum(a), frz, sst, Tf, 0.1_wp, 0.0_wp, 5.0e-4_wp, &
                                     p%thermo%floediam, p%thermo%floeshape, p%c%rhow, p%c%cp_ocn, p%c%pi, p%c%puny, &
                                     et, Tb, fb, rs, wl, xt, ie)
      call check(error, xt == 1.0_wp .and. fb == fb0 .and. rs == rs0, "not binding: nothing scaled, bitwise")
      if (allocated(error)) return
      call check(error, ie == 0_int32, "no error bits")
   end subroutine test_energy_cap

   subroutine test_energy_random(error)
      !! Over 400 random cells (all gates, limiter on and off): `frzmlt <= fbot <= 0`, `0 <= rside <= 1`, and
      !! the total heat taken `|fbot + rside*sum(Etot)/dt|` never exceeds `|frzmlt|` (beyond the `puny` slack
      !! of the limiter).  Counts that the limiter bound, the gate closed and the clip to 1 were all exercised.
      type(error_type), allocatable, intent(out) :: error
      type(ice_params_t) :: p
      real(wp) :: a(NC), v(NC), vs(NC), qi(NIL, NC), qs(1, NC), et(NC)
      real(wp) :: dt, frz, sst, Tf, tx, ty, um, fb, rs, wl, Tb, xt, tot
      integer(int32) :: ie
      integer :: key, nbind, ngate, nzero

      p = ice_params_default(ICE_CONSTANTS_ICEPACK, NC, NIL, NSL)
      nbind = 0; ngate = 0; nzero = 0
      do key = 1, 400
         call gen_state(key, NC, NIL, dt, frz, sst, Tf, tx, ty, um, a, v, vs, qi, qs)
         et = melt_energy(NC, NIL, v, vs, qi, qs)
         ie = 0_int32
         call ice_frzmlt_bottom_lateral(NC, dt, sum(a), frz, sst, Tf, tx, ty, um, p%thermo%floediam, &
                                        p%thermo%floeshape, p%c%rhow, p%c%cp_ocn, p%c%pi, p%c%puny, &
                                        et, Tb, fb, rs, wl, xt, ie)
         if (ie /= 0_int32 .or. .not. (ieee_is_finite(fb) .and. ieee_is_finite(rs) .and. ieee_is_finite(wl))) then
            call test_failed(error, "unexpected error or non-finite output")
            return
         end if
         if (rs < 0.0_wp .or. rs > 1.0_wp .or. fb > 0.0_wp) then
            call test_failed(error, "fbot > 0 or rside outside [0, 1]")
            return
         end if
         if (.not. (sum(a) > p%c%puny .and. frz < 0.0_wp)) then
            ngate = ngate + 1
            if (fb /= 0.0_wp .or. rs /= 0.0_wp .or. wl /= 0.0_wp) then
               call test_failed(error, "gate closed but outputs not zero")
               return
            end if
            cycle
         end if
         if (fb < frz) then
            call test_failed(error, "fbot below frzmlt")
            return
         end if
         tot = fb + rs*sum(et)/dt
         if (abs(tot) > abs(frz)*(1.0_wp + 1.0e-12_wp) + 1.0e-9_wp) then
            call test_failed(error, "basal + lateral heat exceeds frzmlt")
            return
         end if
         if (xt < 1.0_wp) nbind = nbind + 1
         if (rs == 0.0_wp) nzero = nzero + 1
      end do
      call check(error, nbind > 20 .and. ngate > 20, "limiter and gate both exercised")
   end subroutine test_energy_random

   subroutine test_gates(error)
      type(error_type), allocatable, intent(out) :: error
      type(ice_params_t) :: p
      real(wp) :: a(NC), v(NC), vs(NC), qi(NIL, NC), qs(1, NC)
      real(wp) :: fb, rs, wl, puny
      integer(int32) :: ie

      p = ice_params_default(ICE_CONSTANTS_ICEPACK, NC, NIL, NSL)
      puny = p%c%puny
      call simple_state(a, v, vs, qi, qs, .true.)
      ie = 0_int32
      ! no ice at all
      a = 0.0_wp
      call run_cell(p, NC, NIL, 900.0_wp, -300.0_wp, 0.0_wp, -1.8_wp, 0.1_wp, 0.0_wp, 5.0e-4_wp, a, v, vs, qi, qs, fb, rs, wl, ie)
      call check(error, fb == 0.0_wp .and. rs == 0.0_wp .and. wl == 0.0_wp, "aice = 0: all outputs 0")
      if (allocated(error)) return
      ! aice exactly puny: the gate is strict
      a(1) = puny
      call run_cell(p, NC, NIL, 900.0_wp, -300.0_wp, 0.0_wp, -1.8_wp, 0.1_wp, 0.0_wp, 5.0e-4_wp, a, v, vs, qi, qs, fb, rs, wl, ie)
      call check(error, fb == 0.0_wp .and. rs == 0.0_wp .and. wl == 0.0_wp, "aice = puny: all outputs 0")
      if (allocated(error)) return
      a(1) = 2.0_wp*puny
      call run_cell(p, NC, NIL, 900.0_wp, -300.0_wp, 0.0_wp, -1.8_wp, 0.1_wp, 0.0_wp, 5.0e-4_wp, a, v, vs, qi, qs, fb, rs, wl, ie)
      call check(error, fb < 0.0_wp .and. rs > 0.0_wp, "aice = 2 puny: melts")
      if (allocated(error)) return
      call simple_state(a, v, vs, qi, qs, .true.)
      ! freezing or zero potential: no basal melt, no lateral melt, even with a warm ocean
      call run_cell(p, NC, NIL, 900.0_wp, 0.0_wp, 2.0_wp, -1.8_wp, 0.1_wp, 0.0_wp, 5.0e-4_wp, a, v, vs, qi, qs, fb, rs, wl, ie)
      call check(error, fb == 0.0_wp .and. rs == 0.0_wp .and. wl == 0.0_wp, "frzmlt = 0: all outputs 0")
      if (allocated(error)) return
      call run_cell(p, NC, NIL, 900.0_wp, 40.0_wp, 2.0_wp, -1.8_wp, 0.1_wp, 0.0_wp, 5.0e-4_wp, a, v, vs, qi, qs, fb, rs, wl, ie)
      call check(error, fb == 0.0_wp .and. rs == 0.0_wp .and. wl == 0.0_wp, "frzmlt > 0 (freezing): all outputs 0")
      if (allocated(error)) return
      ! ocean at or below freezing: melt potential but nothing to transfer
      call run_cell(p, NC, NIL, 900.0_wp, -300.0_wp, -1.8_wp, -1.8_wp, 0.1_wp, 0.0_wp, 5.0e-4_wp, a, v, vs, qi, qs, fb, rs, wl, ie)
      call check(error, fb == 0.0_wp .and. rs == 0.0_wp .and. wl == 0.0_wp, "sst = Tf: no flux")
      if (allocated(error)) return
      call run_cell(p, NC, NIL, 900.0_wp, -300.0_wp, -2.0_wp, -1.8_wp, 0.1_wp, 0.0_wp, 5.0e-4_wp, a, v, vs, qi, qs, fb, rs, wl, ie)
      call check(error, fb == 0.0_wp .and. rs == 0.0_wp .and. wl == 0.0_wp, "sst < Tf: no flux")
      if (allocated(error)) return
      call check(error, ie == 0_int32, "no error bits")
   end subroutine test_gates

   subroutine test_rside_edges(error)
      type(error_type), allocatable, intent(out) :: error
      type(ice_params_t) :: p
      real(wp) :: a(NC), v(NC), vs(NC), qi(NIL, NC), qs(1, NC), et(NC)
      real(wp) :: fb, rs, wl, Tb, xt, cpchr, fside
      integer(int32) :: ie

      p = ice_params_default(ICE_CONSTANTS_ICEPACK, NC, NIL, NSL)
      call simple_state(a, v, vs, qi, qs, .true.)
      et = melt_energy(NC, NIL, v, vs, qi, qs)
      ie = 0_int32
      ! rside clips to 1 (dT = 20 K and a 0.1 m floe give 4.0 before the clip)
      call ice_frzmlt_bottom_lateral(NC, 900.0_wp, sum(a), -1.0e12_wp, 18.2_wp, -1.8_wp, 0.1_wp, 0.0_wp, 5.0e-4_wp, &
                                     0.1_wp, p%thermo%floeshape, p%c%rhow, p%c%cp_ocn, p%c%pi, p%c%puny, &
                                     et, Tb, fb, rs, wl, xt, ie)
      call check(error, rs == 1.0_wp .and. xt == 1.0_wp, "rside clipped to 1, unlimited")
      if (allocated(error)) return
      ! rside underflows to exactly 0 although dT > 0: upstream returns before the limiter,
      ! fbot keeps only its frzmlt bound and wlat is 0 (not the unclipped speed)
      cpchr = 4218.0_wp*1026.0_wp*0.006_wp
      call ice_frzmlt_bottom_lateral(NC, 900.0_wp, sum(a), -50.0_wp, -1.8_wp + 1.0e-250_wp, -1.8_wp, 0.1_wp, 0.0_wp, &
                                     5.0e-4_wp, p%thermo%floediam, p%thermo%floeshape, p%c%rhow, p%c%cp_ocn, p%c%pi, &
                                     p%c%puny, et, Tb, fb, rs, wl, xt, ie)
      fside = 0.0_wp
      call check(error, rs == 0.0_wp .and. wl == 0.0_wp .and. xt == 1.0_wp, "rside = 0 exit: rside = wlat = 0, no limiter")
      if (allocated(error)) return
      call check(error, ie == 0_int32, "no error bits")
   end subroutine test_rside_edges

   subroutine test_errors(error)
      type(error_type), allocatable, intent(out) :: error
      type(ice_params_t) :: p
      real(wp) :: a(NC), v(NC), vs(NC), qi(NIL, NC), qs(1, NC)
      real(wp) :: fb, rs, wl, big
      integer(int32) :: ie

      p = ice_params_default(ICE_CONSTANTS_ICEPACK, NC, NIL, NSL)
      call simple_state(a, v, vs, qi, qs, .true.)
      big = huge(1.0_wp)
      ! non-finite category enthalpy inside the melt gate
      qi(3, 2) = ieee_value(1.0_wp, ieee_positive_inf)
      ie = 0_int32
      call run_cell(p, NC, NIL, 900.0_wp, -300.0_wp, 1.0_wp, -1.8_wp, 0.1_wp, 0.0_wp, 5.0e-4_wp, a, v, vs, qi, qs, fb, rs, wl, ie)
      call check(error, iand(ie, ICE_ERR_NONFINITE) /= 0, &
                 "Inf enthalpy: ICE_ERR_NONFINITE (outputs unspecified)")
      if (allocated(error)) return
      ! the same enthalpy outside the gate is never read: no error
      ie = 0_int32
      call run_cell(p, NC, NIL, 900.0_wp, 5.0_wp, 1.0_wp, -1.8_wp, 0.1_wp, 0.0_wp, 5.0e-4_wp, a, v, vs, qi, qs, fb, rs, wl, ie)
      call check(error, ie == 0_int32 .and. fb == 0.0_wp, "Inf enthalpy behind a closed gate: untouched")
      if (allocated(error)) return
      call simple_state(a, v, vs, qi, qs, .true.)
      ! overflowing lateral flux
      qi(1, 1) = -big
      v(1) = 1.0e30_wp
      ie = 0_int32
      call run_cell(p, NC, NIL, 900.0_wp, -300.0_wp, 1.0_wp, -1.8_wp, 0.1_wp, 0.0_wp, 5.0e-4_wp, a, v, vs, qi, qs, fb, rs, wl, ie)
      call check(error, iand(ie, ICE_ERR_NONFINITE) /= 0, &
                 "overflowing fside: ICE_ERR_NONFINITE")
      if (allocated(error)) return
      call simple_state(a, v, vs, qi, qs, .true.)
      ! negative area beyond -puny
      a(4) = -1.0e-3_wp
      ie = 0_int32
      call run_cell(p, NC, NIL, 900.0_wp, -300.0_wp, 1.0_wp, -1.8_wp, 0.1_wp, 0.0_wp, 5.0e-4_wp, a, v, vs, qi, qs, fb, rs, wl, ie)
      call check(error, iand(ie, ICE_ERR_AICEN_NEG) /= 0, &
                 "aicen < -puny: ICE_ERR_AICEN_NEG")
      if (allocated(error)) return
      ! a round-off negative area is not an error
      a(4) = -1.0e-20_wp
      ie = 0_int32
      call run_cell(p, NC, NIL, 900.0_wp, -300.0_wp, 1.0_wp, -1.8_wp, 0.1_wp, 0.0_wp, 5.0e-4_wp, a, v, vs, qi, qs, fb, rs, wl, ie)
      call check(error, ie == 0_int32 .and. fb < 0.0_wp, "round-off negative area: no error")
      if (allocated(error)) return
      ! bits already in the word survive
      call simple_state(a, v, vs, qi, qs, .true.)
      a(4) = -1.0e-3_wp
      ie = 128_int32
      call run_cell(p, NC, NIL, 900.0_wp, -300.0_wp, 1.0_wp, -1.8_wp, 0.1_wp, 0.0_wp, 5.0e-4_wp, a, v, vs, qi, qs, fb, rs, wl, ie)
      call check(error, iand(ie, 128_int32) /= 0 .and. iand(ie, ICE_ERR_AICEN_NEG) /= 0, "prior error bits kept and OR-ed")
   end subroutine test_errors

   subroutine test_nan_in(error)
      !! A NaN or Inf in any scalar input of a cell raises `ICE_ERR_NONFINITE`, whatever the gate (outputs are unspecified on an error bit).
      type(error_type), allocatable, intent(out) :: error
      type(ice_params_t) :: p
      real(wp) :: a(NC), v(NC), vs(NC), qi(NIL, NC), qs(1, NC)
      real(wp) :: x(7), y(7), fb, rs, wl, nan, inf
      integer(int32) :: ie
      integer :: m, mode
      character(len=7), parameter :: NAMES(7) = [character(len=7) :: "dt", "frzmlt", "sst", "Tf", "tau_x", "tau_y", "aicen"]

      p = ice_params_default(ICE_CONSTANTS_ICEPACK, NC, NIL, NSL)
      nan = ieee_value(1.0_wp, ieee_quiet_nan)
      inf = ieee_value(1.0_wp, ieee_positive_inf)
      do mode = 1, 2
         do m = 1, 7
            call simple_state(a, v, vs, qi, qs, .true.)
            x = [900.0_wp, -300.0_wp, 1.0_wp, -1.8_wp, 0.1_wp, 0.05_wp, 0.0_wp]
            y = x
            if (m < 7) then
               y(m) = merge(nan, inf, mode == 1)
            else
               a(2) = merge(nan, inf, mode == 1)
            end if
            ie = 0_int32
            call run_cell(p, NC, NIL, y(1), y(2), y(3), y(4), y(5), y(6), 5.0e-4_wp, a, v, vs, qi, qs, fb, rs, wl, ie)
            if (iand(ie, ICE_ERR_NONFINITE) == 0) then
               call test_failed(error, trim(NAMES(m))//" non-finite: ICE_ERR_NONFINITE not raised")
               return
            end if
         end do
      end do
   end subroutine test_nan_in

