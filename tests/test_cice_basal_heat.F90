   subroutine test_cell_vs_column(error)
      !! The cell entry reads the state in place; the column routine sees per-category energies.  Bitwise equal
      !! for several category / layer counts (the arithmetic order is the same by construction).
      type(error_type), allocatable, intent(out) :: error
      integer, parameter :: NCS(4) = [1, 3, 5, 8], NLS(4) = [1, 4, 7, 7]
      integer :: is
      do is = 1, 4
         call one_shape(NCS(is), NLS(is), error)
         if (allocated(error)) return
      end do
   end subroutine test_cell_vs_column

   subroutine one_shape(ncat, nilyr, error)
      integer, intent(in) :: ncat, nilyr
      type(error_type), allocatable, intent(out) :: error
      type(ice_params_t) :: p
      real(wp) :: a(ncat), v(ncat), vs(ncat), qi(nilyr, ncat), qs(1, ncat), et(ncat)
      real(wp) :: dt, frz, sst, Tf, tx, ty, um, fb, rs, wl, fc, rc, wc, Tb, xt
      integer(int32) :: ie, ic
      integer :: key, nact

      p = ice_params_default(ICE_CONSTANTS_ICEPACK, ncat, nilyr, NSL)
      nact = 0
      do key = 1, 120
         call gen_state(key, ncat, nilyr, dt, frz, sst, Tf, tx, ty, um, a, v, vs, qi, qs)
         et = melt_energy(ncat, nilyr, v, vs, qi, qs)
         ie = 0_int32
         call run_cell(p, ncat, nilyr, dt, frz, sst, Tf, tx, ty, um, a, v, vs, qi, qs, fb, rs, wl, ie)
         ic = 0_int32
         call ice_frzmlt_bottom_lateral(ncat, dt, sum(a), frz, sst, Tf, tx, ty, um, p%thermo%floediam, &
                                        p%thermo%floeshape, p%c%rhow, p%c%cp_ocn, p%c%pi, p%c%puny, &
                                        et, Tb, fc, rc, wc, xt, ic)
         if (ie /= ic .or. fb /= fc .or. rs /= rc .or. wl /= wc) then
            call test_failed(error, "cell entry differs from the column routine")
            return
         end if
         if (fc < 0.0_wp) nact = nact + 1
      end do
      call check(error, nact > 20, "enough melting cells in the comparison")
   end subroutine one_shape

   subroutine fill_cell_state(nx, ny, ncat, nilyr, i, j, aicen, vicen, vsnon, qicen, qsnon, frzmlt, sst, Tf, tx, ty)
      !! Random state of cell (i, j): a distinct recipe key per cell, copied into the SoA arrays.
      integer, intent(in) :: nx, ny, ncat, nilyr, i, j
      real(wp), intent(inout) :: aicen(nx, ny, ncat), vicen(nx, ny, ncat), vsnon(nx, ny, ncat)
      real(wp), intent(inout) :: qicen(nx, ny, ncat, nilyr), qsnon(nx, ny, ncat, 1)
      real(wp), intent(inout) :: frzmlt(nx, ny), sst(nx, ny), Tf(nx, ny), tx(nx, ny), ty(nx, ny)
      real(wp) :: dt, um, a(ncat), v(ncat), vs(ncat), qi(nilyr, ncat), qs(1, ncat)
      integer :: n, k

      call gen_state(i + 1000*j, ncat, nilyr, dt, frzmlt(i, j), sst(i, j), Tf(i, j), tx(i, j), ty(i, j), um, &
                     a, v, vs, qi, qs)
      do n = 1, ncat
         aicen(i, j, n) = a(n); vicen(i, j, n) = v(n); vsnon(i, j, n) = vs(n); qsnon(i, j, n, 1) = qs(1, n)
         do k = 1, nilyr
            qicen(i, j, n, k) = qi(k, n)
         end do
      end do
   end subroutine fill_cell_state

   subroutine test_device_sweep(error)
      !! Device sweep over a random multi-cell state in which EVERY cell differs (own stress, ocean, ice, melt
      !! potential): every output of every cell is compared with the host cell kernel (indices as literal loop
      !! variables) over the INTERIOR range 2:NX-1, 2:NY-1 (the ring must stay untouched).  Two cells carry injected errors (NaN `frzmlt`, negative area) so the error word is compared
      !! non-trivially (outputs of those two cells are unspecified and not compared).  Tolerance 1e-13 relative on the GPU build (FMA), bitwise on CPU builds; non-finite
      !! results fail explicitly.
      type(error_type), allocatable, intent(out) :: error
      integer, parameter :: NX = 37, NY = 23
      type(ice_params_t) :: p
      real(wp) :: a(NX, NY, NC), v(NX, NY, NC), vs(NX, NY, NC), qi(NX, NY, NC, NIL), qs(NX, NY, NC, 1)
      real(wp) :: frz(NX, NY), sst(NX, NY), Tf(NX, NY), tx(NX, NY), ty(NX, NY)
      real(wp) :: fb(NX, NY), rs(NX, NY), wl(NX, NY), fbh(NX, NY), rsh(NX, NY), wlh(NX, NY)
      integer(int32) :: ie(NX, NY), ieh(NX, NY)
      real(wp) :: dt, worst, x
      integer :: i, j, nmelt, nzero, nlim
      logical :: ring(NX, NY)

      p = ice_params_default(ICE_CONSTANTS_ICEPACK, NC, NIL, NSL)
      dt = 1200.0_wp
      do j = 1, NY
         do i = 1, NX
            call fill_cell_state(NX, NY, NC, NIL, i, j, a, v, vs, qi, qs, frz, sst, Tf, tx, ty)
         end do
      end do
      frz(3, 4) = ieee_value(1.0_wp, ieee_quiet_nan)
      a(5, 2, 1) = -1.0e-3_wp
      fb = 7.0_wp; rs = 7.0_wp; wl = 7.0_wp; ie = 0_int32
      fbh = 7.0_wp; rsh = 7.0_wp; wlh = 7.0_wp; ieh = 0_int32
      do j = 2, NY - 1
         do i = 2, NX - 1
            call ice_frzmlt_bottom_lateral_cell(i, j, NX, NY, NC, NIL, NSL, dt, p%thermo%ustar_min, p%thermo%floediam, &
                                                p%thermo%floeshape, p%c%rhow, p%c%cp_ocn, p%c%pi, p%c%puny, &
                                                a, v, vs, qi, qs, frz, sst, Tf, tx, ty, fbh, rsh, wlh, ieh)
         end do
      end do
      !$acc enter data copyin(a, v, vs, qi, qs, frz, sst, Tf, tx, ty, fb, rs, wl, ie)
      call ice_basal_heat_step(NX, NY, NC, NIL, NSL, 2, NX - 1, 2, NY - 1, dt, p, a, v, vs, qi, qs, frz, sst, Tf, tx, ty, &
                               fb, rs, wl, ie)
      !$acc update self(fb, rs, wl, ie)
      !$acc exit data delete(a, v, vs, qi, qs, frz, sst, Tf, tx, ty, fb, rs, wl, ie)
      worst = 0.0_wp
      nmelt = 0; nzero = 0; nlim = 0
      do j = 1, NY
         do i = 1, NX
            if (ieh(i, j) == 0_int32) then      ! outputs are unspecified on an error bit
               call chk(fb(i, j), fbh(i, j))
               call chk(rs(i, j), rsh(i, j))
               call chk(wl(i, j), wlh(i, j))
            end if
            if (fbh(i, j) < 0.0_wp) nmelt = nmelt + 1
            if (fbh(i, j) == 0.0_wp) nzero = nzero + 1
            if (rsh(i, j) > 0.0_wp .and. rsh(i, j) < 1.0_wp) nlim = nlim + 1
         end do
      end do
      if (.not. (worst <= TOL_DEV)) then
         call test_failed(error, "device driver differs from the host kernel in some cell (or is non-finite)")
         return
      end if
      call check(error, all(ie == ieh), "error words agree on every cell")
      if (allocated(error)) return
      ! the outer ring is outside the driver's range: sentinels and error words untouched
      ring = .true.
      ring(2:NX - 1, 2:NY - 1) = .false.
      call check(error, all(fb(:, :) == 7.0_wp .or. .not. ring) .and. all(rs == 7.0_wp .or. .not. ring) &
                 .and. all(wl == 7.0_wp .or. .not. ring) .and. all(ie == 0_int32 .or. .not. ring), &
                 "outer ring keeps its sentinel and a zero error word")
      if (allocated(error)) return
      call check(error, ie(3, 4) == ICE_ERR_NONFINITE .and. ie(5, 2) == ICE_ERR_AICEN_NEG .and. count(ie /= 0) == 2, &
                 "exactly the two injected errors are flagged")
      if (allocated(error)) return
      call check(error, nmelt > NX*NY/4 .and. nzero > NX*NY/10 .and. nlim > NX*NY/10, &
                 "sweep covers melting, closed-gate and lateral-melt cells (not vacuous)")
   contains
      subroutine chk(d, h)
         real(wp), intent(in) :: d, h
         if (.not. (ieee_is_finite(d) .and. ieee_is_finite(h))) then
            worst = huge(1.0_wp)
            return
         end if
         x = abs(d - h)/max(abs(h), tiny(1.0_wp))
         if (x > worst) worst = x
      end subroutine chk
   end subroutine test_device_sweep

   subroutine test_throughput(error)
      !! Throughput of the driver on 512 x 512 cells, 5 categories, 7 ice layers (cells per second; reported
      !! on the output unit; the assertion is only that the result is finite and that cells melted).
      type(error_type), allocatable, intent(out) :: error
      integer, parameter :: NX = 512, NY = 512, NIT = 5
      type(ice_params_t) :: p
      real(wp), allocatable :: a(:, :, :), v(:, :, :), vs(:, :, :), qi(:, :, :, :), qs(:, :, :, :)
      real(wp), allocatable :: frz(:, :), sst(:, :), Tf(:, :), tx(:, :), ty(:, :), fb(:, :), rs(:, :), wl(:, :)
      integer(int32), allocatable :: ie(:, :)
      integer(int64) :: t0, t1, rate
      integer :: i, j, it
      real(wp) :: secs, tot

      allocate (a(NX, NY, NC), v(NX, NY, NC), vs(NX, NY, NC), qi(NX, NY, NC, NIL), qs(NX, NY, NC, 1))
      allocate (frz(NX, NY), sst(NX, NY), Tf(NX, NY), tx(NX, NY), ty(NX, NY), fb(NX, NY), rs(NX, NY), wl(NX, NY))
      allocate (ie(NX, NY))
      p = ice_params_default(ICE_CONSTANTS_ICEPACK, NC, NIL, NSL)
      do j = 1, NY
         do i = 1, NX
            call fill_cell_state(NX, NY, NC, NIL, i, j, a, v, vs, qi, qs, frz, sst, Tf, tx, ty)
         end do
      end do
      fb = 0.0_wp; rs = 0.0_wp; wl = 0.0_wp; ie = 0_int32
      !$acc enter data copyin(a, v, vs, qi, qs, frz, sst, Tf, tx, ty, fb, rs, wl, ie)
      call ice_basal_heat_step(NX, NY, NC, NIL, NSL, 1, NX, 1, NY, 1200.0_wp, p, a, v, vs, qi, qs, frz, sst, Tf, tx, ty, &
                               fb, rs, wl, ie)                                ! warm-up
      !$acc update self(fb)
      call system_clock(t0, rate)
      do it = 1, NIT
         call ice_basal_heat_step(NX, NY, NC, NIL, NSL, 1, NX, 1, NY, 1200.0_wp, p, a, v, vs, qi, qs, frz, sst, Tf, tx, &
                                  ty, fb, rs, wl, ie)
      end do
      !$acc update self(fb)
      call system_clock(t1)
      !$acc update self(rs, wl, ie)
      !$acc exit data delete(a, v, vs, qi, qs, frz, sst, Tf, tx, ty, fb, rs, wl, ie)
      secs = real(t1 - t0, wp)/real(rate, wp)
      write (output_unit, '(a,f9.3,a,es10.3,a)') "basal_heat driver 512x512x5x7: ", 1.0e3_wp*secs/real(NIT, wp), &
         " ms/step, ", real(NX, wp)*real(NY, wp)*real(NIT, wp)/secs, " cells/s"
      tot = sum(fb) + sum(rs) + sum(wl)
      call check(error, ieee_is_finite(tot) .and. all(ie == 0_int32), "finite results, no error bits")
      if (allocated(error)) return
      call check(error, count(fb < 0.0_wp) > NX*NY/4, "cells melted")
   end subroutine test_throughput

end module test_cice_basal_heat
