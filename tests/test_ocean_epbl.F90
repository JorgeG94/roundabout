   subroutine test_lf17_spot(error)
      !! La spot values vs the Python reference implementation
      !! (post floor-removal): the COARE 3.5
      !! u*->U10 inversion + Phillips-spectrum SL-averaged Stokes
      !! drift, zsl = 0.04*BLD, raw La = sqrt(u*/u_s_SL).
      type(error_type), allocatable, intent(out) :: error
      real(wp), parameter :: USTAR_REF(4) = [0.005_wp, 0.01_wp, 0.01_wp, 0.02_wp]
      real(wp), parameter :: BLD_REF(4) = [20.0_wp, 20.0_wp, 50.0_wp, 50.0_wp]
      real(wp), parameter :: LA_REF(4) = [0.4129_wp, 0.3627_wp, 0.4372_wp, 0.3947_wp]
      real(wp), parameter :: U10_REF(4) = [5.08_wp, 8.51_wp, 8.51_wp, 14.01_wp]
      real(wp) :: u10, ustokes, kphil, la
      integer :: n
      checks: block
         do n = 1, 4
            call epbl_lf17_wave_state(USTAR_REF(n), RHO0, u10, ustokes, kphil)
            call check(error, abs(u10 - U10_REF(n)) < 0.02_wp*U10_REF(n), &
                       "LF17 U10 outside 2% of the prototype reference")
            if (allocated(error)) exit checks
            la = epbl_lf17_la(USTAR_REF(n), 0.04_wp*BLD_REF(n), ustokes, kphil)
            call check(error, abs(la - LA_REF(n)) < 0.01_wp*LA_REF(n), &
                       "LF17 La outside 1% of the prototype reference")
            if (allocated(error)) exit checks
         end do
      end block checks
   end subroutine test_lf17_spot

   subroutine test_lt_monotone(error)
      !! With the stability modification off (lac = 0): smaller La =>
      !! larger multiplicative enhancement, capped at lt_max_enhance.
      type(error_type), allocatable, intent(out) :: error
      real(wp) :: m_hi_la, m_lo_la, m_tiny_la
      checks: block
         m_hi_la = 1.0_wp
         call epbl_lt_enhance(EPBL_LT_RESCALE, 0.447_wp, -1.33_wp, 5.0_wp, &
                              0.41_wp, 0.0_wp, 0.0_wp, 0.0_wp, 0.0_wp, 0.0_wp, &
                              0.6_wp, 0.0_wp, 0.01_wp, 50.0_wp, 0.0_wp, m_hi_la)
         m_lo_la = 1.0_wp
         call epbl_lt_enhance(EPBL_LT_RESCALE, 0.447_wp, -1.33_wp, 5.0_wp, &
                              0.41_wp, 0.0_wp, 0.0_wp, 0.0_wp, 0.0_wp, 0.0_wp, &
                              0.3_wp, 0.0_wp, 0.01_wp, 50.0_wp, 0.0_wp, m_lo_la)
         m_tiny_la = 1.0_wp
         call epbl_lt_enhance(EPBL_LT_RESCALE, 0.447_wp, -1.33_wp, 5.0_wp, &
                              0.41_wp, 0.0_wp, 0.0_wp, 0.0_wp, 0.0_wp, 0.0_wp, &
                              0.01_wp, 0.0_wp, 0.01_wp, 50.0_wp, 0.0_wp, m_tiny_la)
         call check(error, m_hi_la > 1.0_wp, "LT must enhance mstar (La = 0.6)")
         if (allocated(error)) exit checks
         call check(error, m_lo_la > m_hi_la, &
                    "smaller La must enhance more (La 0.3 vs 0.6)")
         if (allocated(error)) exit checks
         call check(error, abs(m_tiny_la - 5.0_wp) < 1.0e-12_wp, &
                    "enhancement must cap at lt_max_enhance for tiny La")
         if (allocated(error)) exit checks
         ! Hand value: 1 + 0.447*0.3^(-1.33) = 1 + 0.447*exp(-1.33*log(0.3)).
         call check(error, abs(m_lo_la - (1.0_wp + 0.447_wp*0.3_wp**(-1.33_wp))) &
                    < 1.0e-12_wp, "rescale formula mismatch at La = 0.3")
      end block checks
   end subroutine test_lt_monotone

   subroutine test_lt_deepens(error)
      !! End-to-end: same wind-deepening setup, LT off vs LT on (lac
      !! = 0, rescale).  The Langmuir enhancement multiplies mstar by
      !! ~3x at La ~ 0.36, so the LT-on MLD must be clearly deeper.
      type(error_type), allocatable, intent(out) :: error
      type(hgrid_t) :: grid
      type(multilayer_state_t) :: ms
      type(ocean_epbl_t) :: epbl_off, epbl_on
      type(ocean_surface_stress_t) :: ss
      type(ocean_surface_flux_t) :: sf
      type(ocean_vdiff_t) :: vd
      integer, parameter :: NZ = 80
      real(wp), parameter :: DZ = 3.0_wp, DT = 1800.0_wp
      integer, parameter :: N_STEPS = 48           ! 1 day
      real(wp) :: mld_a(4), mld_b(4), t_s(4), dT_dz
      checks: block
         call make_grid(grid, 6, 4)
         ms%nz_ml = NZ
         call ms%init(grid)
         call ss%init(grid)
         call ss%set_wind_stress_const(RHO0*0.01_wp**2, 0.0_wp)
         call sf%init(grid)
         call vd%init(grid, nz_ml=NZ)
         dT_dz = 1.0e-4_wp*RHO0/(GRAVITY*ALPHA_LIN)

         call setup_epbl(epbl_off, grid, NZ)
         call setup_stratified_T(ms, NZ, DZ, 15.0_wp, dT_dz)
         call run_epbl_steps(grid, ms, epbl_off, ss, sf, vd, DT, N_STEPS, &
                             mld_a, t_s, sample_every=N_STEPS/4)

         call setup_epbl(epbl_on, grid, NZ)
         epbl_on%use_lt = .true.
         epbl_on%lt_scheme = EPBL_LT_RESCALE
         epbl_on%lt_lac1 = 0.0_wp
         epbl_on%lt_lac4 = 0.0_wp
         epbl_on%lt_lac5 = 0.0_wp
         call setup_stratified_T(ms, NZ, DZ, 15.0_wp, dT_dz)
         call run_epbl_steps(grid, ms, epbl_on, ss, sf, vd, DT, N_STEPS, &
                             mld_b, t_s, sample_every=N_STEPS/4)

         call check(error, mld_b(4) > 1.1_wp*mld_a(4), &
                    "Langmuir enhancement failed to deepen the wind-mixed layer")
         if (allocated(error)) exit checks
         ! La diagnostic populated and in the wind-sea range.
         call check(error, epbl_on%la(grid%nx_total/2, grid%ny_total/2) > 0.2_wp &
                    .and. epbl_on%la(grid%nx_total/2, grid%ny_total/2) < 0.6_wp, &
                    "La diagnostic outside the wind-sea range")
         if (allocated(error)) exit checks
         call check(error, abs(epbl_off%la(grid%nx_total/2, grid%ny_total/2)) &
                    < 1.0e-30_wp, "La must stay 0 with use_lt off")
      end block checks
      call vd%destroy(); call sf%destroy(); call ss%destroy()
      call epbl_on%destroy(); call epbl_off%destroy(); call ms%destroy()
   end subroutine test_lt_deepens

end module test_ocean_epbl
