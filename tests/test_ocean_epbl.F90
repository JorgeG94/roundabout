!! Unit + analytical tests for the energetics-based PBL
!! (`rdb_ocean_epbl`).  Golden values generated by a Python reference
!! prototype of the RH18 energetics solve.
!!
!! Cases:
!!   * Wright/linear dSV derivatives vs centred finite differences.
!!   * OM4 mstar formula hand-check.
!!   * Surface-seed identity: pure cooling gives the convective
!!     ledger term nstar * (-0.5 rho0 h_sfc B0) exactly.
!!   * Kraus-Turner wind deepening: f = 0, linear N², constant u*;
!!     MLD grows as (12 mstar u*^3 t / N²)^(1/3) — exponent + a
!!     prefactor band that accounts for the transition-layer shape.
!!   * TKE budget closure to round-off under combined wind + cooling.
!!   * Stabilizing surface flux shoals the MLD vs the neutral run.
!!   * Convective deepening tracks the encroachment scale when the
!!     cooling is actually applied to T (production ordering:
!!     surface flux -> EPBL -> implicit diffusion).
module test_ocean_epbl
   use testdrive, only: new_unittest, unittest_type, error_type, check
   use rdb_constants, only: wp, GRAVITY
   use rdb_grid, only: hgrid_t
   use rdb_multilayer_state, only: multilayer_state_t
   use rdb_ocean_epbl, only: ocean_epbl_t, epbl_compute, epbl_find_mstar, &
                             epbl_lf17_wave_state, epbl_lf17_la, epbl_lt_enhance, &
                             EPBL_MSTAR_CONSTANT, EPBL_MSTAR_OM4, EPBL_LT_RESCALE
   use rdb_eos, only: eos_t, eos_specvol_derivs, eos_density_point, &
                      EOS_VARIANT_LINEAR, EOS_VARIANT_WRIGHT_97
   use rdb_ocean_surface_stress, only: ocean_surface_stress_t
   use rdb_ocean_surface_flux, only: ocean_surface_flux_t, SEAWATER_CP, &
                                     ocean_surface_flux_apply_tracers
   use rdb_ocean_vdiff, only: ocean_vdiff_t, vdiff_apply_tracers
   implicit none
   private

   public :: collect_ocean_epbl_tests

   integer, parameter :: NGHOST = 2
   real(wp), parameter :: RHO0 = 1035.0_wp
   real(wp), parameter :: ALPHA_LIN = 0.2_wp   ! kg/m^3/K (realistic)
   real(wp), parameter :: BETA_LIN = 0.8_wp    ! kg/m^3/PSU

contains

   subroutine collect_ocean_epbl_tests(testsuite)
      type(unittest_type), allocatable, intent(out) :: testsuite(:)

      testsuite = [ &
                  new_unittest("epbl_dsv_derivs_match_finite_difference", test_dsv_fd), &
                  new_unittest("epbl_mstar_om4_formula", test_mstar_om4), &
                  new_unittest("epbl_ctke_seed_identity", test_ctke_seed), &
                  new_unittest("epbl_wind_deepening_kraus_turner", test_wind_deepening), &
                  new_unittest("epbl_tke_budget_closes", test_budget_closure), &
                  new_unittest("epbl_stable_flux_shoals_mld", test_stable_shoals), &
                  new_unittest("epbl_convective_deepening", test_convective), &
                  new_unittest("epbl_lf17_la_spot_values", test_lf17_spot), &
                  new_unittest("epbl_lt_enhancement_monotone", test_lt_monotone), &
                  new_unittest("epbl_lt_deepens_wind_mixing", test_lt_deepens) &
                  ]
   end subroutine collect_ocean_epbl_tests

   ! -----------------------------------------------------------------
   ! Helpers
   ! -----------------------------------------------------------------

   subroutine make_grid(grid, nx_phys, ny_phys)
      type(hgrid_t), intent(out) :: grid
      integer, intent(in) :: nx_phys, ny_phys
      call grid%init(nx_phys, ny_phys, NGHOST, 1.0_wp, 1.0_wp)
   end subroutine make_grid

   subroutine setup_epbl(epbl, grid, nz)
      !! Default analytical-test configuration: linear EOS with
      !! realistic sensitivities, constant mstar, cube-root vstar,
      !! f = 0 (set_f_centre overrides where a test needs rotation).
      type(ocean_epbl_t), intent(inout) :: epbl
      type(hgrid_t), intent(in) :: grid
      integer, intent(in) :: nz
      call epbl%init(grid, nz_ml=nz)
      epbl%enable = .true.
      epbl%mstar_scheme = EPBL_MSTAR_CONSTANT
      epbl%mstar_const = 1.2_wp
      epbl%nstar = 0.2_wp
      epbl%eos%variant = EOS_VARIANT_LINEAR
      epbl%eos%alpha_T = ALPHA_LIN
      epbl%eos%beta_S = BETA_LIN
      epbl%eos%rho0 = RHO0
      epbl%rho0 = RHO0
      epbl%f_centre = 0.0_wp
      epbl%tke_diags = .true.
   end subroutine setup_epbl

   subroutine setup_stratified_T(ms, nz, dz, t_surf, dT_dz)
      !! Linear temperature stratification: T(k) decreases downward
      !! from `t_surf` at the surface layer (k = nz) with gradient
      !! dT_dz (K/m, positive = stable for alpha > 0).  Uniform S.
      type(multilayer_state_t), intent(inout) :: ms
      integer, intent(in) :: nz
      real(wp), intent(in) :: dz, t_surf, dT_dz
      integer :: k
      real(wp) :: z_below_surf, t_k

      ms%h_layer = dz
      ms%u_face_x_layer = 0.0_wp
      ms%v_face_y_layer = 0.0_wp
      do k = 1, nz
         ! depth of layer-k centre below the surface
         z_below_surf = (real(nz - k, wp) + 0.5_wp)*dz
         t_k = t_surf - dT_dz*z_below_surf
         ms%tracers(ms%idx_temperature)%hTr(:, :, k) = t_k*dz
         ms%tracers(ms%idx_salinity)%hTr(:, :, k) = 35.0_wp*dz
      end do
   end subroutine setup_stratified_T

   subroutine run_epbl_steps(grid, ms, epbl, ss, sf, vd, dt, n_steps, &
                             mld_series, t_series, sample_every)
      !! Drive the production sequence per step on device:
      !!   surface flux into T -> EPBL -> implicit T/S diffusion
      !! with EPBL's kd_int as the tracer diffusivity.  Samples
      !! `epbl%mld` at the probe column every `sample_every` steps.
      type(hgrid_t), intent(in) :: grid
      type(multilayer_state_t), intent(inout) :: ms
      type(ocean_epbl_t), intent(inout) :: epbl
      type(ocean_surface_stress_t), intent(inout) :: ss
      type(ocean_surface_flux_t), intent(inout) :: sf
         !! inout: enter_data / exit_data map Q_heat/Q_salt to device
      type(ocean_vdiff_t), intent(inout) :: vd
      real(wp), intent(in) :: dt
      integer, intent(in) :: n_steps, sample_every
      real(wp), intent(out) :: mld_series(:), t_series(:)

      integer :: step, n_sample, i_probe, j_probe

      i_probe = grid%nx_total/2
      j_probe = grid%ny_total/2
      n_sample = 0

      !$acc enter data copyin(ms, epbl, ss, sf, vd)
      call ms%enter_data()
      call sf%enter_data()
      call epbl%enter_data()
      call vd%enter_data()
      do step = 1, n_steps
         call ocean_surface_flux_apply_tracers(grid, sf, ms, dt, active=.true.)
         call epbl_compute(grid, epbl, ms, ss, dt, sf=sf)
         call vdiff_apply_tracers(grid, vd, ms, dt, kt_source=epbl%kd_int)
         if (mod(step, sample_every) == 0 .and. n_sample < size(mld_series)) then
            n_sample = n_sample + 1
            !$acc update self(epbl%mld)
            mld_series(n_sample) = epbl%mld(i_probe, j_probe)
            t_series(n_sample) = real(step, wp)*dt
         end if
      end do
      !$acc update self(epbl%mld, epbl%kd_int, epbl%la)
      !$acc update self(epbl%tke_wind, epbl%tke_conv)
      !$acc update self(epbl%tke_forcing, epbl%tke_mixing)
      !$acc update self(epbl%tke_mech_decay, epbl%tke_conv_decay)
      call vd%exit_data()
      call epbl%exit_data()
      call sf%exit_data()
      call ms%exit_data()
      !$acc exit data delete(ms, epbl, ss, sf, vd)
   end subroutine run_epbl_steps

   pure subroutine fit_loglog_slope(t_series, d_series, n, slope)
      !! Least-squares slope of log(D) vs log(t).
      real(wp), intent(in) :: t_series(:), d_series(:)
      integer, intent(in) :: n
      real(wp), intent(out) :: slope
      real(wp) :: x_mean, y_mean, sxy, sxx, x, y
      integer :: m

      x_mean = 0.0_wp
      y_mean = 0.0_wp
      do m = 1, n
         x_mean = x_mean + log(t_series(m))
         y_mean = y_mean + log(d_series(m))
      end do
      x_mean = x_mean/real(n, wp)
      y_mean = y_mean/real(n, wp)
      sxy = 0.0_wp
      sxx = 0.0_wp
      do m = 1, n
         x = log(t_series(m)) - x_mean
         y = log(d_series(m)) - y_mean
         sxy = sxy + x*y
         sxx = sxx + x*x
      end do
      slope = sxy/sxx
   end subroutine fit_loglog_slope

