   ! Cases
   ! -----------------------------------------------------------------

   subroutine test_dsv_fd(error)
      !! eos_specvol_derivs vs centred finite differences of
      !! 1/eos_density_point, for Wright (three (T,S,p) points) and
      !! linear (exact).
      type(error_type), allocatable, intent(out) :: error
      real(wp), parameter :: T_PTS(3) = [2.0_wp, 10.0_wp, 25.0_wp]
      real(wp), parameter :: S_PTS(3) = [33.0_wp, 35.0_wp, 37.5_wp]
      real(wp), parameter :: P_PTS(3) = [0.0_wp, 2.0e6_wp, 4.0e7_wp]
      real(wp), parameter :: EPS_T = 1.0e-4_wp, EPS_S = 1.0e-4_wp
      real(wp) :: dsv_dt, dsv_ds, fd_dt, fd_ds, sv_p, sv_m
      type(eos_t) :: eos_w, eos_l
      integer :: n
      eos_w%variant = EOS_VARIANT_WRIGHT_97
      eos_w%rho0 = RHO0; eos_w%alpha_T = ALPHA_LIN; eos_w%beta_S = BETA_LIN
      eos_l%variant = EOS_VARIANT_LINEAR
      eos_l%rho0 = RHO0; eos_l%alpha_T = ALPHA_LIN; eos_l%beta_S = BETA_LIN
      checks: block
         do n = 1, 3
            call eos_specvol_derivs(eos_w, T_PTS(n), S_PTS(n), P_PTS(n), &
                                    dsv_dt, dsv_ds)
            sv_p = 1.0_wp/eos_density_point(eos_w, T_PTS(n) + EPS_T, S_PTS(n), P_PTS(n))
            sv_m = 1.0_wp/eos_density_point(eos_w, T_PTS(n) - EPS_T, S_PTS(n), P_PTS(n))
            fd_dt = (sv_p - sv_m)/(2.0_wp*EPS_T)
            sv_p = 1.0_wp/eos_density_point(eos_w, T_PTS(n), S_PTS(n) + EPS_S, P_PTS(n))
            sv_m = 1.0_wp/eos_density_point(eos_w, T_PTS(n), S_PTS(n) - EPS_S, P_PTS(n))
            fd_ds = (sv_p - sv_m)/(2.0_wp*EPS_S)
            call check(error, abs(dsv_dt - fd_dt) < 1.0e-7_wp*abs(fd_dt), &
                       "Wright dSV/dT disagrees with finite difference")
            if (allocated(error)) exit checks
            call check(error, abs(dsv_ds - fd_ds) < 1.0e-7_wp*abs(fd_ds), &
                       "Wright dSV/dS disagrees with finite difference")
            if (allocated(error)) exit checks
         end do
         ! Linear: exact closed forms.
         call eos_specvol_derivs(eos_l, 10.0_wp, 35.0_wp, 0.0_wp, dsv_dt, dsv_ds)
         call check(error, abs(dsv_dt - ALPHA_LIN/RHO0**2) < 1.0e-20_wp, &
                    "linear dSV/dT mismatch")
         if (allocated(error)) exit checks
         call check(error, abs(dsv_ds + BETA_LIN/RHO0**2) < 1.0e-20_wp, &
                    "linear dSV/dS mismatch")
      end block checks
   end subroutine test_dsv_fd

   subroutine test_mstar_om4(error)
      !! OM4 mstar hand-check: stabilizing term mstar_coef1 *
      !! sqrt(B0/(u*^2 f)), Ekman term c_ek*log(u*/(f*BLD)) capped at
      !! 1.25, max of the two.
      type(error_type), allocatable, intent(out) :: error
      real(wp), parameter :: USTAR = 0.01_wp, ABSF = 1.0e-4_wp, BLD = 50.0_wp
      real(wp) :: mstar, expected_n, expected_s, b0
      checks: block
         ! Neutral: B0 = 0 -> Ekman term only.
         call epbl_find_mstar(EPBL_MSTAR_OM4, 1.2_wp, -1.0_wp, 0.3_wp, &
                              0.085_wp, 0.0_wp, &
                              0.275_wp, 8.0_wp, -5.0_wp, 0.2_wp, 0.4_wp, &
                              0.0_wp, USTAR, BLD, ABSF, mstar)
         expected_n = min(1.25_wp, 0.085_wp*log(USTAR/(ABSF*BLD)))
         call check(error, abs(mstar - expected_n) < 1.0e-14_wp, &
                    "OM4 neutral mstar mismatch")
         if (allocated(error)) exit checks
         ! Strongly stabilizing: mstar_S dominates.
         b0 = 1.0e-6_wp
         call epbl_find_mstar(EPBL_MSTAR_OM4, 1.2_wp, -1.0_wp, 0.3_wp, &
                              0.085_wp, 0.0_wp, &
                              0.275_wp, 8.0_wp, -5.0_wp, 0.2_wp, 0.4_wp, &
                              b0, USTAR, BLD, ABSF, mstar)
         expected_s = 0.3_wp*sqrt(b0/(USTAR**2*ABSF))
         call check(error, abs(mstar - max(expected_s, expected_n)) < 1.0e-14_wp, &
                    "OM4 stabilizing mstar mismatch")
         if (allocated(error)) exit checks
         ! Constant scheme ignores everything.
         call epbl_find_mstar(EPBL_MSTAR_CONSTANT, 1.2_wp, -1.0_wp, 0.3_wp, &
                              0.085_wp, 0.0_wp, &
                              0.275_wp, 8.0_wp, -5.0_wp, 0.2_wp, 0.4_wp, &
                              b0, USTAR, BLD, ABSF, mstar)
         call check(error, abs(mstar - 1.2_wp) < 1.0e-15_wp, &
                    "constant mstar mismatch")
      end block checks
   end subroutine test_mstar_om4

   subroutine test_ctke_seed(error)
      !! Pure cooling, no wind, first call on a stable column: the
      !! convective ledger term must equal nstar * (-0.5 rho0 h_sfc
      !! B0) with B0 = g alpha q_T / rho0 (linear EOS) — verifies the
      !! surface-seed energetics + sign conventions end to end.  Also
      !! checks the boundary interfaces stay at zero.
      type(error_type), allocatable, intent(out) :: error
      type(hgrid_t) :: grid
      type(multilayer_state_t) :: ms
      type(ocean_epbl_t) :: epbl
      type(ocean_surface_stress_t) :: ss
      type(ocean_surface_flux_t) :: sf
      type(ocean_vdiff_t) :: vd
      integer, parameter :: NZ = 8
      real(wp), parameter :: DZ = 5.0_wp, DT = 1800.0_wp
      real(wp), parameter :: Q_HEAT = -200.0_wp
      real(wp) :: mld_series(1), t_series(1)
      real(wp) :: q_t_kin, b0, ctke_expected, conv_expected
      integer :: i_probe, j_probe
      checks: block
         call make_grid(grid, 6, 4)
         ms%nz_ml = NZ
         call ms%init(grid)
         call setup_epbl(epbl, grid, NZ)
         call ss%init(grid)
         call ss%set_wind_stress_const(0.0_wp, 0.0_wp)
         call sf%init(grid)
         call sf%set_surface_flux_const(Q_HEAT, 0.0_wp)
         call vd%init(grid, nz_ml=NZ)
         call setup_stratified_T(ms, NZ, DZ, 15.0_wp, 0.05_wp)

         ! Single step.  NOTE: the flux is applied to T BEFORE EPBL
         ! (production ordering), so the surface layer is already
         ! cooled by dt*q_T when the seed is computed — the seed
         ! itself describes that just-applied flux.
         call run_epbl_steps(grid, ms, epbl, ss, sf, vd, DT, 1, &
                             mld_series, t_series, sample_every=1)

         i_probe = grid%nx_total/2
         j_probe = grid%ny_total/2
         q_t_kin = Q_HEAT/(RHO0*SEAWATER_CP)
         b0 = GRAVITY*ALPHA_LIN*q_t_kin/RHO0
         ctke_expected = -0.5_wp*RHO0*DZ*b0*DT
         conv_expected = epbl%nstar*ctke_expected/DT

         call check(error, ctke_expected > 0.0_wp, &
                    "test setup: cooling must release PE")
         if (allocated(error)) exit checks
         call check(error, abs(epbl%tke_conv(i_probe, j_probe) - conv_expected) &
                    < 1.0e-10_wp*conv_expected, &
                    "convective seed != nstar*(-0.5 rho0 h B0)")
         if (allocated(error)) exit checks
         call check(error, abs(epbl%kd_int(i_probe, j_probe, 1)) < 1.0e-30_wp, &
                    "bed interface kd must be zero")
         if (allocated(error)) exit checks
         call check(error, abs(epbl%kd_int(i_probe, j_probe, NZ + 1)) < 1.0e-30_wp, &
                    "surface interface kd must be zero")
      end block checks
      call vd%destroy(); call sf%destroy(); call ss%destroy()
      call epbl%destroy(); call ms%destroy()
   end subroutine test_ctke_seed

   subroutine test_wind_deepening(error)
      !! Kraus-Turner limit: f = 0 (no TKE decay, no Ekman rolloff),
      !! linear N² = 1e-4, u* = 0.01 m/s, no surface buoyancy flux,
      !! constant mstar.  Energetics: mixing a linear profile to
      !! depth D costs rho0 N² D³/12, wind supplies mstar rho0 u*³ t,
      !! so D(t) = (12 mstar u*³ t / N²)^(1/3).  The transition-layer
      !! shape function pushes the realized MLD above the ideal value
      !! (prototype: 1.33x) — assert the exponent tightly and the
      !! prefactor within a generous band.
      type(error_type), allocatable, intent(out) :: error
      type(hgrid_t) :: grid
      type(multilayer_state_t) :: ms
      type(ocean_epbl_t) :: epbl
      type(ocean_surface_stress_t) :: ss
      type(ocean_surface_flux_t) :: sf
      type(ocean_vdiff_t) :: vd
      integer, parameter :: NZ = 100
      real(wp), parameter :: DZ = 3.0_wp, DT = 1800.0_wp
      real(wp), parameter :: USTAR = 0.01_wp
      real(wp), parameter :: N2 = 1.0e-4_wp
      integer, parameter :: N_STEPS = 240          ! 5 days
      integer, parameter :: N_SAMPLE = 20
      real(wp) :: mld_series(N_SAMPLE), t_series(N_SAMPLE)
      real(wp) :: dT_dz, d_analytic, slope, ratio
      integer :: m
      logical :: monotone
      checks: block
         call make_grid(grid, 6, 4)
         ms%nz_ml = NZ
         call ms%init(grid)
         call setup_epbl(epbl, grid, NZ)
         call ss%init(grid)
         call ss%set_wind_stress_const(RHO0*USTAR**2, 0.0_wp)
         call sf%init(grid)            ! zero fluxes
         call vd%init(grid, nz_ml=NZ)
         dT_dz = N2*RHO0/(GRAVITY*ALPHA_LIN)
         call setup_stratified_T(ms, NZ, DZ, 15.0_wp, dT_dz)

         call run_epbl_steps(grid, ms, epbl, ss, sf, vd, DT, N_STEPS, &
                             mld_series, t_series, sample_every=N_STEPS/N_SAMPLE)

         monotone = .true.
         do m = 2, N_SAMPLE
            if (mld_series(m) < mld_series(m - 1) - 1.0e-9_wp) monotone = .false.
         end do
         call check(error, monotone, "wind-driven MLD must grow monotonically")
         if (allocated(error)) exit checks

         ! Exponent over the second half (early samples carry the
         ! half-depth first-guess transient).
         call fit_loglog_slope(t_series(N_SAMPLE/2:), mld_series(N_SAMPLE/2:), &
                               N_SAMPLE - N_SAMPLE/2 + 1, slope)
         call check(error, slope > 0.20_wp .and. slope < 0.47_wp, &
                    "Kraus-Turner exponent outside [0.20, 0.47]")
         if (allocated(error)) exit checks

         d_analytic = (12.0_wp*epbl%mstar_const*USTAR**3* &
                       t_series(N_SAMPLE)/N2)**(1.0_wp/3.0_wp)
         ratio = mld_series(N_SAMPLE)/d_analytic
         call check(error, ratio > 0.9_wp .and. ratio < 1.8_wp, &
                    "Kraus-Turner prefactor outside [0.9, 1.8] of analytic")
      end block checks
      call vd%destroy(); call sf%destroy(); call ss%destroy()
      call epbl%destroy(); call ms%destroy()
   end subroutine test_wind_deepening

   subroutine test_budget_closure(error)
      !! Combined wind + cooling on a rotating column: the column TKE
      !! ledger must close to round-off every step:
      !!   wind + conv + forcing - mixing - mech_decay - conv_decay = 0
      !! (forcing <= 0; the leftover stocks at the bed are folded into
      !! the decay terms).  This validates the whole bookkeeping
      !! incl. the proportional-drain and rotation-reduction paths.
      !!
      !! (PR-21) Extended with penetrating shortwave via the `q_sw` source
      !! (`q_sw > 0` while `Q_heat < 0` — sunny-but-net-cooling), so the
      !! ledger carries `d_forcing`/`d_mixing`/`d_cdecay` increments from
      !! the sub-surface SW TKE drain (steps 2 + 3b of epbl_column_kernel)
      !! in addition to the surface seed.  The closure must still hold to
      !! round-off — every drain branch posts its ledger increment.
      type(error_type), allocatable, intent(out) :: error
      type(hgrid_t) :: grid
      type(multilayer_state_t) :: ms
      type(ocean_epbl_t) :: epbl
      type(ocean_surface_stress_t) :: ss
      type(ocean_surface_flux_t) :: sf
      type(ocean_vdiff_t) :: vd
      integer, parameter :: NZ = 40
      real(wp), parameter :: DZ = 5.0_wp, DT = 1800.0_wp
      integer, parameter :: N_STEPS = 12
      real(wp) :: mld_series(N_STEPS), t_series(N_STEPS)
      real(wp) :: residual, scale_ref
      integer :: i, j
      checks: block
         call make_grid(grid, 6, 4)
         ms%nz_ml = NZ
         call ms%init(grid)
         call setup_epbl(epbl, grid, NZ)
         call epbl%set_f_centre(grid, 1.0e-4_wp, 0.0_wp, 0.0_wp)
         call ss%init(grid)
         call ss%set_wind_stress_const(0.1_wp, 0.0_wp)
         call sf%init(grid)
         call sf%set_surface_flux_const(-300.0_wp, 0.0_wp)
         ! (PR-21) penetrating shortwave via q_sw (>0) while Q_heat<0:
         ! I0>0 ⇒ ctke_sw<0 ⇒ the sub-surface TKE drain (step 3b) fires,
         ! posting into d_forcing / d_mixing / d_cdecay.
         call sf%set_components(grid, .true.)
         sf%q_sw = 250.0_wp
         call sf%set_sw_penetration(1.0_wp, 0.58_wp, 0.35_wp, 23.0_wp, sw_source="q_sw")
         epbl%epbl_sw_ctke = .true.
         call vd%init(grid, nz_ml=NZ)
         call setup_stratified_T(ms, NZ, DZ, 15.0_wp, 0.0527_wp)

         ! The budget arrays hold the LAST step's ledger; running
         ! several steps exercises seeds, drains and decays across a
         ! deepening, then we assert the final step's closure at
         ! every interior column.
         call run_epbl_steps(grid, ms, epbl, ss, sf, vd, DT, N_STEPS, &
                             mld_series, t_series, sample_every=1)

         do j = NGHOST + 1, grid%ny_total - NGHOST
            do i = NGHOST + 1, grid%nx_total - NGHOST
               residual = epbl%tke_wind(i, j) + epbl%tke_conv(i, j) + &
                          epbl%tke_forcing(i, j) - epbl%tke_mixing(i, j) - &
                          epbl%tke_mech_decay(i, j) - epbl%tke_conv_decay(i, j)
               scale_ref = epbl%tke_wind(i, j) + epbl%tke_conv(i, j) + &
                           abs(epbl%tke_forcing(i, j)) + 1.0e-30_wp
               call check(error, abs(residual) < 1.0e-9_wp*scale_ref, &
                          "TKE budget ledger does not close")
               if (allocated(error)) exit checks
            end do
         end do
         ! Sanity: with wind + cooling both source terms are active.
         i = grid%nx_total/2
         j = grid%ny_total/2
         call check(error, epbl%tke_wind(i, j) > 0.0_wp, "wind term inactive")
         if (allocated(error)) exit checks
         call check(error, epbl%tke_conv(i, j) > 0.0_wp, "conv term inactive")
      end block checks
      call vd%destroy(); call sf%destroy(); call ss%destroy()
      call epbl%destroy(); call ms%destroy()
   end subroutine test_budget_closure

   subroutine test_stable_shoals(error)
      !! Strong stabilizing (warming) surface flux + the same wind
      !! must produce a clearly shallower MLD than the neutral run
      !! (the warming both drains TKE at the seed and stiffens the
      !! near-surface stratification).
      type(error_type), allocatable, intent(out) :: error
      type(hgrid_t) :: grid
      type(multilayer_state_t) :: ms
      type(ocean_epbl_t) :: epbl_neutral, epbl_stable
      type(ocean_surface_stress_t) :: ss
      type(ocean_surface_flux_t) :: sf_neutral, sf_stable
      type(ocean_vdiff_t) :: vd
      integer, parameter :: NZ = 60
      real(wp), parameter :: DZ = 3.0_wp, DT = 1800.0_wp
      integer, parameter :: N_STEPS = 96           ! 2 days
      real(wp) :: mld_a(4), mld_b(4), t_s(4), dT_dz
      integer :: i_probe, j_probe
      checks: block
         call make_grid(grid, 6, 4)
         ms%nz_ml = NZ
         call ms%init(grid)
         call ss%init(grid)
         call ss%set_wind_stress_const(RHO0*0.01_wp**2, 0.0_wp)
         call sf_neutral%init(grid)
         call sf_stable%init(grid)
         call sf_stable%set_surface_flux_const(500.0_wp, 0.0_wp)
         call vd%init(grid, nz_ml=NZ)
         dT_dz = 1.0e-4_wp*RHO0/(GRAVITY*ALPHA_LIN)
         i_probe = grid%nx_total/2
         j_probe = grid%ny_total/2

         call setup_epbl(epbl_neutral, grid, NZ)
         call setup_stratified_T(ms, NZ, DZ, 15.0_wp, dT_dz)
         call run_epbl_steps(grid, ms, epbl_neutral, ss, sf_neutral, vd, DT, &
                             N_STEPS, mld_a, t_s, sample_every=N_STEPS/4)

         call setup_epbl(epbl_stable, grid, NZ)
         call setup_stratified_T(ms, NZ, DZ, 15.0_wp, dT_dz)
         call run_epbl_steps(grid, ms, epbl_stable, ss, sf_stable, vd, DT, &
                             N_STEPS, mld_b, t_s, sample_every=N_STEPS/4)

         call check(error, mld_b(4) < 0.95_wp*mld_a(4), &
                    "stabilizing flux failed to shoal the MLD")
      end block checks
      call vd%destroy(); call sf_stable%destroy(); call sf_neutral%destroy()
      call ss%destroy(); call epbl_stable%destroy(); call epbl_neutral%destroy()
      call ms%destroy()
   end subroutine test_stable_shoals

   subroutine test_convective(error)
      !! Pure convection with the production ordering (cooling
      !! applied to T each step BEFORE EPBL): the deepening must
      !! track the encroachment scale D_enc = sqrt(2 |B0| t)/N.
      !! Discrete-layer + transition effects spread the result, so
      !! the band is generous; tighten during validation tuning.
      type(error_type), allocatable, intent(out) :: error
      type(hgrid_t) :: grid
      type(multilayer_state_t) :: ms
      type(ocean_epbl_t) :: epbl
      type(ocean_surface_stress_t) :: ss
      type(ocean_surface_flux_t) :: sf
      type(ocean_vdiff_t) :: vd
      integer, parameter :: NZ = 60
      real(wp), parameter :: DZ = 2.5_wp, DT = 1800.0_wp
      real(wp), parameter :: Q_HEAT = -200.0_wp
      real(wp), parameter :: N2 = 1.0e-4_wp
      integer, parameter :: N_STEPS = 96           ! 2 days
      integer, parameter :: N_SAMPLE = 8
      real(wp) :: mld_series(N_SAMPLE), t_series(N_SAMPLE)
      real(wp) :: dT_dz, q_t_kin, b0_mag, d_enc, ratio
      integer :: m, i_probe, j_probe
      logical :: monotone
      checks: block
         call make_grid(grid, 6, 4)
         ms%nz_ml = NZ
         call ms%init(grid)
         call setup_epbl(epbl, grid, NZ)
         call ss%init(grid)
         call ss%set_wind_stress_const(0.0_wp, 0.0_wp)
         call sf%init(grid)
         call sf%set_surface_flux_const(Q_HEAT, 0.0_wp)
         call vd%init(grid, nz_ml=NZ)
         dT_dz = N2*RHO0/(GRAVITY*ALPHA_LIN)
         call setup_stratified_T(ms, NZ, DZ, 15.0_wp, dT_dz)

         call run_epbl_steps(grid, ms, epbl, ss, sf, vd, DT, N_STEPS, &
                             mld_series, t_series, sample_every=N_STEPS/N_SAMPLE)

         monotone = .true.
         do m = 2, N_SAMPLE
            if (mld_series(m) < mld_series(m - 1) - 1.0e-9_wp) monotone = .false.
         end do
         call check(error, monotone, "convective MLD must grow monotonically")
         if (allocated(error)) exit checks

         q_t_kin = Q_HEAT/(RHO0*SEAWATER_CP)
         b0_mag = abs(GRAVITY*ALPHA_LIN*q_t_kin/RHO0)
         d_enc = sqrt(2.0_wp*b0_mag*t_series(N_SAMPLE))/sqrt(N2)
         ratio = mld_series(N_SAMPLE)/d_enc
         call check(error, ratio > 0.5_wp .and. ratio < 1.4_wp, &
                    "convective MLD outside [0.5, 1.4] of encroachment")
         if (allocated(error)) exit checks

         ! Diffusivity must be active inside the convective layer.
         i_probe = grid%nx_total/2
         j_probe = grid%ny_total/2
         call check(error, epbl%kd_int(i_probe, j_probe, NZ) > 1.0e-6_wp, &
                    "no convective diffusivity at the near-surface interface")
      end block checks
      call vd%destroy(); call sf%destroy(); call ss%destroy()
      call epbl%destroy(); call ms%destroy()
   end subroutine test_convective

