   end subroutine test_bounds_pinned

   subroutine test_bounds_oracle(error)
      !! Every `kcatbound` (-1..3, ncat 5) and the delta-function variant against Icepack,
      !! 1e-14 relative.
      type(error_type), allocatable, intent(out) :: error
      real(wp) :: h(0:5), worst
      integer :: ic, st, nn
      character(len=48) :: lab

      worst = 0.0_wp
      do ic = 1, 6
         call itd_category_bounds(BND_CFG(1, ic), BND_CFG(2, ic), 5, 0.01_wp, h, st)
         nn = 5
         if (BND_CFG(1, ic) == -1) then
            ! upstream defines two edges only; the port also refuses ncat /= 1
            call check(error, st, ITD_BOUNDS_BAD_NCAT, "kcatbound=-1 at ncat=5 refused")
            if (allocated(error)) return
            nn = 1
         else
            call check(error, st, ITD_BOUNDS_OK, "status")
            if (allocated(error)) return
         end if
         write (lab, '(a,i0,a,i0)') "oracle kcatbound=", BND_CFG(1, ic), " kitd=", BND_CFG(2, ic)
         call ice_golden_check(error, trim(lab), h(0:nn), BND_REF(0:nn, ic), 1.0e-14_wp, 0.0_wp)
         if (allocated(error)) return
         if (.not. (maxval(abs(h(0:nn) - BND_REF(0:nn, ic))) <= worst)) worst = maxval(abs(h(0:nn) - BND_REF(0:nn, ic)))
      end do
      ! 1e-14 relative (a few ulp): safe_tanh vs libm tanh in the oracle
      call check(error, worst <= 1.0e-13_wp, "worst absolute difference vs oracle")
   end subroutine test_bounds_oracle

   subroutine test_bounds_closed_forms(error)
      !! Formulas written out in the test for every legal ncat: kcatbound 1, 2, 3,
      !! single category, top edge 999.9 under kitd 1, monotone edges everywhere.
      type(error_type), allocatable, intent(out) :: error
      real(wp) :: h(0:ICE_NCAT_MAX), e
      integer :: ncat, n, st, kc, kitd
      real(wp), parameter :: wmo5(5) = [0.3_wp, 0.7_wp, 1.2_wp, 2.0_wp, 999.9_wp]
      real(wp), parameter :: wmo6(6) = [0.15_wp, 0.3_wp, 0.7_wp, 1.2_wp, 2.0_wp, 999.9_wp]
      real(wp), parameter :: wmo7(7) = [0.1_wp, 0.15_wp, 0.3_wp, 0.7_wp, 1.2_wp, 2.0_wp, 999.9_wp]
      real(wp) :: rn, rnc, b3

      do ncat = 1, ICE_NCAT_MAX
         rnc = real(ncat, wp)
         ! kcatbound 1: H(n) = n*(3/ncat + (n-1)*0.5/ncat); only the top edge is overwritten
         call itd_category_bounds(1, 1, ncat, 0.01_wp, h(0:ncat), st)
         call check(error, st, ITD_BOUNDS_OK, "kcatbound=1 status")
         if (allocated(error)) return
         do n = 1, ncat - 1
            rn = real(n, wp)
            e = rn*(3.0_wp/rnc + (rn - 1.0_wp)*0.5_wp/rnc)
            if (.not. (abs(h(n) - e) <= 1.0e-14_wp*e)) then
               call test_failed(error, "kcatbound=1 closed form")
               return
            end if
         end do
         call check(error, h(ncat), 999.9_wp, "top edge 999.9")
         if (allocated(error)) return

         ! kcatbound 3: b1*(n + b3*n*(n+1)/(2*ncat*(ncat-1))), b3 = max(ncat*(ncat-1), 60)
         if (ncat > 1) then
            call itd_category_bounds(3, 1, ncat, 0.01_wp, h(0:ncat), st)
            b3 = max(rnc*(rnc - 1.0_wp), 60.0_wp)
            do n = 1, ncat - 1
               rn = real(n, wp)
               e = 0.1_wp*(rn + b3*rn*(rn + 1.0_wp)/(2.0_wp*rnc*(rnc - 1.0_wp)))
               if (.not. (abs(h(n) - e) <= 1.0e-13_wp*e)) then
                  call test_failed(error, "kcatbound=3 closed form")
                  return
               end if
            end do
         end if

         ! WMO: tabulated classes for 5, 6, 7 only
         call itd_category_bounds(2, 1, ncat, 0.01_wp, h(0:ncat), st)
         select case (ncat)
         case (5)
            call ice_golden_check(error, "wmo5", h(1:5), wmo5, 0.0_wp, 0.0_wp)
         case (6)
            call ice_golden_check(error, "wmo6", h(1:6), wmo6, 0.0_wp, 0.0_wp)
         case (7)
            call ice_golden_check(error, "wmo7", h(1:7), wmo7, 0.0_wp, 0.0_wp)
         case default
            call check(error, st, ITD_BOUNDS_BAD_NCAT, "wmo refuses ncat not in 5..7")
         end select
         if (allocated(error)) return
      end do

      ! single category, kcatbound -1: edges 0 and (kitd=1) the top value, (kitd=0) 100 m
      call itd_category_bounds(-1, 0, 1, 0.01_wp, h(0:1), st)
      call ice_golden_check(error, "kcatbound=-1 kitd=0", h(0:1), [0.0_wp, 100.0_wp], 0.0_wp, 0.0_wp)
      if (allocated(error)) return
      call itd_category_bounds(-1, 1, 1, 0.01_wp, h(0:1), st)
      call check(error, st, ITD_BOUNDS_OK, "kcatbound=-1 ncat=1 accepted")
      if (allocated(error)) return
      call ice_golden_check(error, "kcatbound=-1 kitd=1", h(0:1), [0.0_wp, 999.9_wp], 0.0_wp, 0.0_wp)
      if (allocated(error)) return

      ! strictly increasing for every accepted combination; lower edge 0 (kitd 1) / hi_min (kitd 0, kc 0)
      do kitd = 0, 1
         do kc = 0, 3
            do ncat = 1, ICE_NCAT_MAX
               call itd_category_bounds(kc, kitd, ncat, 0.01_wp, h(0:ncat), st)
               if (st /= ITD_BOUNDS_OK) cycle
               do n = 1, ncat
                  if (.not. (h(n) > h(n - 1))) then
                     call test_failed(error, "bounds strictly increasing")
                     return
                  end if
               end do
               e = 0.0_wp
               if (kitd == 0 .and. kc == 0) e = 0.01_wp
               if (h(0) /= e) then
                  call test_failed(error, "lower edge")
                  return
               end if
            end do
         end do
      end do
   end subroutine test_bounds_closed_forms

