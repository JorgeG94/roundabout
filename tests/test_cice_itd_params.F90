   subroutine test_bounds_pinned(error)
      !! The OM3 bounds (kcatbound 0, ncat 5, linear remap), pinned to 1e-12.
      type(error_type), allocatable, intent(out) :: error
      real(wp) :: h(0:5)
      integer :: st
      real(wp), parameter :: ref(6) = [0.0_wp, 0.6445072168194258_wp, 1.3914334975763036_wp, &
                                       2.4701793819598885_wp, 4.567287918850491_wp, 999.9_wp]

