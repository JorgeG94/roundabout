   subroutine test_device(error)
      !! `itd_fit_line`, `itd_aggregate_area` and `itd_aggregate` inside `do concurrent`
      !! over columns on the offload build, against the host evaluation (1e-13 / 1e-12; FMA
      !! is on there).  Every array the kernel touches is mapped (`mem:separate`); the column
      !! sections are contiguous and the tracer array has leading extent `ICE_NTRCR_MAX` with
      !! 10 active.  The last two columns exercise the non-finite paths under the optimiser:
      !! column `ncol-1` has a degenerate fit (mean on the lower bound: `g = 0`, finite) and a
      !! clean aggregate, column `ncol` a NaN mean / NaN area (outputs non-finite, error bit).
      type(error_type), allocatable, intent(out) :: error
      integer, parameter :: ncol = 600, ncat = 5, ldt = ICE_NTRCR_MAX
      real(wp), parameter :: HB1 = 0.6445072168194258_wp, HB2 = 1.3914334975763036_wp
      real(wp), allocatable :: aicen(:, :), vicen(:, :), vsnon(:, :), trcrn(:, :, :)
      real(wp), allocatable :: aice(:), vice(:), vsno(:), aice0(:), trcr(:, :), g(:, :)
      real(wp), allocatable :: haice(:), hvice(:), hvsno(:), haice0(:), htrcr(:, :), hg(:, :)
      real(wp), allocatable :: hmean(:), fa(:)
      integer(int32), allocatable :: ierr(:), hierr(:)
      real(wp) :: tmp(10), col10(10, ncat)
      integer :: c

      allocate (aicen(ncat, ncol), vicen(ncat, ncol), vsnon(ncat, ncol), trcrn(ldt, ncat, ncol))
      allocate (aice(ncol), vice(ncol), vsno(ncol), aice0(ncol), trcr(ldt, ncol), g(4, ncol))
      allocate (haice(ncol), hvice(ncol), hvsno(ncol), haice0(ncol), htrcr(ldt, ncol), hg(4, ncol))
      allocate (hmean(ncol), fa(ncol), ierr(ncol), hierr(ncol))
      trcrn = 0.0_wp
      do c = 1, ncol
         call gen_col(mod(c - 1, 31), aicen(:, c), vicen(:, c), vsnon(:, c), col10)
         trcrn(1:10, :, c) = col10
         hmean(c) = HB1 + 0.05_wp + 0.1_wp*real(mod(c, 8), wp)
         fa(c) = aicen(2, c)
      end do
      hmean(ncol - 1) = HB1
      fa(ncol - 1) = 0.3_wp
      hmean(ncol) = QNAN
      fa(ncol) = 0.3_wp
      aicen(3, ncol) = QNAN
      ierr = 0_int32
      hierr = 0_int32
      trcr = 0.0_wp
      htrcr = 0.0_wp

      !$acc enter data copyin(aicen, vicen, vsnon, trcrn, hmean, fa, ierr, trcr) create(aice, vice, vsno, aice0, g)
      do concurrent(c=1:ncol)
         call itd_aggregate(ncat, ldt, 4, 1, aicen(:, c), vicen(:, c), vsnon(:, c), trcrn(:, :, c), &
                            -1.86_wp, PUNY, aice(c), vice(c), vsno(c), aice0(c), trcr(:, c), ierr(c))
      end do
      do concurrent(c=1:ncol)
         call itd_fit_line(fa(c), hmean(c), HB1, HB2, PUNY, g(1, c), g(2, c), g(3, c), g(4, c))
      end do
      !$acc update self(aice, vice, vsno, aice0, trcr, g, ierr)
      !$acc exit data delete(aicen, vicen, vsnon, trcrn, hmean, fa, ierr, trcr, aice, vice, vsno, aice0, g)

      do c = 1, ncol
         call itd_aggregate(ncat, ldt, 4, 1, aicen(:, c), vicen(:, c), vsnon(:, c), trcrn(:, :, c), &
                            -1.86_wp, PUNY, haice(c), hvice(c), hvsno(c), haice0(c), htrcr(:, c), hierr(c))
         call itd_fit_line(fa(c), hmean(c), HB1, HB2, PUNY, hg(1, c), hg(2, c), hg(3, c), hg(4, c))
      end do
      do c = 1, ncol - 1
         tmp = trcr(1:10, c)
         call ice_golden_check(error, "device aggregate tracers", tmp, htrcr(1:10, c), 1.0e-13_wp, 1.0e-13_wp)
         if (allocated(error)) return
         call ice_golden_check(error, "device aggregate totals", [aice(c), vice(c), vsno(c), aice0(c)], &
                               [haice(c), hvice(c), hvsno(c), haice0(c)], 1.0e-13_wp, 1.0e-13_wp)
         if (allocated(error)) return
         call ice_golden_check(error, "device fit_line", g(:, c), hg(:, c), 1.0e-12_wp, 1.0e-12_wp)
         if (allocated(error)) return
         call check(error, ierr(c), 0_int32, "device error word clean")
         if (allocated(error)) return
      end do
      ! degenerate fit: finite zeros on host and device
      call ice_golden_check(error, "device degenerate fit", g(:, ncol - 1), [0.0_wp, 0.0_wp, HB1, HB1], 0.0_wp, 1.0e-15_wp)
      if (allocated(error)) return
      ! NaN column: non-finite outputs, error bit, on host and device
      if (any([(ieee_is_finite(g(c, ncol)), c=1, 4)]) .or. any([(ieee_is_finite(hg(c, ncol)), c=1, 4)])) then
         call test_failed(error, "NaN mean gives non-finite fit on host and device")
         return
      end if
      if (ieee_is_finite(aice(ncol)) .or. ieee_is_finite(trcr(1, ncol)) .or. iand(ierr(ncol), ICE_ERR_NONFINITE) == 0_int32 &
          .or. iand(hierr(ncol), ICE_ERR_NONFINITE) == 0_int32) then
         call test_failed(error, "NaN area gives non-finite aggregate and the error bit")
      end if
   end subroutine test_device

