   subroutine gen_col(row, aicen, vicen, vsnon, trcrn)
      !! The oracle's column recipe (5 categories, ~25 % empty, row 30 entirely empty).
      !! Tracers: 1 Tsfc, 2:5 qice, 6 qsno, 7:10 sice.  Draw order is part of the contract.
      integer, intent(in) :: row
      real(wp), intent(out) :: aicen(5), vicen(5), vsnon(5), trcrn(10, 5)
      integer(int64) :: st
      integer :: n, k
      real(wp) :: u1, u2, u3, u4, u5

      st = lcg_next(int(row, int64)*7919_int64 + 11_int64)
      do n = 1, 5
         st = lcg_next(st); u1 = lcg_unit(st)
         st = lcg_next(st); u2 = lcg_unit(st)
         st = lcg_next(st); u3 = lcg_unit(st)
         st = lcg_next(st); u4 = lcg_unit(st)
         st = lcg_next(st); u5 = lcg_unit(st)
         aicen(n) = 0.02_wp + 0.2_wp*u2
         vicen(n) = aicen(n)*(0.1_wp + 3.0_wp*u3)
         vsnon(n) = 0.0_wp
         if (u4 >= 0.3_wp) vsnon(n) = aicen(n)*0.4_wp*u5
         st = lcg_next(st); trcrn(1, n) = -30.0_wp*lcg_unit(st)
         do k = 2, 5
            st = lcg_next(st); trcrn(k, n) = -4.0e8_wp + 3.0e8_wp*lcg_unit(st)
         end do
         st = lcg_next(st); trcrn(6, n) = -1.2e8_wp + 0.3e8_wp*lcg_unit(st)
         do k = 7, 10
            st = lcg_next(st); trcrn(k, n) = 6.0_wp*lcg_unit(st)
         end do
         if (u1 < 0.25_wp .or. row == 30) then
            aicen(n) = 0.0_wp; vicen(n) = 0.0_wp; vsnon(n) = 0.0_wp
         end if
      end do
   end subroutine gen_col

   subroutine test_agg_oracle(error)
      !! 31 oracle columns (nilyr 4, nslyr 1, Tf = -1.86).  Inputs are regenerated by the
      !! oracle's LCG recipe; a per-row input checksum (relative 1e-12) fails with a clear
      !! message if the regeneration ever drifts.  Outputs are compared EXACTLY on CPU builds
      !! (same additions in the same order as upstream, measured bit-identical) and to 1e-12
      !! on the offload build (FMA contraction in host code compiled with `-fast`).
      !! `itd_aggregate_area` is also checked against the aggregate.
      type(error_type), allocatable, intent(out) :: error
      real(wp) :: aicen(5), vicen(5), vsnon(5), trcrn(10, 5)
      real(wp) :: aice, vice, vsno, aice0, trcr(10), a2, a02, got(14), chk, tol
      integer :: r, n, k
      integer(int32) :: ierr
      character(len=80) :: lab

#ifdef RDB_GPU_OFFLOAD
      tol = 1.0e-12_wp
#else
      tol = 0.0_wp
#endif
      ierr = 0_int32
      do r = 0, NAGG - 1
         call gen_col(r, aicen, vicen, vsnon, trcrn)
         chk = 0.0_wp
         do n = 1, 5
            chk = chk + aicen(n)*real(n, wp) + vicen(n)*real(2*n, wp) + vsnon(n)*real(3*n, wp)
            do k = 1, 10
               chk = chk + trcrn(k, n)*real(k + 10*n, wp)*1.0e-8_wp
            end do
         end do
         write (lab, '(a,i0,a)') "oracle input checksum row ", r, ": gen_col drifted from the oracle recipe"
         if (.not. (abs(chk - AGG_REF(1, r + 1)) <= 1.0e-12_wp*abs(AGG_REF(1, r + 1)))) then
            call test_failed(error, trim(lab))
            return
         end if
         call itd_aggregate(5, 10, 4, 1, aicen, vicen, vsnon, trcrn, -1.86_wp, PUNY, &
                            aice, vice, vsno, aice0, trcr, ierr)
         got = [aice, vice, vsno, aice0, trcr]
         write (lab, '(a,i0)') "aggregate oracle row ", r
         call ice_golden_check(error, trim(lab), got, AGG_REF(2:15, r + 1), tol, tol)
         if (allocated(error)) return
         call itd_aggregate_area(5, aicen, a2, a02)
         call check(error, a2 == aice .and. a02 == aice0, trim(lab)//" aggregate_area")
         if (allocated(error)) return
      end do
      call check(error, ierr, 0_int32, "no error bit on finite oracle columns")
   end subroutine test_agg_oracle

   subroutine test_agg_brute(error)
      !! Random columns for ncat 1..8 and nilyr 1, 4, 8: brute-force upstream form
      !! (`trcr_base` one-hot table, extensive sums, "last positive divisor" division)
      !! against the port, 1e-14 relative; extensive totals reproduce.
      type(error_type), allocatable, intent(out) :: error
      integer, parameter :: nils(3) = [1, 4, 8]
      real(wp) :: aicen(ICE_NCAT_MAX), vicen(ICE_NCAT_MAX), vsnon(ICE_NCAT_MAX)
      real(wp) :: trcrn(ICE_NTRCR_MAX, ICE_NCAT_MAX)   ! fixed-size per-thread local: ldt = ICE_NTRCR_MAX
      real(wp) :: trcr(ICE_NTRCR_MAX), ref(ICE_NTRCR_MAX)
      integer(int32) :: ierr
      real(wp) :: tolb
      real(wp) :: aice, vice, vsno, aice0, atr, div(3), base(3), tf, ra, rv, rs
      integer :: ncat, il, nilyr, nslyr, ntr, col, n, it, d, k
      integer(int64) :: st

#ifdef RDB_GPU_OFFLOAD
      tolb = 5.0e-12_wp   ! measured 4e-13 on the offload build: host code is FMA-contracted (-fast)
#else
      tolb = 1.0e-14_wp
#endif
      st = lcg_next(424242_int64)
      ierr = 0_int32
      trcrn = 0.0_wp
      nslyr = 1
      tf = -1.7_wp
      do il = 1, 3
         nilyr = nils(il)
         ntr = ice_ntrcr(nilyr, nslyr)
         do ncat = 1, ICE_NCAT_MAX
            do col = 1, 25
               do n = 1, ncat
                  st = lcg_next(st); aicen(n) = lcg_unit(st)/real(ncat, wp)
                  st = lcg_next(st); vicen(n) = aicen(n)*3.0_wp*lcg_unit(st)
                  st = lcg_next(st); vsnon(n) = aicen(n)*0.5_wp*lcg_unit(st)
                  if (mod(col + n, 5) == 0) then
                     aicen(n) = 0.0_wp; vicen(n) = 0.0_wp; vsnon(n) = 0.0_wp
                  end if
                  do it = 1, ntr
                     st = lcg_next(st); trcrn(it, n) = -5.0e8_wp + 6.0e8_wp*lcg_unit(st)
                  end do
               end do
               call itd_aggregate(ncat, ICE_NTRCR_MAX, nilyr, nslyr, aicen, vicen, vsnon, trcrn, tf, PUNY, &
                                  aice, vice, vsno, aice0, trcr, ierr)
               ra = sum(aicen(1:ncat)); rv = sum(vicen(1:ncat)); rs = sum(vsnon(1:ncat))
               if (.not. (abs(aice - ra) <= 1.0e-15_wp*max(ra, 1.0_wp) .and. abs(vice - rv) <= 1.0e-14_wp*max(rv, 1.0_wp) &
                          .and. abs(vsno - rs) <= 1.0e-14_wp*max(rs, 1.0_wp))) then
                  call test_failed(error, "aggregate totals")
                  return
               end if
               if (.not. (abs(aice0 - max(1.0_wp - ra, 0.0_wp)) <= 1.0e-15_wp)) then
                  call test_failed(error, "aice0")
                  return
               end if
               ! upstream formulation: base table, extensive sum, divisor loop
               do it = 1, ntr
                  d = ice_trcr_depend(it, nilyr, nslyr)
                  base = ice_trcr_base(d)
                  atr = 0.0_wp
                  do n = 1, ncat
                     atr = atr + trcrn(it, n)*(base(1)*aicen(n) + base(2)*vicen(n) + base(3)*vsnon(n))
                  end do
                  if (d == 0) then
                     if (ra > PUNY) then
                        ref(it) = atr/ra
                     else
                        ref(it) = 0.0_wp
                        if (it == 1) ref(it) = tf
                     end if
                  else
                     div = [base(1)*ra, base(2)*rv, base(3)*rs]
                     ref(it) = 0.0_wp
                     do k = 1, 3
                        if (div(k) > 0.0_wp) ref(it) = atr/div(k)
                     end do
                  end if
               end do
               call ice_golden_check(error, "aggregate vs brute force", trcr(1:ntr), ref(1:ntr), &
                                     tolb, 0.0_wp)
               if (allocated(error)) return
               if (ierr /= 0_int32) then
                  call test_failed(error, "no error bit on finite columns")
                  return
               end if
            end do
         end do
      end do
   end subroutine test_agg_brute

   subroutine test_agg_edges(error)
      !! Empty column, snow without ice, ice without snow, over-full cell.
      type(error_type), allocatable, intent(out) :: error
      real(wp) :: aicen(3), vicen(3), vsnon(3), trcrn(10, 3), trcr(10)
