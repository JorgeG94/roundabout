   pure function is_garbage(x) result(b)
      !! The documented degenerate-fit blow-up: non-finite or enormous.
      real(wp), intent(in) :: x
      logical :: b
      b = .not. ieee_is_finite(x)
      if (.not. b) b = abs(x) > 1.0e10_wp
   end function is_garbage

   subroutine test_fit_oracle(error)
      !! 38 Icepack rows: categories 1-4 of the OM3 bounds at mean positions -0.1 .. 1.0 of
      !! the category width, plus empty / sub-puny / zero-width / aicen = puny / thick /
      !! mean-left rows.  Where the cut support collapses (mean at a bound, upstream quirk)
      !! only hL, hR and "garbage-or-NaN" g are asserted: the g values there are 1/0-type
      !! round-off noise that an FMA build legitimately changes.
      type(error_type), allocatable, intent(out) :: error
      integer :: r
      real(wp) :: g0, g1, hL, hR, ex(4), got(4), tol
      character(len=40) :: lab
      logical :: degenerate

      do r = 1, NFIT
         call itd_fit_line(FIT_REF(1, r), FIT_REF(2, r), FIT_REF(3, r), FIT_REF(4, r), PUNY, &
                           g0, g1, hL, hR)
         ex = FIT_REF(5:8, r)
         got = [g0, g1, hL, hR]
         write (lab, '(a,i0)') "fit_line oracle row ", r
         degenerate = is_garbage(ex(1)) .or. is_garbage(ex(2))
         if (.not. (ex(4) > ex(3))) then
            ! empty cut support (mean at or outside a bound, or an empty category): upstream's
            ! g is NaN / garbage / a negative-width fit; the port defines g = 0 (answers-neutral)
            call ice_golden_check(error, trim(lab)//" collapsed support", got, [0.0_wp, 0.0_wp, ex(3), ex(4)], &
                                  0.0_wp, 4.0e-16_wp*max(1.0_wp, abs(ex(4))))
         else if (degenerate) then
            call ice_golden_check(error, trim(lab)//" hL,hR", got(3:4), ex(3:4), 0.0_wp, 4.0e-16_wp*max(1.0_wp, abs(ex(4))))
            if (allocated(error)) return
            call check(error, (g0 == 0.0_wp .or. abs(g0) > 1.0e10_wp) .and. (g1 == 0.0_wp .or. abs(g1) > 1.0e10_wp), &
                       trim(lab)//" degenerate g: exactly 0 (support collapsed) or the upstream blow-up, never NaN")
         else
#ifdef RDB_GPU_OFFLOAD
            tol = 1.0e-12_wp   ! FMA contraction in host code compiled with -fast
#else
            tol = 0.0_wp       ! same operations as upstream (one-third multiplied): bitwise
#endif
            call ice_golden_check(error, trim(lab), got, ex, tol, tol)
         end if
         if (allocated(error)) return
      end do
   end subroutine test_fit_oracle

   subroutine test_fit_moments(error)
      !! The fitted line reproduces the category's area and mean thickness exactly:
      !! `int g = aicen`, `int h*g = aicen*hice` over the support, `g >= 0` there, the
      !! support inside the bounds, and the whole category used in the middle third.
      type(error_type), allocatable, intent(out) :: error
      real(wp), parameter :: hb(0:4) = [0.0_wp, 0.6445072168194258_wp, 1.3914334975763036_wp, &
                                        2.4701793819598885_wp, 4.567287918850491_wp]
      integer :: c, i, k, region
      integer(int64) :: st
      real(wp) :: a, hice, hbl, hbr, g0, g1, hL, hR, w, area, mom, u, gl, gr, scale

      st = lcg_next(20261113_int64)
      do c = 1, 4
         hbl = hb(c - 1); hbr = hb(c)
         do region = 1, 3
            do i = 1, 40
               st = lcg_next(st); a = 0.01_wp + 0.9_wp*lcg_unit(st)
               st = lcg_next(st); u = 0.02_wp + 0.96_wp*lcg_unit(st)
               ! position of the mean inside the third `region` (strictly interior, away from a bound)
               hice = hbl + (hbr - hbl)*((real(region - 1, wp) + u)/3.0_wp)
               call itd_fit_line(a, hice, hbl, hbr, PUNY, g0, g1, hL, hR)
               w = hR - hL
               scale = a*(hbr - hbl)
               area = g0*w + g1*w*w/2.0_wp
               mom = hL*area + g0*w*w/2.0_wp + g1*w*w*w/3.0_wp
               if (.not. (abs(area - a) <= 1.0e-12_wp*a)) then
                  call test_failed(error, "fit_line area moment")
                  return
               end if
               if (.not. (abs(mom - a*hice) <= 1.0e-12_wp*a*max(hice, hbr))) then
                  call test_failed(error, "fit_line first moment")
                  return
               end if
               gl = g0
               gr = g0 + g1*w
               if (.not. (gl >= -1.0e-12_wp*a/w .and. gr >= -1.0e-12_wp*a/w)) then
                  call test_failed(error, "fit_line g >= 0 on the support")
                  return
               end if
               if (.not. (hL >= hbl - 1.0e-13_wp .and. hR <= hbr + 1.0e-13_wp .and. hR > hL)) then
                  call test_failed(error, "fit_line support inside the bounds")
                  return
               end if
               if (region == 2) then
                  if (hL /= hbl .or. hR /= hbr) then
                     call test_failed(error, "middle third uses the whole category")
                     return
                  end if
               else if (region == 1) then
                  if (hL /= hbl) then
                     call test_failed(error, "left third keeps hL = hbL")
                     return
                  end if
               else
                  if (hR /= hbr) then
                     call test_failed(error, "right third keeps hR = hbR")
                     return
                  end if
               end if
               ! midpoint-rule quadrature of g (independent of the closed forms above)
               area = 0.0_wp; mom = 0.0_wp
               do k = 1, 2000
                  u = (real(k, wp) - 0.5_wp)/2000.0_wp*w
                  area = area + (g0 + g1*u)*w/2000.0_wp
                  mom = mom + (hL + u)*(g0 + g1*u)*w/2000.0_wp
               end do
               if (.not. (abs(area - a) <= 1.0e-6_wp*a .and. abs(mom - a*hice) <= 1.0e-6_wp*a*hbr)) then
                  call test_failed(error, "fit_line quadrature")
                  return
               end if
            end do
         end do
      end do
   end subroutine test_fit_moments

   subroutine test_fit_edges(error)
      !! Documented edge cases: empty, sub-puny, zero-width, mean at the third boundaries
      !! (continuity of g across the switch), mean at a bound (degenerate, kept from upstream).
      type(error_type), allocatable, intent(out) :: error
      real(wp) :: g0, g1, hL, hR, g0b, g1b, hLb, hRb, h13, h23, eps

      ! empty, below puny, exactly puny (not greater), zero width: all zero
      call itd_fit_line(0.0_wp, 1.0_wp, 0.5_wp, 1.5_wp, PUNY, g0, g1, hL, hR)
      call ice_golden_check(error, "empty", [g0, g1, hL, hR], [0.0_wp, 0.0_wp, 0.0_wp, 0.0_wp], 0.0_wp, 0.0_wp)
      if (allocated(error)) return
      call itd_fit_line(5.0e-12_wp, 1.0_wp, 0.5_wp, 1.5_wp, PUNY, g0, g1, hL, hR)
      call ice_golden_check(error, "sub-puny", [g0, g1, hL, hR], [0.0_wp, 0.0_wp, 0.0_wp, 0.0_wp], 0.0_wp, 0.0_wp)
      if (allocated(error)) return
      call itd_fit_line(PUNY, 1.0_wp, 0.5_wp, 1.5_wp, PUNY, g0, g1, hL, hR)
      call ice_golden_check(error, "aicen == puny", [g0, g1, hL, hR], [0.0_wp, 0.0_wp, 0.0_wp, 0.0_wp], 0.0_wp, 0.0_wp)
      if (allocated(error)) return
      call itd_fit_line(0.3_wp, 1.0_wp, 1.0_wp, 1.0_wp + 5.0e-12_wp, PUNY, g0, g1, hL, hR)
      call ice_golden_check(error, "zero width", [g0, g1, hL, hR], [0.0_wp, 0.0_wp, 0.0_wp, 0.0_wp], 0.0_wp, 0.0_wp)
      if (allocated(error)) return

      ! mean exactly in the middle: uniform distribution g0 = a/w, g1 = 0
      call itd_fit_line(0.4_wp, 1.0_wp, 0.5_wp, 1.5_wp, PUNY, g0, g1, hL, hR)
      call ice_golden_check(error, "uniform", [g0, g1, hL, hR], [0.4_wp, 0.0_wp, 0.5_wp, 1.5_wp], 1.0e-14_wp, 1.0e-15_wp)
      if (allocated(error)) return

      ! mean on a third boundary: the two branches agree (g continuous in hice)
      h13 = (2.0_wp*0.5_wp + 1.5_wp)/3.0_wp
      h23 = (0.5_wp + 2.0_wp*1.5_wp)/3.0_wp
      eps = 1.0e-9_wp
      call itd_fit_line(0.4_wp, h13 - eps, 0.5_wp, 1.5_wp, PUNY, g0, g1, hL, hR)
      call itd_fit_line(0.4_wp, h13 + eps, 0.5_wp, 1.5_wp, PUNY, g0b, g1b, hLb, hRb)
      call ice_golden_check(error, "continuity at h13", [g0, g1, hL, hR], [g0b, g1b, hLb, hRb], 1.0e-6_wp, 1.0e-6_wp)
      if (allocated(error)) return
      call itd_fit_line(0.4_wp, h23 - eps, 0.5_wp, 1.5_wp, PUNY, g0, g1, hL, hR)
      call itd_fit_line(0.4_wp, h23 + eps, 0.5_wp, 1.5_wp, PUNY, g0b, g1b, hLb, hRb)
      call ice_golden_check(error, "continuity at h23", [g0, g1, hL, hR], [g0b, g1b, hLb, hRb], 1.0e-6_wp, 1.0e-6_wp)
      if (allocated(error)) return
      ! mean at the third boundary: a 2/3-width triangle-free linear g, hL = bL, hR = 3*hice - 2*hL = hbR
      call itd_fit_line(0.4_wp, h13, 0.5_wp, 1.5_wp, PUNY, g0, g1, hL, hR)
      call ice_golden_check(error, "mean at h13", [hL, hR], [0.5_wp, 1.5_wp], 0.0_wp, 1.0e-14_wp)
      if (allocated(error)) return

      ! mean at the lower bound: the cut support is empty (upstream: 1/0 gives NaN), outputs are exactly 0 (deliberate, answers-neutral deviation)
      call itd_fit_line(0.4_wp, 0.5_wp, 0.5_wp, 1.5_wp, PUNY, g0, g1, hL, hR)
      call check(error, g0 == 0.0_wp .and. g1 == 0.0_wp, "mean at lower bound: empty support gives g = 0 (upstream NaN)")
      if (allocated(error)) return
      call itd_fit_line(0.4_wp, 1.5_wp, 0.5_wp, 1.5_wp, PUNY, g0, g1, hL, hR)
      call check(error, g0 == 0.0_wp .and. g1 == 0.0_wp, "mean at upper bound: empty support gives g = 0 (upstream NaN)")
   end subroutine test_fit_edges

   subroutine test_fit_nonfinite(error)
      !! A non-finite input never reads as "empty category": every output is non-finite.
      type(error_type), allocatable, intent(out) :: error
      real(wp) :: g0, g1, hL, hR
      integer :: i
      real(wp) :: v(4)

      do i = 1, 5
         v = [0.4_wp, 1.0_wp, 0.5_wp, 1.5_wp]
         select case (i)
         case (1); v(1) = QNAN
         case (2); v(2) = QNAN
         case (3); v(3) = QNAN
         case (4); v(4) = QNAN
         case (5); v(2) = QINF
         end select
         call itd_fit_line(v(1), v(2), v(3), v(4), PUNY, g0, g1, hL, hR)
         if (ieee_is_finite(g0) .or. ieee_is_finite(g1) .or. ieee_is_finite(hL) .or. ieee_is_finite(hR)) then
            call test_failed(error, "fit_line propagates non-finite input")
            return
         end if
      end do
   end subroutine test_fit_nonfinite

