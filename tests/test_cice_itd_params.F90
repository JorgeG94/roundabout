                            1.0e-14_wp, 0.0_wp)
      if (allocated(error)) return

      ! ice with no snow: qsno = 0 (not NaN), over-full cell: aice0 clamps at 0
      aicen = [0.7_wp, 0.5_wp, 0.0_wp]; vicen = [0.7_wp, 1.0_wp, 0.0_wp]; vsnon = 0.0_wp
      trcrn(:, 1) = [-1.0_wp, -1.0e8_wp, -1.0e8_wp, -1.0e8_wp, -1.0e8_wp, -1.0e8_wp, 4.0_wp, 4.0_wp, 4.0_wp, 4.0_wp]
      trcrn(:, 2) = [-3.0_wp, -3.0e8_wp, -3.0e8_wp, -3.0e8_wp, -3.0e8_wp, -1.0e8_wp, 2.0_wp, 2.0_wp, 2.0_wp, 2.0_wp]
      call itd_aggregate(3, 10, 4, 1, aicen, vicen, vsnon, trcrn, tf, PUNY, aice, vice, vsno, aice0, trcr, ierr)
      call ice_golden_check(error, "overfull ice, no snow", [aice, aice0, vsno, trcr(1), trcr(2), trcr(6), trcr(7)], &
                            [1.2_wp, 0.0_wp, 0.0_wp, (-0.7_wp - 1.5_wp)/1.2_wp, &
                             (-0.7e8_wp - 3.0e8_wp)/1.7_wp, 0.0_wp, (2.8_wp + 2.0_wp)/1.7_wp], 1.0e-14_wp, 0.0_wp)
   end subroutine test_agg_edges

   subroutine test_agg_nonfinite(error)
      !! NaN anywhere reaches the output: no `max` clamp, no `> 0` divisor test hides it.
      type(error_type), allocatable, intent(out) :: error
      real(wp) :: aicen(3), vicen(3), vsnon(3), trcrn(10, 3), trcr(10)
      real(wp) :: aice, vice, vsno, aice0, a, a0
      integer :: i
      integer(int32) :: ierr

      ierr = 0_int32

      aicen = [0.3_wp, 0.2_wp, 0.1_wp]; vicen = [0.5_wp, 0.4_wp, 0.3_wp]; vsnon = [0.1_wp, 0.0_wp, 0.05_wp]
      trcrn = -2.0e8_wp
      trcrn(1, :) = -10.0_wp

      ! NaN area: aice, aice0 and every tracer non-finite
      aicen(2) = QNAN
      call itd_aggregate(3, 10, 4, 1, aicen, vicen, vsnon, trcrn, -1.8_wp, PUNY, aice, vice, vsno, aice0, trcr, ierr)
      if (ieee_is_finite(aice) .or. ieee_is_finite(aice0) .or. any([(ieee_is_finite(trcr(i)), i=1, 10)])) then
         call test_failed(error, "NaN aicen propagates to aice, aice0, all tracers")
         return
      end if
      call check(error, iand(ierr, ICE_ERR_NONFINITE) /= 0_int32, "ICE_ERR_NONFINITE set for NaN input")
      if (allocated(error)) return
      call itd_aggregate_area(3, aicen, a, a0)
      if (ieee_is_finite(a) .or. ieee_is_finite(a0)) then
         call test_failed(error, "aggregate_area NaN")
         return
      end if

      ! NaN volume in any category poisons the cell totals, hence EVERY tracer (Tsfc included)
      aicen = [0.3_wp, 0.2_wp, 0.1_wp]
      vicen(3) = QNAN
      call itd_aggregate(3, 10, 4, 1, aicen, vicen, vsnon, trcrn, -1.8_wp, PUNY, aice, vice, vsno, aice0, trcr, ierr)
      if (ieee_is_finite(vice) .or. ieee_is_finite(trcr(2)) .or. ieee_is_finite(trcr(1))) then
         call test_failed(error, "NaN vicen poisons vice and every tracer, Tsfc included")
         return
      end if

      ! NaN tracer value in a populated category: that tracer only
      vicen = [0.5_wp, 0.4_wp, 0.3_wp]
      trcrn(3, 2) = QNAN
      call itd_aggregate(3, 10, 4, 1, aicen, vicen, vsnon, trcrn, -1.8_wp, PUNY, aice, vice, vsno, aice0, trcr, ierr)
      if (ieee_is_finite(trcr(3)) .or. .not. ieee_is_finite(trcr(2)) .or. .not. ieee_is_finite(trcr(1))) then
         call test_failed(error, "NaN tracer value stays on its own tracer")
         return
      end if
      ! the same NaN in a category with zero weight still poisons (NaN*0), upstream arithmetic
      aicen(2) = 0.0_wp; vicen(2) = 0.0_wp; vsnon(2) = 0.0_wp
      call itd_aggregate(3, 10, 4, 1, aicen, vicen, vsnon, trcrn, -1.8_wp, PUNY, aice, vice, vsno, aice0, trcr, ierr)
      call check(error, ieee_is_finite(trcr(3)), .false., "NaN tracer in an empty category is not hidden")
   end subroutine test_agg_nonfinite

   subroutine test_agg_layout(error)
      !! A caller's fixed-size local (`ldt = ICE_NTRCR_MAX`) with fewer active tracers gives
      !! the same answer as an exact-size array; an array shorter than the layer counts
      !! needs is refused (non-finite outputs plus `ICE_ERR_NONFINITE`), never mis-associated.
      type(error_type), allocatable, intent(out) :: error
      real(wp) :: aicen(5), vicen(5), vsnon(5), tbig(ICE_NTRCR_MAX, 5), texact(10, 5), tshort(6, 5)
      real(wp) :: trbig(ICE_NTRCR_MAX), trex(10), trsh(6), aice, vice, vsno, aice0
      real(wp) :: aice2, vice2, vsno2, aice02
      integer(int32) :: ierr
      integer :: n

      call gen_col(3, aicen, vicen, vsnon, texact)
      tbig = 123.0_wp
      do n = 1, 5
         tbig(1:10, n) = texact(:, n)
      end do
      trbig = -77.0_wp
      ierr = 0_int32
      call itd_aggregate(5, ICE_NTRCR_MAX, 4, 1, aicen, vicen, vsnon, tbig, -1.86_wp, PUNY, &
                         aice, vice, vsno, aice0, trbig, ierr)
      call itd_aggregate(5, 10, 4, 1, aicen, vicen, vsnon, texact, -1.86_wp, PUNY, &
                         aice2, vice2, vsno2, aice02, trex, ierr)
      call ice_golden_check(error, "fixed-size local == exact-size array", trbig(1:10), trex, 0.0_wp, 0.0_wp)
      if (allocated(error)) return
      call ice_golden_check(error, "untouched tail", trbig(11:ICE_NTRCR_MAX), &
                            [(-77.0_wp, n=11, ICE_NTRCR_MAX)], 0.0_wp, 0.0_wp)
      if (allocated(error)) return
      call check(error, ierr, 0_int32, "no error")
      if (allocated(error)) return

      tshort = 1.0_wp
      trsh = 0.0_wp
      call itd_aggregate(5, 6, 4, 1, aicen, vicen, vsnon, tshort, -1.86_wp, PUNY, &
                         aice, vice, vsno, aice0, trsh, ierr)
      call check(error, iand(ierr, ICE_ERR_NONFINITE) /= 0_int32, "short array sets the error bit")
      if (allocated(error)) return
      if (any([(ieee_is_finite(trsh(n)), n=1, 6)]) .or. ieee_is_finite(aice) .or. ieee_is_finite(aice0)) then
         call test_failed(error, "short array gives non-finite outputs")
      end if
   end subroutine test_agg_layout

