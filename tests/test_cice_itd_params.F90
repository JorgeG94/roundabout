      call ice_golden_check(error, "empty column", [aice, vice, vsno, aice0, trcr], &
                            [0.0_wp, 0.0_wp, 0.0_wp, 1.0_wp, tf, 0.0_wp, 0.0_wp, 0.0_wp, 0.0_wp, 0.0_wp, &
                             0.0_wp, 0.0_wp, 0.0_wp, 0.0_wp], 0.0_wp, 0.0_wp)
      if (allocated(error)) return

      ! area below puny: Tsfc falls back to Tf, volume tracers still follow their own divisor
      aicen = [5.0e-12_wp, 0.0_wp, 0.0_wp]; vicen = [1.0e-3_wp, 0.0_wp, 0.0_wp]; vsnon = 0.0_wp
      trcrn(:, 1) = [-5.0_wp, -3.0e8_wp, -3.0e8_wp, -3.0e8_wp, -3.0e8_wp, -9.0e7_wp, 2.0_wp, 2.0_wp, 2.0_wp, 2.0_wp]
