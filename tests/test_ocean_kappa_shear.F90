!! Unit and analytical tests for the kappa-shear interior closure
!! (`rdb_ocean_kappa_shear`).  Golden values generated by a Python
!! reference prototype of the JHL08 column solve.
!!
!! Global index convention (Roundabout bottom-up):
!!   kd_int(:,:,K=1) = bed (always 0)
!!   kd_int(:,:,K=nz+1) = surface (always 0)
!! Local prototype surface-down: K_local=0 surface, K_local=nz bed.
!! Flip: global K = nz+2 - K_local.
module test_ocean_kappa_shear
   use testdrive, only: new_unittest, unittest_type, error_type, check
   use rdb_constants, only: wp, GRAVITY, NZ_STACK_MAX
   use rdb_grid, only: hgrid_t
   use rdb_multilayer_state, only: multilayer_state_t
   use rdb_ocean_kappa_shear, only: ocean_kappa_shear_t, &
                                    kappa_shear_compute, &
                                    kappa_shear_merge_into_kv_kt, &
                                    kappa_shear_vertex_scatter, &
                                    ks_gather_corner
   use rdb_ocean_vdiff, only: ocean_vdiff_t, vdiff_apply_momentum
   use rdb_eos, only: EOS_VARIANT_LINEAR
   implicit none
   private

   public :: collect_ocean_kappa_shear_tests

   integer, parameter :: NGHOST = 2
   real(wp), parameter :: RHO0_KS = 1025.0_wp
   !! Thermal expansion in kg/m³/K (Fortran EOS convention).
   !! The prototype uses alpha_T=2e-4 in 1/K (dimensionless), so the Fortran
   !! slot value must be RHO0 * 2e-4 = 0.205 so that:
   !!   dbuoy_t = G * alpha_lin / rho0 = G * 2e-4   (matches prototype G*ALPHA_T)
   real(wp), parameter :: ALPHA_LIN_KS = RHO0_KS*2.0e-4_wp  ! 0.205 kg/m³/K
   real(wp), parameter :: BETA_LIN_KS = RHO0_KS*7.6e-4_wp  ! matches prototype
   real(wp), parameter :: F_CORIOLIS = 1.0e-4_wp
   !! Use the SAME gravity the kernel's buoyancy derivatives use
   !! (rdb_constants GRAVITY) so the column construction and the kernel
   !! agree exactly — the prototype is run with G=GRAVITY to match.
   real(wp), parameter :: GRAVITY_KS = GRAVITY

contains

   subroutine collect_ocean_kappa_shear_tests(testsuite)
      type(unittest_type), allocatable, intent(out) :: testsuite(:)

      testsuite = [ &
                  new_unittest("kshear_no_source", test_no_source), &
