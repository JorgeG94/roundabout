   subroutine test_oracle_melt(error)
      !! Upstream `lateral_melt` on 30 random 5-category columns, both constant
      !! sets.  Same arithmetic order as upstream: measured worst relative
      !! difference on gfortran is 0 (bitwise); bound 1e-14 for FMA builds.
      type(error_type), allocatable, intent(out) :: error
      type(ice_params_t) :: p
      real(wp) :: dt, rside, f0(4), a(1, 1, NC), v(1, 1, NC), vs(1, 1, NC), qi(1, 1, NC, NIL), qs(1, 1, NC, NSL)
      real(wp) :: fr(1, 1), fs(1, 1), fh(1, 1), ml(1, 1), got(20), chk
      integer(int32) :: ie(1, 1)
      integer :: iset, row, n, o
      real(wp) :: exp_all(20*30)

      do iset = 1, 2
         p = ice_params_default(merge(ICE_CONSTANTS_ICEPACK, ICE_CONSTANTS_CESM, iset == 1), NC, NIL, NSL)
         if (iset == 1) then
            exp_all = OM_ICEPACK
         else
            exp_all = OM_CESM
         end if
         do row = 0, 29
            call gen_row(row, dt, rside, f0, a, v, vs, qi, qs)
            chk = sum(a) + sum(v) + sum(vs) + rside + dt
            fr = f0(1); fs = f0(2); fh = f0(3); ml = f0(4); ie = 0_int32
            call ice_lateral_melt_cell(1, 1, 1, 1, NC, NIL, NSL, rside, dt, p%c%rhoi, p%c%rhos, &
                                       p%thermo%ice_ref_salinity, p%c%puny, a, v, vs, qi, qs, fr, fs, fh, ml, ie)
            got(1) = chk
            got(2) = fr(1, 1); got(3) = fs(1, 1); got(4) = fh(1, 1); got(5) = ml(1, 1)
            do n = 1, NC
               got(5 + n) = a(1, 1, n)
               got(10 + n) = v(1, 1, n)
               got(15 + n) = vs(1, 1, n)
            end do
            o = row*20
            call ice_golden_check(error, "lateral_melt row (inputs regenerated, outputs)", got, exp_all(o + 1:o + 20), &
                                  MELT_RTOL, 0.0_wp)
            if (allocated(error)) return
            call check(error, ie(1, 1) == 0_int32, "no error bits")
            if (allocated(error)) return
         end do
      end do
   end subroutine test_oracle_melt

   subroutine gen_row(row, dt, rside, f0, aicen, vicen, vsnon, qicen, qsnon)
      !! Identical draw order to the oracle driver (part of the contract).
      integer, intent(in) :: row
      real(wp), intent(out) :: dt, rside, f0(4), aicen(1, 1, NC), vicen(1, 1, NC), vsnon(1, 1, NC)
      real(wp), intent(out) :: qicen(1, 1, NC, NIL), qsnon(1, 1, NC, NSL)
      integer(int64) :: st
      integer :: n, k
      real(wp) :: u1, u2, u3, u4, u5

      st = lcg_next(int(row, int64)*104729_int64 + 7_int64)
      st = lcg_next(st); dt = 600.0_wp + 2400.0_wp*lcg_unit(st)
      st = lcg_next(st); rside = lcg_unit(st)
      if (row == 28) rside = 1.0_wp
      if (row == 29) rside = 0.0_wp
      do k = 1, 4
         st = lcg_next(st); f0(k) = lcg_unit(st)
      end do
      f0(1) = 1.0e-5_wp*f0(1); f0(2) = 1.0e-7_wp*f0(2); f0(3) = -3.0_wp*f0(3); f0(4) = 0.01_wp*f0(4)
      do n = 1, NC
         st = lcg_next(st); u1 = lcg_unit(st)
         st = lcg_next(st); u2 = lcg_unit(st)
         st = lcg_next(st); u3 = lcg_unit(st)
         st = lcg_next(st); u4 = lcg_unit(st)
         st = lcg_next(st); u5 = lcg_unit(st)
         aicen(1, 1, n) = 0.02_wp + 0.2_wp*u2
         vicen(1, 1, n) = aicen(1, 1, n)*(0.1_wp + 3.0_wp*u3)
         vsnon(1, 1, n) = 0.0_wp
         if (u4 >= 0.3_wp) vsnon(1, 1, n) = aicen(1, 1, n)*0.4_wp*u5
         do k = 1, 4
            st = lcg_next(st); qicen(1, 1, n, k) = -4.0e8_wp + 3.0e8_wp*lcg_unit(st)
         end do
         st = lcg_next(st); qsnon(1, 1, n, 1) = -1.2e8_wp + 0.3e8_wp*lcg_unit(st)
         if (u1 < 0.25_wp) then
            aicen(1, 1, n) = 0.0_wp; vicen(1, 1, n) = 0.0_wp; vsnon(1, 1, n) = 0.0_wp
         end if
      end do
   end subroutine gen_row

   subroutine test_shapes(error)
      !! Closure for ncat in {1, 3, 5} and nilyr in {1, 4, 8} (nslyr = 1: the dims
      !! module has NSLYR_MAX = 1 today, so nslyr > 1 cannot be built), with a
      !! snow-only category (vicen = 0, vsnon > 0) in every column.  Tolerance 1e-14.
      type(error_type), allocatable, intent(out) :: error
      integer, parameter :: NCS(5) = [1, 3, 5, 5, 3], NLS(5) = [1, 8, 1, 4, 8]
      integer :: is

      do is = 1, 5
         call one_shape(NCS(is), NLS(is), error)
         if (allocated(error)) return
      end do
   end subroutine test_shapes

   subroutine one_shape(ncat, nilyr, error)
      integer, intent(in) :: ncat, nilyr
      type(error_type), allocatable, intent(out) :: error
      type(ice_params_t) :: p
      real(wp) :: a(1, 1, ncat), v(1, 1, ncat), vs(1, 1, ncat), qi(1, 1, ncat, nilyr), qs(1, 1, ncat, 1)
      real(wp) :: fr(1, 1), fs(1, 1), fh(1, 1), ml(1, 1), r, dt, e(4), v0(ncat), vs0(ncat), a0(ncat)
      integer(int32) :: ie(1, 1)
      integer(int64) :: st
      integer :: n, k

      p = ice_params_default(ICE_CONSTANTS_ICEPACK, ncat, nilyr, 1)
      st = lcg_next(int(ncat*100 + nilyr, int64))
      dt = 700.0_wp
      r = 0.37_wp
      e = 0.0_wp
      do n = 1, ncat
         st = lcg_next(st); a(1, 1, n) = 0.05_wp + 0.15_wp*lcg_unit(st)
         st = lcg_next(st); v(1, 1, n) = a(1, 1, n)*(0.2_wp + 2.0_wp*lcg_unit(st))
         st = lcg_next(st); vs(1, 1, n) = a(1, 1, n)*0.3_wp*lcg_unit(st)
         do k = 1, nilyr
            st = lcg_next(st); qi(1, 1, n, k) = -4.0e8_wp + 3.0e8_wp*lcg_unit(st)
         end do
         st = lcg_next(st); qs(1, 1, n, 1) = -1.2e8_wp + 0.3e8_wp*lcg_unit(st)
      end do
      v(1, 1, 1) = 0.0_wp                    ! snow-only category
      vs(1, 1, 1) = 0.2_wp*a(1, 1, 1) + 0.01_wp
      v0 = v(1, 1, :); vs0 = vs(1, 1, :); a0 = a(1, 1, :)
      fr = 0.0_wp; fs = 0.0_wp; fh = 0.0_wp; ml = 0.0_wp; ie = 0_int32
      call ice_lateral_melt_cell(1, 1, 1, 1, ncat, nilyr, 1, r, dt, p%c%rhoi, p%c%rhos, &
                                 p%thermo%ice_ref_salinity, p%c%puny, a, v, vs, qi, qs, fr, fs, fh, ml, ie)
      do n = 1, ncat
         e(1) = e(1) + p%c%rhoi*v0(n) + p%c%rhos*vs0(n)
         e(2) = e(2) + p%c%rhoi*v0(n)*p%thermo%ice_ref_salinity*1.0e-3_wp
         do k = 1, nilyr
            e(3) = e(3) + qi(1, 1, n, k)*v0(n)/real(nilyr, wp)
         end do
         e(3) = e(3) + qs(1, 1, n, 1)*vs0(n)
         e(4) = e(4) + v0(n)
      end do
      e = e*r
      e(1:3) = e(1:3)/dt
      call ice_golden_check(error, "fresh, fsalt, fhocn, meltl", [fr(1, 1), fs(1, 1), fh(1, 1), ml(1, 1)], e, &
                            1.0e-14_wp, 0.0_wp)
      if (allocated(error)) return
      call check(error, v(1, 1, 1) == 0.0_wp .and. fr(1, 1) > p%c%rhos*vs0(1)*r/dt*0.999_wp, "snow-only category melts its snow")
      if (allocated(error)) return
      call ice_golden_check(error, "state scaled by 1 - rside", [a(1, 1, ncat), vs(1, 1, 1)], &
                            [a0(ncat)*(1.0_wp - r), vs0(1)*(1.0_wp - r)], 1.0e-15_wp, 0.0_wp)
      if (allocated(error)) return
      call check(error, ie(1, 1) == 0_int32, "no error bits")
   end subroutine one_shape

   subroutine test_driver_device(error)
      !! The column driver over mapped arrays (device on the GPU build, host
      !! otherwise).  A closed-form comparison with a tolerance (1e-13; FMA is on
      !! in GPU builds), NOT a CPU/GPU bitwise check: owned cells match the closed
      !! forms of fresh, fsalt, fhocn, meltl and the state (increments compared,
      !! not only signs); ghost cells are bitwise untouched.  The driver reads the
      !! parameter bundle on the host, so it is not mapped.  The second half of L6
      !! (a re-aggregation restoring `aice0`) belongs to the therm2 driver PR,
      !! which owns `itd_aggregate`.
      type(error_type), allocatable, intent(out) :: error
      integer, parameter :: NX = 8, NY = 6
      type(ice_params_t) :: p
      real(wp) :: a(NX, NY, NC), v(NX, NY, NC), vs(NX, NY, NC), qi(NX, NY, NC, NIL), qs(NX, NY, NC, NSL)
      real(wp) :: a0(NX, NY, NC), v0(NX, NY, NC), vs0(NX, NY, NC), rside(NX, NY), dt
      real(wp) :: fr(NX, NY), fs(NX, NY), fh(NX, NY), ml(NX, NY), exp_fr, exp_ml, exp_fs, exp_fh, worst
      integer(int32) :: ie(NX, NY)
      integer :: i, j, n, k
      logical :: owned

      call build_state(ICE_CONSTANTS_ICEPACK, NX*NY, 31337_int64, NX, NY, p, a, v, vs, qi, qs, rside)
      dt = 900.0_wp
      a0 = a; v0 = v; vs0 = vs
      fr = 1.0_wp; fs = 2.0_wp; fh = -3.0_wp; ml = 0.5_wp; ie = 0_int32
      !$acc enter data copyin(a, v, vs, qi, qs, rside, fr, fs, fh, ml, ie)
      call ice_lateral_melt_step(NX, NY, NC, NIL, NSL, 2, NX - 1, 2, NY - 1, dt, p, rside, &
                                 a, v, vs, qi, qs, fr, fs, fh, ml, ie)
      !$acc update self(a, v, vs, fr, fs, fh, ml, ie)
      !$acc exit data delete(a, v, vs, qi, qs, rside, fr, fs, fh, ml, ie)
      worst = 0.0_wp
      do j = 1, NY
         do i = 1, NX
            owned = i >= 2 .and. i <= NX - 1 .and. j >= 2 .and. j <= NY - 1
            if (owned) then
               exp_fr = 1.0_wp + (p%c%rhoi*sum(v0(i, j, :)) + p%c%rhos*sum(vs0(i, j, :)))*rside(i, j)/dt
               exp_ml = 0.5_wp + sum(v0(i, j, :))*rside(i, j)
               call acc(fr(i, j) - exp_fr, exp_fr)
               call acc(ml(i, j) - exp_ml, exp_ml)
               do n = 1, NC
                  call acc(v(i, j, n) - v0(i, j, n)*(1.0_wp - rside(i, j)), max(v0(i, j, n), tiny(1.0_wp)))
                  call acc(a(i, j, n) - a0(i, j, n)*(1.0_wp - rside(i, j)), max(a0(i, j, n), tiny(1.0_wp)))
               end do
               exp_fs = 2.0_wp + p%c%rhoi*sum(v0(i, j, :))*p%thermo%ice_ref_salinity*1.0e-3_wp*rside(i, j)/dt
               exp_fh = -3.0_wp
               do n = 1, NC
                  do k = 1, NIL
                     exp_fh = exp_fh + qi(i, j, n, k)*v0(i, j, n)/real(NIL, wp)*rside(i, j)/dt
                  end do
                  exp_fh = exp_fh + qs(i, j, n, 1)*vs0(i, j, n)*rside(i, j)/dt
               end do
               call acc(fs(i, j) - exp_fs, exp_fs)
               call acc(fh(i, j) - exp_fh, exp_fh)
            else
               call check(error, all(a(i, j, :) == a0(i, j, :)) .and. fr(i, j) == 1.0_wp .and. fs(i, j) == 2.0_wp &
                          .and. fh(i, j) == -3.0_wp .and. ml(i, j) == 0.5_wp, "ghost cell untouched")
               if (allocated(error)) return
            end if
         end do
      end do
      call check(error, worst <= 1.0e-13_wp, "owned cells match the closed form (device/host tolerance 1e-13)")
      if (allocated(error)) return
      call check(error, all(ie == 0_int32), "no error bits")
   contains
      subroutine acc(resid, scale)
         real(wp), intent(in) :: resid, scale
         real(wp) :: x
         x = abs(resid)/max(abs(scale), tiny(1.0_wp))
         if (.not. (x <= worst)) worst = x
      end subroutine acc
   end subroutine test_driver_device

   subroutine test_driver_every_cell(error)
      !! Guards the index passing of the in-place kernel: a random state in which
      !! EVERY cell differs (own `rside`, own areas, volumes and enthalpies) goes
      !! through the device driver, and every cell of every output and of the
      !! melted state is compared with a host run of the SAME cell kernel
      !! (`ice_lateral_melt_cell`, indices as literal loop variables).  A kernel
      !! that read the wrong cells (indices passed by reference to a device
      !! routine) would differ almost everywhere.  Tolerance 1e-13 relative
      !! (FMA on the GPU build); bitwise on CPU builds.  Non-finite results fail
      !! explicitly.
      type(error_type), allocatable, intent(out) :: error
      integer, parameter :: NX = 33, NY = 21
      type(ice_params_t) :: p
      real(wp) :: a(NX, NY, NC), v(NX, NY, NC), vs(NX, NY, NC), qi(NX, NY, NC, NIL), qs(NX, NY, NC, NSL)
      real(wp) :: ah(NX, NY, NC), vh(NX, NY, NC), vsh(NX, NY, NC), rside(NX, NY), dt, tol, worst, x
      real(wp) :: fr(NX, NY), fs(NX, NY), fh(NX, NY), ml(NX, NY)
      real(wp) :: frh(NX, NY), fsh(NX, NY), fhh(NX, NY), mlh(NX, NY)
      integer(int32) :: ie(NX, NY), ieh(NX, NY)
      integer :: i, j, nchg

#ifdef RDB_GPU_OFFLOAD
      tol = 1.0e-13_wp
#else
      tol = 0.0_wp
#endif
      call build_state(ICE_CONSTANTS_ICEPACK, NX*NY, 271828_int64, NX, NY, p, a, v, vs, qi, qs, rside)
      do j = 1, NY
         do i = 1, NX
            rside(i, j) = 0.002_wp + 0.5_wp*real(mod(7*i + 13*j, 29), wp)/29.0_wp   ! every cell differs
         end do
      end do
      dt = 900.0_wp
      ah = a; vh = v; vsh = vs
      fr = 0.1_wp; fs = 0.2_wp; fh = -0.3_wp; ml = 0.4_wp; ie = 0_int32
      frh = fr; fsh = fs; fhh = fh; mlh = ml; ieh = 0_int32
      do j = 1, NY
         do i = 1, NX
            call ice_lateral_melt_cell(i, j, NX, NY, NC, NIL, NSL, rside(i, j), dt, p%c%rhoi, p%c%rhos, &
                                       p%thermo%ice_ref_salinity, p%c%puny, ah, vh, vsh, qi, qs, frh, fsh, fhh, mlh, ieh)
         end do
      end do
      !$acc enter data copyin(a, v, vs, qi, qs, rside, fr, fs, fh, ml, ie)
      call ice_lateral_melt_step(NX, NY, NC, NIL, NSL, 1, NX, 1, NY, dt, p, rside, &
                                 a, v, vs, qi, qs, fr, fs, fh, ml, ie)
      !$acc update self(a, v, vs, fr, fs, fh, ml, ie)
      !$acc exit data delete(a, v, vs, qi, qs, rside, fr, fs, fh, ml, ie)
      worst = 0.0_wp
      nchg = 0
      do j = 1, NY
         do i = 1, NX
            call chk(fr(i, j), frh(i, j))
            call chk(fs(i, j), fsh(i, j))
            call chk(fh(i, j), fhh(i, j))
            call chk(ml(i, j), mlh(i, j))
            if (fr(i, j) /= 0.1_wp) nchg = nchg + 1
         end do
      end do
      call chk_all(a, ah)
      call chk_all(v, vh)
      call chk_all(vs, vsh)
      if (.not. (worst <= tol)) then
         call test_failed(error, "device driver differs from the host kernel in some cell (or is non-finite)")
         return
      end if
      call check(error, nchg == NX*NY, "every cell received a flux (no cell skipped)")
      if (allocated(error)) return
      call check(error, all(ie == ieh) .and. all(ie == 0_int32), "error words agree and are clean")
   contains
      subroutine chk(d, h)
         real(wp), intent(in) :: d, h
         if (.not. (ieee_is_finite(d) .and. ieee_is_finite(h))) then
            worst = huge(1.0_wp)
            return
         end if
         x = abs(d - h)/max(abs(h), tiny(1.0_wp))
         if (x > worst) worst = x
      end subroutine chk
      subroutine chk_all(d, h)
         real(wp), intent(in) :: d(:, :, :), h(:, :, :)
         integer :: ii, jj, nn
         do nn = 1, NC
            do jj = 1, NY
               do ii = 1, NX
                  call chk(d(ii, jj, nn), h(ii, jj, nn))
               end do
            end do
         end do
      end subroutine chk_all
   end subroutine test_driver_every_cell

end module test_cice_lateral_melt
