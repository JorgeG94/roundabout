   subroutine test_bad_input(error)
      !! Non-finite inputs, rside out of [0,1] and negative area set their bit
      !! and leave the cell and its fluxes untouched; the next cell is melted.
      type(error_type), allocatable, intent(out) :: error
      type(ice_params_t) :: p
      real(wp) :: a(2, 1, NC), v(2, 1, NC), vs(2, 1, NC), qi(2, 1, NC, NIL), qs(2, 1, NC, NSL), rside(2, 1)
      real(wp) :: a1(2, 1, NC), v1(2, 1, NC), vs1(2, 1, NC), qi1(2, 1, NC, NIL), qs1(2, 1, NC, NSL)
      real(wp) :: fr(2, 1), fs(2, 1), fh(2, 1), ml(2, 1), nan, r
      integer(int32) :: ie(2, 1)
      integer :: icase
      integer(int32), parameter :: WANT(7) = [ICE_ERR_NONFINITE, ICE_ERR_NONFINITE, ICE_ERR_NONFINITE, &
                                              ICE_ERR_NONFINITE, ICE_ERR_AICE_RANGE, ICE_ERR_AICE_RANGE, ICE_ERR_AICEN_NEG]

      nan = ieee_value(1.0_wp, ieee_quiet_nan)
      call build_state(ICE_CONSTANTS_ICEPACK, 2, 79_int64, 2, 1, p, a1, v1, vs1, qi1, qs1, rside)
      do icase = 1, 7
         a = a1; v = v1; vs = vs1; qi = qi1; qs = qs1
         r = 0.4_wp
         select case (icase)
         case (1); a(1, 1, 2) = nan
         case (2); v(1, 1, 3) = nan
         case (3); qi(1, 1, 4, 2) = nan
         case (4); r = nan
         case (5); r = 1.5_wp
         case (6); r = -0.1_wp
         case (7); a(1, 1, 1) = -1.0e-3_wp
         end select
         fr = 0.0_wp; fs = 0.0_wp; fh = 0.0_wp; ml = 0.0_wp; ie = 0_int32
         call ice_lateral_melt_cell(1, 1, 2, 1, NC, NIL, NSL, r, 100.0_wp, p%c%rhoi, p%c%rhos, &
                                    p%thermo%ice_ref_salinity, p%c%puny, a, v, vs, qi, qs, fr, fs, fh, ml, ie)
         call ice_lateral_melt_cell(2, 1, 2, 1, NC, NIL, NSL, 0.4_wp, 100.0_wp, p%c%rhoi, p%c%rhos, &
                                    p%thermo%ice_ref_salinity, p%c%puny, a, v, vs, qi, qs, fr, fs, fh, ml, ie)
         call check(error, ie(1, 1) == WANT(icase) .and. ie(2, 1) == 0_int32, "error bit set on the bad cell only")
         if (allocated(error)) return
         call check(error, fr(1, 1) == 0.0_wp .and. fs(1, 1) == 0.0_wp .and. fh(1, 1) == 0.0_wp .and. ml(1, 1) == 0.0_wp, &
                    "bad cell: fluxes untouched")
         if (allocated(error)) return
         call check(error, (a(1, 1, 1) == a1(1, 1, 1) .or. icase == 7) .and. all(v(1, 1, 1:2) == v1(1, 1, 1:2)), &
                    "bad cell: state untouched")
         if (allocated(error)) return
         call check(error, v(2, 1, 1) == v1(2, 1, 1)*(1.0_wp - 0.4_wp) .and. fr(2, 1) > 0.0_wp, "neighbouring cell melted normally")
         if (allocated(error)) return
      end do
   end subroutine test_bad_input

