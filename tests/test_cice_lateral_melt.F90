   subroutine test_rside_closed_forms(error)
      !! dT = 1 K: wlat = m1 exactly (1**m2 = 1); alpha = pi/4 gives 4 wlat dt/D;
      !! dT = 2: wlat = m1 * 2**1.36 (literal 2.5668517951258085).
      type(error_type), allocatable, intent(out) :: error
      real(wp) :: rs, wl
      integer(int32) :: ierr

      ierr = 0_int32
      call ice_lateral_rside(900.0_wp, 1.0_wp - 1.8_wp, -1.8_wp, 300.0_wp, 0.66_wp, PI, rs, wl, ierr)
      call check(error, wl == 1.6e-6_wp, "wlat(dT=1) == m1")
      if (allocated(error)) return
      call ice_golden_check(error, "rside(dT=1, 900 s, D=300, alpha=0.66)", [rs], &
                            [PI*1.6e-6_wp*900.0_wp/(0.66_wp*300.0_wp)], 1.0e-15_wp, 0.0_wp)
      if (allocated(error)) return
      call ice_lateral_rside(900.0_wp, 1.0_wp - 1.8_wp, -1.8_wp, 300.0_wp, PI/4.0_wp, PI, rs, wl, ierr)
      call ice_golden_check(error, "circular floes: rside = 4 wlat dt / D", [rs], &
                            [4.0_wp*1.6e-6_wp*900.0_wp/300.0_wp], 1.0e-15_wp, 0.0_wp)
      if (allocated(error)) return
      call ice_lateral_rside(900.0_wp, 0.2_wp, -1.8_wp, 300.0_wp, 0.66_wp, PI, rs, wl, ierr)   ! dT = 2
      call ice_golden_check(error, "wlat(dT=2)", [wl], [1.6e-6_wp*2.5668517951258085_wp], 1.0e-14_wp, 0.0_wp)
      if (allocated(error)) return
      call check(error, ierr == 0_int32, "no error bits on valid input")
   end subroutine test_rside_closed_forms

   subroutine test_rside_limits(error)
      type(error_type), allocatable, intent(out) :: error
      real(wp) :: rs, wl, nan
      integer(int32) :: ierr

      nan = ieee_value(1.0_wp, ieee_quiet_nan)
      ierr = 0_int32
      call ice_lateral_rside(900.0_wp, -1.8_wp, -1.8_wp, 300.0_wp, 0.66_wp, PI, rs, wl, ierr)
      call check(error, rs == 0.0_wp .and. wl == 0.0_wp, "ocean at freezing: no melt")
      if (allocated(error)) return
      call ice_lateral_rside(900.0_wp, -2.5_wp, -1.8_wp, 300.0_wp, 0.66_wp, PI, rs, wl, ierr)
      call check(error, rs == 0.0_wp .and. wl == 0.0_wp, "ocean below freezing: no melt")
      if (allocated(error)) return
      call ice_lateral_rside(1.0e9_wp, 3.0_wp, -1.8_wp, 300.0_wp, 0.66_wp, PI, rs, wl, ierr)
      call check(error, rs == 1.0_wp, "huge dt clips to exactly 1")
      if (allocated(error)) return
      call ice_lateral_rside(900.0_wp, 3.0_wp, -1.8_wp, 1.0e-3_wp, 0.66_wp, PI, rs, wl, ierr)
      call check(error, rs == 1.0_wp, "tiny floe diameter clips to exactly 1")
      if (allocated(error)) return
      call check(error, ierr == 0_int32, "clipping is not an error")
      if (allocated(error)) return
      ierr = 0_int32
      call ice_lateral_rside(900.0_wp, nan, -1.8_wp, 300.0_wp, 0.66_wp, PI, rs, wl, ierr)
      call check(error, rs == 0.0_wp .and. ierr == ICE_ERR_NONFINITE, "NaN sst: 0 and flagged")
      if (allocated(error)) return
      ierr = 0_int32
      call ice_lateral_rside(nan, 1.0_wp, -1.8_wp, 300.0_wp, 0.66_wp, PI, rs, wl, ierr)
      call check(error, rs == 0.0_wp .and. ierr == ICE_ERR_NONFINITE, "NaN dt: 0 and flagged")
      if (allocated(error)) return
      ierr = 0_int32
      call ice_lateral_rside(900.0_wp, 1.0_wp, -1.8_wp, 0.0_wp, 0.66_wp, PI, rs, wl, ierr)
      call check(error, rs == 1.0_wp .and. ierr == 0_int32, "floe diameter 0 (documents upstream behaviour: +Inf clips to 1)")
   end subroutine test_rside_limits

   subroutine test_rside_oracle(error)
      !! Upstream rside and wlat over (dT, floediam, floeshape, dt).  Tolerance: the
      !! port takes dT**1.36 from the reproducible power (<= ~2 ulp) where upstream
      !! uses libm; the two differ by <= 2 ulp (~5e-16 relative) on ~9 % of dT values.
      !! The 240 grid rows hold only a few distinct dT (they happen to agree bitwise);
      !! 40 further rows use random dT in (0, 6) K, so the tolerance is exercised.
      !! Bound 1e-14: ~20x the 2 ulp worst case, also covering FMA-contracting builds.
      type(error_type), allocatable, intent(out) :: error
      real(wp), parameter :: dT(8) = [0.0_wp, 1.0e-3_wp, 1.0e-2_wp, 0.1_wp, 0.5_wp, 1.0_wp, 2.0_wp, 5.0_wp]
      real(wp), parameter :: diam(5) = [10.0_wp, 100.0_wp, 300.0_wp, 1000.0_wp, 5000.0_wp]
      real(wp) :: shp(2), dtv(3), rs(280), wl(280)
      integer :: id, jf, js, kd, r
      integer(int32) :: ierr
      integer(int64) :: st
      real(wp) :: dtr

      shp = [0.66_wp, PI/4.0_wp]
      dtv = [900.0_wp, 7200.0_wp, 2.0e5_wp]
      ierr = 0_int32
      r = 0
      do kd = 1, 3
         do js = 1, 2
            do jf = 1, 5
               do id = 1, 8
                  r = r + 1
                  call ice_lateral_rside(dtv(kd), -1.8_wp + dT(id), -1.8_wp, diam(jf), shp(js), PI, rs(r), wl(r), ierr)
               end do
            end do
         end do
      end do
      st = lcg_next(20261113_int64)
      do kd = 1, 40
         st = lcg_next(st)
         dtr = 6.0_wp*lcg_unit(st)
         r = r + 1
         call ice_lateral_rside(900.0_wp, -1.8_wp + dtr, -1.8_wp, 300.0_wp, 0.66_wp, PI, rs(r), wl(r), ierr)
      end do
      call ice_golden_check(error, "rside vs upstream", rs, RS_RSIDE, RSIDE_RTOL, 0.0_wp)
      if (allocated(error)) return
      call ice_golden_check(error, "wlat vs upstream", wl, RS_WLAT, RSIDE_RTOL, 0.0_wp)
      if (allocated(error)) return
      call check(error, count(RS_RSIDE == 1.0_wp) > 0 .and. count(RS_RSIDE > 0.0_wp .and. RS_RSIDE < 1.0_wp) > 20, &
                 "table covers both the clipped and the open range")
   end subroutine test_rside_oracle

