   subroutine build_state(cset, ncell, seed, nx, ny, p, a, v, vs, qi, qs, rside)
      !! Random 5-category cells; thermodynamic columns from `ice_random_columns`.
      integer, intent(in) :: cset, ncell, nx, ny
      integer(int64), intent(in) :: seed
      type(ice_params_t), intent(out) :: p
      real(wp), intent(out) :: a(nx, ny, NC), v(nx, ny, NC), vs(nx, ny, NC)
      real(wp), intent(out) :: qi(nx, ny, NC, NIL), qs(nx, ny, NC, NSL), rside(nx, ny)
      real(wp) :: hi(ncell*NC), hs(ncell*NC), Tsfc(ncell*NC), S(NIL, ncell*NC), T(NIL, ncell*NC)
      integer(int64) :: st
      integer :: i, j, n, k, c, cell

      p = ice_params_default(cset, NC, NIL, NSL)
      call ice_random_columns(ncell*NC, NIL, seed, hi, hs, Tsfc, S, T)
      st = lcg_next(seed + 99_int64)
      cell = 0
      do j = 1, ny
         do i = 1, nx
            cell = cell + 1
            st = lcg_next(st)
            rside(i, j) = lcg_unit(st)
            do n = 1, NC
               c = (cell - 1)*NC + n
               st = lcg_next(st)
               a(i, j, n) = 0.02_wp + 0.18_wp*lcg_unit(st)
               v(i, j, n) = a(i, j, n)*hi(c)
               vs(i, j, n) = a(i, j, n)*hs(c)
               do k = 1, NIL
                  qi(i, j, n, k) = ice_q_from_T(T(k, c), S(k, c), p%c, p%thermo%l_brine)
               end do
               qs(i, j, n, 1) = ice_qsno_from_T(Tsfc(c), p%c)
            end do
         end do
      end do
   end subroutine build_state

   subroutine test_closure_random(error)
      !! Per cell: water, salt, enthalpy and area ledgers close to round-off
      !! between the state change and the deposited fluxes; intensive tracers
      !! (enthalpies, thickness per area) are unchanged.  Both constant sets.
      !! Tolerance: measured worst relative residual between 1e-16 and 1e-15
      !! (sums over 5 categories); bound 1e-14 (10x).
      type(error_type), allocatable, intent(out) :: error
      integer, parameter :: NX = 8, NY = 5
      type(ice_params_t) :: p
      real(wp) :: a(NX, NY, NC), v(NX, NY, NC), vs(NX, NY, NC), qi(NX, NY, NC, NIL), qs(NX, NY, NC, NSL)
      real(wp) :: a0(NX, NY, NC), v0(NX, NY, NC), vs0(NX, NY, NC), qi0(NX, NY, NC, NIL), qs0(NX, NY, NC, NSL)
      real(wp) :: rside(NX, NY), fr(NX, NY), fs(NX, NY), fh(NX, NY), ml(NX, NY)
      real(wp) :: dt, M0, M1, S0, S1, E0, E1, A0s, A1s, hi0, hi1, res, worst(5)
      integer(int32) :: ie(NX, NY)
      integer :: cset, i, j, n, k, isets(2)
      type(ice_ledger_t) :: led

      isets = [ICE_CONSTANTS_ICEPACK, ICE_CONSTANTS_CESM]
      dt = 1234.5_wp
      do cset = 1, 2
         worst = 0.0_wp
         call build_state(isets(cset), NX*NY, 4242_int64 + cset, NX, NY, p, a, v, vs, qi, qs, rside)
         rside(1, 1) = 1.0_wp
         rside(2, 1) = 0.0_wp
         a0 = a; v0 = v; vs0 = vs; qi0 = qi; qs0 = qs
         fr = 0.0_wp; fs = 0.0_wp; fh = 0.0_wp; ml = 0.0_wp; ie = 0_int32
         do j = 1, NY
            do i = 1, NX
               call ice_lateral_melt_cell(i, j, NX, NY, NC, NIL, NSL, rside(i, j), dt, p%c%rhoi, p%c%rhos, &
                                          p%thermo%ice_ref_salinity, p%c%puny, a, v, vs, qi, qs, &
                                          fr, fs, fh, ml, ie)
            end do
         end do
         call check(error, all(ie == 0_int32), "no error bits")
         if (allocated(error)) return
         call check(error, all(qi == qi0) .and. all(qs == qs0), "enthalpy tracers bitwise unchanged")
         if (allocated(error)) return
         do j = 1, NY
            do i = 1, NX
               M0 = 0.0_wp; M1 = 0.0_wp; S0 = 0.0_wp; S1 = 0.0_wp; E0 = 0.0_wp; E1 = 0.0_wp
               A0s = 0.0_wp; A1s = 0.0_wp
               do n = 1, NC
                  M0 = M0 + p%c%rhoi*v0(i, j, n) + p%c%rhos*vs0(i, j, n)
                  M1 = M1 + p%c%rhoi*v(i, j, n) + p%c%rhos*vs(i, j, n)
                  S0 = S0 + p%c%rhoi*v0(i, j, n)*p%thermo%ice_ref_salinity*1.0e-3_wp
                  S1 = S1 + p%c%rhoi*v(i, j, n)*p%thermo%ice_ref_salinity*1.0e-3_wp
                  do k = 1, NIL
                     E0 = E0 + qi0(i, j, n, k)*v0(i, j, n)/real(NIL, wp)
                     E1 = E1 + qi(i, j, n, k)*v(i, j, n)/real(NIL, wp)
                  end do
                  E0 = E0 + qs0(i, j, n, 1)*vs0(i, j, n)
                  E1 = E1 + qs(i, j, n, 1)*vs(i, j, n)
                  A0s = A0s + a0(i, j, n)
                  A1s = A1s + a(i, j, n)
                  ! per-category: intensive quantities unchanged (thickness per area)
                  if (a0(i, j, n) > 0.0_wp .and. rside(i, j) < 1.0_wp) then
                     hi0 = v0(i, j, n)/a0(i, j, n)
                     hi1 = v(i, j, n)/a(i, j, n)
                     res = hi1 - hi0
                     call acc(worst(5), res/hi0)
                  end if
               end do
               call acc(worst(1), (M1 - M0) + dt*fr(i, j), M0)           ! water
               call acc(worst(2), (S1 - S0) + dt*fs(i, j), S0)           ! salt
               call acc(worst(3), (E1 - E0) + dt*fh(i, j), E0)           ! heat: dE = -dt*fhocn
               call acc(worst(4), (A1s - A0s*(1.0_wp - rside(i, j))), A0s) ! area
               res = ml(i, j) - rside(i, j)*sum(v0(i, j, :))
               call acc(worst(4), res, sum(v0(i, j, :)))
            end do
         end do
         call led%add("water", worst(1), 1.0_wp)
         call led%add("salt", worst(2), 1.0_wp)
         call led%add("enthalpy", worst(3), 1.0_wp)
         call led%add("area_meltl", worst(4), 1.0_wp)
         call led%add("thickness", worst(5), 1.0_wp)
         call check(error, led%closed(1.0e-14_wp), "ledger closes to round-off")
         if (allocated(error)) return
         call check(error, worst(1) <= 1.0e-14_wp .and. worst(2) <= 1.0e-14_wp .and. worst(3) <= 1.0e-14_wp &
                    .and. worst(4) <= 1.0e-14_wp .and. worst(5) <= 1.0e-14_wp, "ledger lines finite and closed")
         if (allocated(error)) return
         ! rside = 1 cell is empty; rside = 0 cell has zero fluxes
         call check(error, all(a(1, 1, :) == 0.0_wp) .and. all(v(1, 1, :) == 0.0_wp) .and. all(vs(1, 1, :) == 0.0_wp), &
                    "rside = 1 empties the cell")
         if (allocated(error)) return
         call check(error, fr(2, 1) == 0.0_wp .and. fh(2, 1) == 0.0_wp .and. all(v(2, 1, :) == v0(2, 1, :)), &
                    "rside = 0 cell untouched")
         if (allocated(error)) return
      end do
   contains
      subroutine acc(w, resid, scale)
         !! NaN-proof worst-residual accumulation (a NaN is kept, not hidden).
         real(wp), intent(inout) :: w
         real(wp), intent(in) :: resid
         real(wp), intent(in), optional :: scale
         real(wp) :: x
         x = abs(resid)
         if (present(scale)) x = x/max(abs(scale), tiny(1.0_wp))
         if (.not. (x <= w)) w = x
      end subroutine acc
   end subroutine test_closure_random

   subroutine test_rside_one(error)
      !! rside = 1: every category empty; fluxes equal all mass, salt, energy.
      type(error_type), allocatable, intent(out) :: error
      type(ice_params_t) :: p
      real(wp) :: a(1, 1, NC), v(1, 1, NC), vs(1, 1, NC), qi(1, 1, NC, NIL), qs(1, 1, NC, NSL), rside(1, 1)
      real(wp) :: fr(1, 1), fs(1, 1), fh(1, 1), ml(1, 1), v0, vs0, e0
      integer(int32) :: ie(1, 1)
      integer :: n, k

      call build_state(ICE_CONSTANTS_ICEPACK, 1, 77_int64, 1, 1, p, a, v, vs, qi, qs, rside)
      rside = 1.0_wp
      v0 = sum(v); vs0 = sum(vs)
      e0 = 0.0_wp
      do n = 1, NC
         do k = 1, NIL
            e0 = e0 + qi(1, 1, n, k)*v(1, 1, n)/real(NIL, wp)
         end do
         e0 = e0 + qs(1, 1, n, 1)*vs(1, 1, n)
      end do
      fr = 0.0_wp; fs = 0.0_wp; fh = 0.0_wp; ml = 0.0_wp; ie = 0_int32
      call ice_lateral_melt_cell(1, 1, 1, 1, NC, NIL, NSL, 1.0_wp, 100.0_wp, p%c%rhoi, p%c%rhos, &
                                 p%thermo%ice_ref_salinity, p%c%puny, a, v, vs, qi, qs, fr, fs, fh, ml, ie)
      call check(error, all(a == 0.0_wp) .and. all(v == 0.0_wp) .and. all(vs == 0.0_wp), "all categories exactly empty")
      if (allocated(error)) return
      call ice_golden_check(error, "fluxes carry everything", [fr(1, 1), fh(1, 1), ml(1, 1)], &
                            [(p%c%rhoi*v0 + p%c%rhos*vs0)/100.0_wp, e0/100.0_wp, v0], 1.0e-13_wp, 0.0_wp)
   end subroutine test_rside_one

