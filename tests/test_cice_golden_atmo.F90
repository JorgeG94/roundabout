   subroutine evaluate(iset, got)
      !! Kernel outputs `[sx, sy, dt, dq, lh, sh]` for every case under constant set `iset`.
      integer, intent(in) :: iset
      real(wp), intent(out) :: got(6, N)
      type(ice_params_t) :: p
      integer :: i
      integer(int32) :: ierr

      p = ice_params_default(iset, 5, 4, 1)
      do i = 1, N
         p%atm%highfreq = IN_HF(i) > 0.5_wp
         p%atm%natmiter = nint(IN_NIT(i))
         p%atm%atmiter_conv = IN_CONV(i)
         ierr = 0_int32
         call ice_atm_boundary_ice(IN_TSF(i), IN_POTT(i), IN_UA(i), IN_VA(i), IN_UI(i), IN_VI(i), IN_WIND(i), &
                                   IN_ZL(i), IN_ZS(i), IN_QA(i), IN_RHO(i), p%c, p%atm, &
                                   got(6, i), got(5, i), got(1, i), got(2, i), got(3, i), got(4, i), ierr)
         if (ierr /= 0_int32) got(:, i) = huge(1.0_wp)
      end do
   end subroutine evaluate

   subroutine compare(error, label, iset, ref)
      type(error_type), allocatable, intent(out) :: error
      character(len=*), intent(in) :: label
      integer, intent(in) :: iset
      real(wp), intent(in) :: ref(6, N)
      real(wp) :: got(6, N), rtol(6), d, tol, ssq
      character(len=8), parameter :: NM(6) = ['strx  ', 'stry  ', 'delt  ', 'delq  ', 'lhcoef', 'shcoef']
      character(len=200) :: msg
      integer :: i, j

      call evaluate(iset, got)
      rtol = [RTOL_SX, RTOL_SY, RTOL_DT, 0.0_wp, RTOL_LH, RTOL_SH]
      do i = 1, N
         do j = 1, 6
            if (.not. ieee_is_finite(got(j, i))) then
               write (msg, '(a,a,a,i0)') trim(label), ": non-finite ", trim(NM(j)), i
               call test_failed(error, trim(msg))
               return
            end if
            d = abs(got(j, i) - ref(j, i))
            if (j == 4) then
               ssq = ice_qsat_surface(IN_TSF(i) + 273.15_wp, IN_RHO(i))
               tol = ATOL_DQ_SSQ*ssq
            else
               tol = rtol(j)*abs(ref(j, i))
            end if
            if (.not. (d <= tol)) then
               write (msg, '(a,a,a,a,i0,2(a,es23.15))') trim(label), ": ", trim(NM(j)), " case ", i, " got ", &
                  got(j, i), " expected ", ref(j, i)
               call test_failed(error, trim(msg))
               return
            end if
         end do
      end do
   end subroutine compare

