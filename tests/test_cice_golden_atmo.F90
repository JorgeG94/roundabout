!! Golden comparison of the atmosphere-ice boundary layer against the Icepack
!! atmospheric boundary-layer routine (ice surface), 64 cases x two constant sets.
!!
!! The table is 17-significant-digit literals from the Icepack oracle (the upstream
!! routine called directly; both constant sets).  Inputs are shared by the two
!! sets (the saturation humidity of the inputs is the same formula); the outputs
!! differ because the CESM-coupled set changes `cp_air` (shcoef), `Lsub` (lhcoef)
!! and `zvir` (virtual temperature and the humidity term of the stability
!! parameter, hence every coefficient and stress through the iteration).  Cases:
!! 10 surface/air scenarios (stable, very stable and clamped, unstable, very
!! unstable and clamped, near neutral on both sides, melting surface with
!! condensation and sublimation, unequal momentum/scalar heights) x 3 winds
!! (below the floor, moderate, strong) x highfreq off/on, plus iteration-control
!! variants (1, 2, 20 passes; an early-exit tolerance).
!!
!! Tolerances: the kernel uses the reproducible `rdb_sm_exp/log/atan`, upstream
!! the system libm.  Measured on gfortran -O2, contraction off: worst relative
!! difference 6.2e-16 (stry, case 29) over all outputs and both sets (strx/stry
!! 2.8e-16..6.2e-16, delq 3.9e-16, lhcoef/shcoef up to 4.7e-16, delt exactly 0):
!! the five-pass iteration does not amplify the few-ulp library difference.
!! CPU builds compare at relative 6e-15 (delt 1e-15).  On the GPU build (FMA
!! contraction on for host code too) the tolerance is scale-aware 1e-12.  `delq`
!! is a difference of near-equal numbers, so it is compared with an ABSOLUTE
!! tolerance scaled to the surface humidity `ssq` (1e-14*ssq CPU, 1e-12*ssq GPU).
