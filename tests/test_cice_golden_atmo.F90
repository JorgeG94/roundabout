   subroutine test_sets_differ(error)
      !! The two tables must differ (`cp_air`, `Lsub`, `zvir`): shcoef and lhcoef everywhere, the stress
      !! wherever the stability correction is active, delt/delq never (they depend on no constant).
      type(error_type), allocatable, intent(out) :: error
      integer :: i, nsh, nlh, nsx

      nsh = 0
      nlh = 0
      nsx = 0
      do i = 1, N
         if (abs(IC_SH(i) - CE_SH(i)) > 1.0e-6_wp*abs(IC_SH(i))) nsh = nsh + 1
         if (abs(IC_LH(i) - CE_LH(i)) > 1.0e-6_wp*abs(IC_LH(i))) nlh = nlh + 1
         if (abs(IC_SX(i) - CE_SX(i)) > 1.0e-6_wp*abs(IC_SX(i))) nsx = nsx + 1
         if (IC_DT(i) /= CE_DT(i) .or. IC_DQ(i) /= CE_DQ(i)) then
            call test_failed(error, "delt/delq must not depend on the constant set")
            return
         end if
      end do
      if (nsh < N/2 .or. nlh < N/2) then
         call test_failed(error, "shcoef/lhcoef tables do not differ between constant sets")
         return
      end if
      if (nsx == 0) call test_failed(error, "stress table identical between constant sets")
   end subroutine test_sets_differ

