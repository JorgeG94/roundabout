!! Law-of-the-wall bottom-boundary-layer diapycnal diffusivity for the ocean core.
module rdb_ocean_bbl_mixing
   !! Tracer diffusivity generated by bottom drag: the mean-flow kinetic
   !! energy the bottom stress removes in the viscous bottom boundary
   !! layer (BBL) is partly spent on mixing the water just above the bed.
   !! A law-of-the-wall profile sets the diffusivity, an energy ledger
   !! limits it, and the result is ADDED to the other interior
   !! diffusivities (tracer diffusivity only: the BBL viscosity is already
   !! carried by `kv_bbl` in the vertical-friction glue).
   !!
   !! Pipeline:
   !!   1. `bbl_mixing_set_tke` (once per outer step, right after the
   !!      per-face viscous BBL is refreshed): per face, the friction
   !!      velocity `u*_f = kv_bbl_f/(sqrt(c_d) bbl_thick_f)` and the
   !!      BBL-mean ALONG-FACE velocity `ubar_f` (thickness-weighted over
   !!      `bbl_thick_f`, signed component).  Per cell: `u*_h` (half the area-weighted
   !!      sum of the four faces' `u*_f^2` over `A_T`), the BBL mean-KE loss
   !!      `P_bbl = sqrt(c_d) Sum_f (A_f/A_T) u*_f ubar_f^2` (all four faces
   !!      summed, no one-half) and `|f|_h`, the mean of `|f|` at the four
   !!      corners.
   !!   2. `bbl_mixing_compute` (thermo cadence): a column sweep up from
   !!      the bed over the interior interfaces.  The available power
   !!      `effic * P_bbl` decays upward, `exp(-h/lambda)` per layer with
   !!      `1/lambda = max(1/max_decay, |f|/u*_h)`; the wall-law diffusivity
   !!      `Kd = kappa u*^2 z (D-z) / (u* D + |f| z (D-z))` (`z` the height
   !!      above the bed, `D` the live column depth) is cut so that
   !!      `Kd dz max(N^2, N^2_min)` never exceeds the power left, and the
   !!      power it uses is removed.  With no stratification to pay for
   !!      (`N^2 = 0` and no rotation floor) the diffusivity fills to the
   !!      cap `kd_max` while any power remains.
   !!   3. `bbl_mixing_merge_into_kt` (every stage): `kt += kd_int` on the
   !!      interior interfaces.
   !!
   !! The wall law is the classical `Kd = kappa u* z` (von Karman 1941;
   !! Prandtl mixing length) closed at the surface by `(1 - z/D)` and capped
   !! by the rotational Ekman-layer scale `u*/|f|` (Zilitinkevich-type
   !! rotation limit of the neutral boundary layer, `L = kappa u*/|f|`; see
   !! also Killworth & Edwards 1999, J. Phys. Oceanogr. 29, for the
   !! rotation-limited BBL thickness the face `bbl_thick` already carries).
   !! The energy ledger follows the turbulent-kinetic-energy budget of a
   !! stratified boundary layer (Osborn 1980, J. Phys. Oceanogr. 10:
   !! mixing efficiency; the buoyancy flux `Kd N^2` is paid out of the
   !! shear production), with the Joule-loss decay of the available power
   !! with height above the bed.  `N^2_min = Omega^2` (`use_omega`) is the
   !! same rotation floor the internal-tide closure uses.
   !!
   !! Interface convention (shared with `rdb_ocean_tidal_mixing`):
   !! `kd_int(:,:,K)` lives at the bottom interface of layer `K`, global
   !! bottom-up (k=1 bed, k=nz surface); `K = kbed` (the bed) and
   !! `K = nz+1` (the free surface) are exactly 0.  The interface
   !! stratification is the SAME layer-centred `N^2` producer as the
   !! tidal kernel (`column_layer_n2`).
   !!
   !! Default off (`enable = .false.`): no state is allocated and the
   !! pipeline is bit-identical.
#ifdef LFORTRAN_PASSING
   use rdb_constants, only: wp, OMEGA_EARTH, H_VANISHED, H_DIV_EPS
#else
   use rdb_constants, only: NZ_STACK_MAX, wp, OMEGA_EARTH, H_VANISHED, H_DIV_EPS
#endif
   use rdb_grid, only: hgrid_t
   use rdb_multilayer_state, only: multilayer_state_t
   use rdb_eos, only: eos_t
   use rdb_ocean_tidal_mixing, only: column_layer_n2
   use, intrinsic :: iso_fortran_env, only: int64
   use rdb_mem_report, only: arr_bytes
   implicit none
   private

#ifdef LFORTRAN_PASSING
   integer, parameter :: NZ_STACK_MAX = 64
      !! LFortran 0.64 workaround: module-local copy of the rdb_constants value.
#endif

   public :: ocean_bbl_mixing_t
   public :: bbl_mixing_set_tke
   public :: bbl_mixing_set_tke_impl
   public :: bbl_mixing_compute
   public :: bbl_mixing_compute_impl
   public :: bbl_column_sweep
   public :: bbl_mixing_merge_into_kt

   integer, parameter :: NZL = NZ_STACK_MAX
      !! Maximum number of layers a single column kernel can solve.

   type :: ocean_bbl_mixing_t
      logical :: is_init = .false.
         !! True between `init` and `destroy`.
      logical :: enable = .false.
         !! Master switch (default off => bit-identical).  Needs the
         !! per-face viscous BBL (`vdiff%bbl_glue .and. bbl_per_face`) and
         !! `c_d > 0`; validated at configure.
      real(wp) :: effic = 0.2_wp
         !! Fraction of the BBL mean-KE loss that becomes mixing power
         !! (BBL_EFFIC).  OM3 value: 0.01.
      real(wp) :: max_decay = 200.0_wp
         !! Upper bound (m) on the upward decay length of the power
         !! (BBL_MIXING_MAX_DECAY).
      logical :: use_omega = .true.
         !! Floor `N^2` at `Omega^2` in the energy bound
         !! (LOTW_BBL_USE_OMEGA).  `.false.`: no floor.
      real(wp) :: von_karman = 0.41_wp
         !! Von Karman constant (VON_KARMAN_BBL).
      real(wp) :: kd_max = 0.1_wp
         !! Cap on the BBL diffusivity (m^2/s), also the unstratified
         !! fill value (KD_MAX).
      real(wp) :: omega2 = OMEGA_EARTH**2
         !! Rotation floor `Omega^2` (s^-2) on `N^2`.
      real(wp) :: c_d = 0.0_wp
         !! Bottom drag coefficient of the per-face BBL (latched at
         !! configure from the bottom-drag configuration).
      type(eos_t) :: eos
         !! Value copy of the run's EOS, set at configure.
      real(wp) :: rho0 = 1035.0_wp
         !! Boussinesq reference density (kg/m^3).

      real(wp), allocatable :: ustar_bbl(:, :)
         !! Cell friction velocity `u*_h` (m/s), (nx,ny).
      real(wp), allocatable :: ke_loss_bbl(:, :)
         !! BBL mean-KE loss `P_bbl` (m^3/s^3), (nx,ny).
      real(wp), allocatable :: f_abs_h(:, :)
         !! `|f|` at the cell centre (mean of the four corners), (1/s).
      real(wp), allocatable :: kd_int(:, :, :)
         !! BBL diffusivity at interfaces (m^2/s), (nx,ny,nz+1).
   contains
      procedure, non_overridable :: init => ocean_bbl_mixing_init
      procedure, non_overridable :: destroy => ocean_bbl_mixing_destroy
      procedure, non_overridable :: enter_data => ocean_bbl_mixing_enter_data
      procedure, non_overridable :: exit_data => ocean_bbl_mixing_exit_data
      procedure, non_overridable :: bytes => ocean_bbl_mixing_bytes
   end type ocean_bbl_mixing_t

contains

   subroutine ocean_bbl_mixing_init(this, nx, ny, nz)
      !! Allocate the persistent fields (zeroed).  Called from configure
      !! only when the closure is enabled.
      class(ocean_bbl_mixing_t), intent(inout) :: this
      integer, intent(in) :: nx, ny, nz
      call this%destroy()
      allocate (this%ustar_bbl(nx, ny), source=0.0_wp)
      allocate (this%ke_loss_bbl(nx, ny), source=0.0_wp)
      allocate (this%f_abs_h(nx, ny), source=0.0_wp)
      allocate (this%kd_int(nx, ny, nz + 1), source=0.0_wp)
      this%is_init = .true.
   end subroutine ocean_bbl_mixing_init

   subroutine ocean_bbl_mixing_destroy(this)
      class(ocean_bbl_mixing_t), intent(inout) :: this
      this%is_init = .false.
      if (allocated(this%ustar_bbl)) deallocate (this%ustar_bbl)
      if (allocated(this%ke_loss_bbl)) deallocate (this%ke_loss_bbl)
      if (allocated(this%f_abs_h)) deallocate (this%f_abs_h)
      if (allocated(this%kd_int)) deallocate (this%kd_int)
   end subroutine ocean_bbl_mixing_destroy

   subroutine ocean_bbl_mixing_enter_data(this)
      class(ocean_bbl_mixing_t), intent(inout) :: this
      if (allocated(this%ustar_bbl)) then
         !$acc enter data copyin(this%ustar_bbl)
      end if
      if (allocated(this%ke_loss_bbl)) then
         !$acc enter data copyin(this%ke_loss_bbl)
      end if
      if (allocated(this%f_abs_h)) then
         !$acc enter data copyin(this%f_abs_h)
      end if
      if (allocated(this%kd_int)) then
         !$acc enter data copyin(this%kd_int)
      end if
   end subroutine ocean_bbl_mixing_enter_data

   subroutine ocean_bbl_mixing_exit_data(this)
      class(ocean_bbl_mixing_t), intent(inout) :: this
      if (allocated(this%kd_int)) then
         !$acc exit data delete(this%kd_int)
      end if
      if (allocated(this%f_abs_h)) then
         !$acc exit data delete(this%f_abs_h)
      end if
      if (allocated(this%ke_loss_bbl)) then
         !$acc exit data delete(this%ke_loss_bbl)
      end if
      if (allocated(this%ustar_bbl)) then
         !$acc exit data delete(this%ustar_bbl)
      end if
   end subroutine ocean_bbl_mixing_exit_data

   pure function ocean_bbl_mixing_bytes(this) result(nbytes)
      !! Counted allocatable footprint (0 when unallocated).  Add a term
      !! when a new allocatable joins the type.
      class(ocean_bbl_mixing_t), intent(in) :: this
      integer(int64) :: nbytes
      nbytes = arr_bytes(this%ustar_bbl) &
               + arr_bytes(this%ke_loss_bbl) &
               + arr_bytes(this%f_abs_h) &
               + arr_bytes(this%kd_int)
   end function ocean_bbl_mixing_bytes

   ! =================================================================
   ! Step 1: face -> cell friction velocity and KE loss
   ! =================================================================

   pure subroutine bbl_mixing_set_tke(grid, this, ms, kv_bbl_u, kv_bbl_v, &
                                      bbl_thick_u, bbl_thick_v, f_corner, &
                                      area_t, area_cu, area_cv)
      !! Outer shim for `bbl_mixing_set_tke_impl` (see there): forwards the
      !! multilayer state and the per-face BBL fields.  No-op unless
      !! enabled.  Call once per outer step right after
      !! `vdiff_set_viscous_bbl`.
      type(hgrid_t), intent(in) :: grid
      type(ocean_bbl_mixing_t), intent(inout) :: this
      type(multilayer_state_t), intent(in) :: ms
      real(wp), intent(in) :: kv_bbl_u(grid%nx_total + 1, grid%ny_total)
      real(wp), intent(in) :: kv_bbl_v(grid%nx_total, grid%ny_total + 1)
      real(wp), intent(in) :: bbl_thick_u(grid%nx_total + 1, grid%ny_total)
      real(wp), intent(in) :: bbl_thick_v(grid%nx_total, grid%ny_total + 1)
      real(wp), intent(in) :: f_corner(grid%nx_total + 1, grid%ny_total + 1)
      real(wp), intent(in) :: area_t(grid%nx_total, grid%ny_total)
      real(wp), intent(in) :: area_cu(grid%nx_total + 1, grid%ny_total)
      real(wp), intent(in) :: area_cv(grid%nx_total, grid%ny_total + 1)

      if (.not. this%enable) return
      call bbl_mixing_set_tke_impl(grid%nx_total, grid%ny_total, ms%nz_ml, this%c_d, &
                                   ms%u_face_x_layer, ms%v_face_y_layer, ms%h_layer, &
                                   ms%wet_mask, kv_bbl_u, kv_bbl_v, bbl_thick_u, &
                                   bbl_thick_v, f_corner, area_t, area_cu, area_cv, &
                                   this%ustar_bbl, this%ke_loss_bbl, this%f_abs_h)
   end subroutine bbl_mixing_set_tke

   pure subroutine bbl_mixing_set_tke_impl(nx, ny, nz, c_d, u_x, v_y, h, wet, &
                                           kv_u, kv_v, th_u, th_v, f_corner, &
                                           area_t, area_cu, area_cv, &
                                           ustar_h, ke_loss, f_abs)
      !! Per-cell BBL friction velocity, KE loss and `|f|`.
      !!
      !! Face `u*_f = kv_bbl_f/(sqrt(c_d) bbl_thick_f)` (zero on a dry face
      !! or a zero-thickness BBL).  `ubar_f` is the thickness-weighted
      !! mean over the bottom `bbl_thick_f` of the SIGNED along-face
      !! velocity (face layer thickness = mean of the two cells; the last
      !! layer partial; normalised by the thickness actually found when the
      !! column is shallower than the BBL).
      !!
      !! Cell values: `u*_h^2 = (1/2)(1/A_T) Sum_f A_f u*_f^2` over all
      !! four faces (each `u*_f` already carries its own face's cross
      !! component and background speed, so uniform flow gives `u*_h =
      !! sqrt(2) u*_f`); `P_bbl = sqrt(c_d) Sum_f
      !! (A_f/A_T) u*_f ubar_f^2` over all four faces, no one-half; `|f|`
      !! is the mean of `|f|` at the four corners.  Dry cells get 0.
      integer, intent(in) :: nx, ny, nz
      real(wp), intent(in) :: c_d
      real(wp), intent(in) :: u_x(nx + 1, ny, nz)
      real(wp), intent(in) :: v_y(nx, ny + 1, nz)
      real(wp), intent(in) :: h(nx, ny, nz)
      real(wp), intent(in) :: wet(nx, ny)
      real(wp), intent(in) :: kv_u(nx + 1, ny)
      real(wp), intent(in) :: kv_v(nx, ny + 1)
      real(wp), intent(in) :: th_u(nx + 1, ny)
      real(wp), intent(in) :: th_v(nx, ny + 1)
      real(wp), intent(in) :: f_corner(nx + 1, ny + 1)
      real(wp), intent(in) :: area_t(nx, ny)
      real(wp), intent(in) :: area_cu(nx + 1, ny)
      real(wp), intent(in) :: area_cv(nx, ny + 1)
      real(wp), intent(inout) :: ustar_h(nx, ny)
      real(wp), intent(inout) :: ke_loss(nx, ny)
      real(wp), intent(inout) :: f_abs(nx, ny)

      integer :: i, j, k, iface
      real(wp) :: us(4), ub(4), aw(4)
      real(wp) :: sqcd, p_sum
      real(wp) :: acc, hv, wgt, usum, tb
      integer :: fi, fj, il, ir, jl, jr

      sqcd = sqrt(c_d)
      do concurrent(j=1:ny, i=1:nx) &
         local(k, iface, us, ub, aw, p_sum, &
               acc, hv, wgt, usum, tb, fi, fj, il, ir, jl, jr)
         ustar_h(i, j) = 0.0_wp
         ke_loss(i, j) = 0.0_wp
         f_abs(i, j) = 0.25_wp*(abs(f_corner(i, j)) + abs(f_corner(i + 1, j)) + &
                                abs(f_corner(i, j + 1)) + abs(f_corner(i + 1, j + 1)))
         if (wet(i, j) > 0.0_wp .and. sqcd > 0.0_wp) then
            ! Faces 1,2 = west/east u-faces; 3,4 = south/north v-faces.
            do iface = 1, 4
               us(iface) = 0.0_wp
               ub(iface) = 0.0_wp
               if (iface <= 2) then
                  fi = i + iface - 1
                  fj = j
                  il = max(1, fi - 1)
                  ir = min(nx, fi)
                  jl = j
                  jr = j
                  aw(iface) = area_cu(fi, fj)
                  tb = th_u(fi, fj)
                  if (kv_u(fi, fj) > 0.0_wp .and. tb > 0.0_wp) us(iface) = kv_u(fi, fj)/(sqcd*tb)
               else
                  fi = i
                  fj = j + iface - 3
                  il = i
                  ir = i
                  jl = max(1, fj - 1)
                  jr = min(ny, fj)
                  aw(iface) = area_cv(fi, fj)
                  tb = th_v(fi, fj)
                  if (kv_v(fi, fj) > 0.0_wp .and. tb > 0.0_wp) us(iface) = kv_v(fi, fj)/(sqcd*tb)
               end if
               if (us(iface) > 0.0_wp) then
                  acc = 0.0_wp
                  usum = 0.0_wp
                  do k = 1, nz
                     if (acc >= tb) exit
                     hv = 0.5_wp*(h(il, jl, k) + h(ir, jr, k))
                     wgt = min(max(hv, 0.0_wp), tb - acc)
                     if (iface <= 2) then
                        usum = usum + wgt*u_x(fi, fj, k)
                     else
                        usum = usum + wgt*v_y(fi, fj, k)
                     end if
                     acc = acc + wgt
                  end do
                  if (acc > 0.0_wp) ub(iface) = usum/acc
               end if
            end do

            p_sum = 0.0_wp
            if (area_t(i, j) > 0.0_wp) then
               do iface = 1, 4
                  p_sum = p_sum + aw(iface)*us(iface)**2
               end do
               ustar_h(i, j) = sqrt(0.5_wp*p_sum/area_t(i, j))
            end if

            p_sum = 0.0_wp
            if (area_t(i, j) > 0.0_wp) then
               do iface = 1, 4
                  p_sum = p_sum + aw(iface)*us(iface)*ub(iface)**2
               end do
               ke_loss(i, j) = sqcd*p_sum/area_t(i, j)
            end if
         end if
      end do
   end subroutine bbl_mixing_set_tke_impl

   ! =================================================================
   ! Step 2: column sweep
   ! =================================================================

   pure subroutine bbl_column_sweep(nz, kbed, h, n2, ustar, f_abs, tke_col, &
                                    max_decay, use_omega, omega2, von_karman, &
                                    kd_max, kd)
      !! One column's law-of-the-wall BBL diffusivity with the decaying
      !! energy ledger (see the module header).  Bottom-up: `h(k)` the
      !! layer thicknesses, `n2(k)` the stratification at the TOP
      !! interface of layer `k` (interface `k+1`), `kd(K)` the output at
      !! interface `K` (zero at `K <= kbed` and `K = nz+1`).
      !! `tke_col` is the power offered at the bed (m^3/s^3).  `D - z` is
      !! evaluated as the live column depth minus the height of the
      !! interface above the bed (equal to the distance down from the
      !! surface up to round-off).  `kd_max` enters only the unstratified
      !! branch; the stratified branch is the wall law scaled by
      !! `used/need`.
      !$acc routine seq
      integer, intent(in) :: nz, kbed
      real(wp), intent(in) :: h(nz), n2(nz)
      real(wp), intent(in) :: ustar, f_abs, tke_col, max_decay, omega2
      real(wp), intent(in) :: von_karman, kd_max
      logical, intent(in) :: use_omega
      real(wp), intent(out) :: kd(nz + 1)

      integer :: k
      real(wp) :: dtot, lam_inv, n2_min, rem, z, zt, den, kw, dzk, need, used, n2e

      do k = 1, nz + 1
         kd(k) = 0.0_wp
      end do
      if (.not. (ustar > 0.0_wp) .or. kbed < 1 .or. kbed >= nz) return

      dtot = H_DIV_EPS
      do k = kbed, nz
         dtot = dtot + h(k)
      end do
      lam_inv = max(1.0_wp/max_decay, f_abs/ustar)
      n2_min = 0.0_wp
      if (use_omega) n2_min = omega2
      rem = max(tke_col, 0.0_wp)
      z = 0.0_wp
      do k = kbed, nz - 1
         ! Joule loss across layer k, then serve its top interface K = k+1.
         z = z + h(k)
         rem = rem*exp(-h(k)*lam_inv)
         zt = dtot - z
         den = ustar*dtot + f_abs*z*zt
         kw = 0.0_wp
         if (den > 0.0_wp) kw = von_karman*ustar*ustar*z*zt/den
         dzk = 0.5_wp*(h(k) + h(k + 1))
         n2e = max(n2(k), n2_min)
         need = kw*dzk*n2e
         used = 0.0_wp
         if (need > 0.0_wp) then
            used = min(need, rem)
            kw = kw*used/need
         else if (n2e <= 0.0_wp) then
            ! Nothing to pay for: fill to the cap while power remains.
            kw = 0.0_wp
            if (rem > 0.0_wp) kw = kd_max
         else
            kw = 0.0_wp
         end if
         rem = max(rem - used, 0.0_wp)
         kd(k + 1) = kw
      end do
   end subroutine bbl_column_sweep

   pure subroutine bbl_mixing_compute(grid, this, ms)
      !! Fill `this%kd_int`.  Call at thermo cadence.  Outer shim:
      !! dereferences the tracer-registry hTr arrays on the host (the
      !! array-of-DT indirection blocks NVHPC device codegen).
      type(hgrid_t), intent(in) :: grid
      type(ocean_bbl_mixing_t), intent(inout) :: this
      type(multilayer_state_t), intent(in) :: ms

      if (.not. this%enable) return
      if (ms%idx_temperature <= 0 .or. ms%idx_salinity <= 0) return
      call bbl_mixing_compute_impl(grid%nx_total, grid%ny_total, ms%nz_ml, ms%h_layer, &
                                   ms%tracers(ms%idx_temperature)%hTr, &
                                   ms%tracers(ms%idx_salinity)%hTr, ms%wet_mask, &
                                   ms%k_bot, this%eos, this%rho0, this%ustar_bbl, &
                                   this%ke_loss_bbl, this%f_abs_h, this%effic, &
                                   this%max_decay, this%use_omega, this%omega2, &
                                   this%von_karman, this%kd_max, this%kd_int)
   end subroutine bbl_mixing_compute

   pure subroutine bbl_mixing_compute_impl(nx, ny, nz, h, htr_t, htr_s, wet, k_bot, &
                                           eos, rho0, ustar_h, ke_loss, f_abs, &
                                           effic, max_decay, use_omega, omega2, &
                                           von_karman, kd_max, kd_int)
      !! Column kernel: gather, interface `N^2` (shared producer
      !! `column_layer_n2`), sweep.  One `do concurrent (j, i)`; the
      !! per-column scratch lives in `local()` stack arrays
      !! (`NZ_STACK_MAX >= nz`).
      integer, intent(in) :: nx, ny, nz
      real(wp), intent(in) :: h(nx, ny, nz), htr_t(nx, ny, nz), htr_s(nx, ny, nz)
      real(wp), intent(in) :: wet(nx, ny)
      integer, intent(in) :: k_bot(nx, ny)
      type(eos_t), intent(in) :: eos
      real(wp), intent(in) :: rho0
      real(wp), intent(in) :: ustar_h(nx, ny), ke_loss(nx, ny), f_abs(nx, ny)
      real(wp), intent(in) :: effic, max_decay, omega2, von_karman, kd_max
      logical, intent(in) :: use_omega
      real(wp), intent(inout) :: kd_int(nx, ny, nz + 1)

      integer :: i, j, k
      real(wp) :: h_col(NZL), hl_col(NZL), t_col(NZL), s_col(NZL), n2_col(NZL)
      real(wp) :: kd_col(NZL + 1)
      real(wp) :: denom

      do concurrent(j=1:ny, i=1:nx) &
         local(k, h_col, hl_col, t_col, s_col, n2_col, kd_col, denom)
         do k = 1, nz + 1
            kd_int(i, j, k) = 0.0_wp
         end do
         if (wet(i, j) > 0.0_wp .and. ustar_h(i, j) > 0.0_wp) then
            do k = 1, nz
               h_col(k) = max(h(i, j, k), H_VANISHED)
               hl_col(k) = max(h(i, j, k), 0.0_wp)
               denom = 1.0_wp/max(h(i, j, k), H_DIV_EPS)
               t_col(k) = htr_t(i, j, k)*denom
               s_col(k) = htr_s(i, j, k)*denom
            end do
            call column_layer_n2(eos, rho0, nz, h_col, t_col, s_col, n2_col)
            call bbl_column_sweep(nz, k_bot(i, j), hl_col, n2_col, ustar_h(i, j), &
                                  f_abs(i, j), effic*ke_loss(i, j), max_decay, &
                                  use_omega, omega2, von_karman, kd_max, kd_col)
            do k = 1, nz + 1
               kd_int(i, j, k) = kd_col(k)
            end do
         end if
      end do
   end subroutine bbl_mixing_compute_impl

   ! =================================================================
   ! Step 3: merge
   ! =================================================================

   pure subroutine bbl_mixing_merge_into_kt(this, nx, ny, nzp1, kt)
      !! Fold the BBL diffusivity into the vmix tracer diffusivity,
      !! ADDITIVELY and on the TRACER diffusivity only (the BBL viscosity
      !! is `kv_bbl` in the friction glue).  Called every stage; interior
      !! interfaces K=2..nzp1-1 only.
      type(ocean_bbl_mixing_t), intent(in) :: this
      integer, intent(in) :: nx, ny, nzp1
         !! Interface-field extents (explicit shape: assumed-shape dummies
         !! in a `do concurrent` kernel make NVHPC walk the descriptor).
      real(wp), intent(inout) :: kt(nx, ny, nzp1)
         !! Tracer diffusivity at interfaces; gets `kd_int`.

      integer :: i, j, k

      do concurrent(k=2:nzp1 - 1, j=1:ny, i=1:nx)
         kt(i, j, k) = kt(i, j, k) + this%kd_int(i, j, k)
      end do
   end subroutine bbl_mixing_merge_into_kt

end module rdb_ocean_bbl_mixing
